#!/usr/bin/env python3
"""What the native-`.c` census asserts, and what would let a false one through.

The subject is `windows/tools/census_native_c.py` and the artefact is
`windows/ghidra/c-census.csv`. The suite exists because of what the census is
for: `GamingCenter3_Cross.c` is 56 MB and 64,588 declared functions, it is in no
index and no listing, and the manifest's row for its program is `0,0,0,0,0`.
A census that quietly covered less would leave exactly that contradiction in
place while reporting clean, which is the failure this repository keeps meeting
from the other direction. So the interesting cases here are the refusals and the
refusals-of-refusals, and the known-good measurement comes FIRST -- a guard
exercised only on bad input cannot tell "clean" from "never ran".

**No figure of the tree is asserted here.** The committed row is checked against
the file it is derived from, never against a number typed into this file. The
counts move when a legitimate re-export lands, and a test holding one of them
would go red on exactly the change that is supposed to be reviewable -- the
§14a/census lesson `census_test_line_pins.py` and
`tools/test_readme_suite_table.py` both carry. What is asserted is the claim:
the committed CSV re-derives from the committed `.c`, in both directions, and
each `c-digests.csv` row names a committed `.c` rather than there being six of
them.

**Read once, not "fast enough".** There is no wall-clock bound anywhere in this
file. §14a's regression was 5.4 s at 26x the work and passed the bound that
would have caught the 0.18 s version, so the property is pinned structurally
instead: the per-file read is counted by replacing the reader, and the marker
container is read back and asserted to be a dict keyed on address, which is
what makes each later lookup a lookup rather than a scan of every function the
file declares.
"""
import contextlib
import csv
import io
import os
from pathlib import Path
import shutil
import sys
import tempfile
import unittest

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent

sys.path.insert(0, str(HERE))
import census_native_c as census  # noqa: E402
import decompile_native  # noqa: E402

CENSUS = census.C_CENSUS
RETAINED_LABEL = "GamingCenter3_Cross"

# The run list the exporter writes into every `// Source:` line: five targets
# and their five digests, identical across the five exports that are in the
# committed project. The retained export's line is this plus a sixth pair, and
# that difference is the whole of the attribution -- so a fixture reproducing it
# has to reproduce the shared part too, or it is testing a different tree.
RUN_SOURCES = [
    "vendor/control-center-3.9.18.0/ACPIDriver/ACPIDriver.sys",
    "vendor/control-center-3.9.18.0/ACPIDriverDll.dll",
    "extract:vendor/control-center-3.9.18.0/GamingCenter3_Cross.UWP_3.9.18.0_x64.msixbundle"
    "#v3.9.18.0/msix/clrcompression.dll",
    "extract:vendor/control-center-3.9.18.0/setup.exe#v3.9.18.0/inno/app/"
    "UniwillService/MyControlCenter/UEFI_Firmware.dll",
    "extract:vendor/control-center-3.9.18.0/GamingCenter3_Cross.UWP_3.9.18.0_x64.msixbundle"
    "#v3.9.18.0/msix/GamingCenter3_Cross.exe",
]
RUN_DIGESTS = [c * 64 for c in "12345"]
RETAINED_SOURCE = ("extract:vendor/control-center-3.9.18.0/GamingCenter3_Cross"
                   ".UWP_3.9.18.0_x64.msixbundle#v3.9.18.0/msix/GamingCenter3_Cross.dll")
RETAINED_DIGEST = "6" * 64


def header(label, sources=None, digests=None):
    sources = RUN_SOURCES if sources is None else sources
    digests = RUN_DIGESTS if digests is None else digests
    return ("// %s: Ghidra 12.1.3 decompile\n"
            "// Generated by windows/tools/decompile_native.py -- do not edit;\n"
            "// improve this by editing the annotations and re-running the "
            "generator.\n"
            "// Source: %s, SHA-256 %s\n"
            "// Machine output carrying this repository's symbols. Not the "
            "vendor's source.\n\n"
            % (label, ",".join(sources), ",".join(digests)))


def export(label, addrs, sources=None, digests=None, names=None):
    """A minimal but structurally real per-program export: header, then one
    `// ==== <name> @ <addr>` separator and body per address.

    `names` overrides the declared function name per position, which is how the
    duplicate-address case gets two *different* names at one address -- the
    shape `_c_markers()`'s set-of-names exists to keep visible.
    """
    body = [header(label, sources, digests)]
    for i, addr in enumerate(addrs):
        name = names[i] if names else "FUN_%s" % addr
        body.append("// ==== %s @ %s\n\nvoid %s(void)\n\n{\n}\n\n"
                    % (name, addr, name))
    return "".join(body)


def write_export(directory, label, addrs, **kwargs):
    path = os.path.join(directory, label + ".c")
    with open(path, "w") as f:
        f.write(export(label, addrs, **kwargs))
    return path


MANIFEST_HEADER = decompile_native.MANIFEST_HEADER


def write_manifest(path, rows):
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=MANIFEST_HEADER, lineterminator="\n",
                           extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)


def manifest_row(program, functions, mode="rebuild-project", sha256="",
                 source="", notes=""):
    row = {h: "" for h in MANIFEST_HEADER}
    row.update({"program": program, "source": source or "(not imported)",
                "sha256": sha256, "pdb_staged": "no",
                "loader": "Portable Executable (PE)", "ghidra_version": "12.1.3",
                "functions": str(functions),
                "decompiled": str(functions), "failed": "0",
                "instruction_bytes": "0", "body_bytes": "0", "mode": mode,
                "notes": notes})
    return row


class MeasurementTests(unittest.TestCase):
    """What the tool measures, on files small enough to read in the assertion.

    The known-good case is first on purpose, and it is a real three-function
    export rather than a count: a suite that only ever fed the tool refusals
    cannot tell a working parser from a parser that refuses everything.
    """

    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)

    def _write(self, name, text):
        path = os.path.join(self.tmp, name)
        with open(path, "w") as f:
            f.write(text)
        return path

    def test_three_separators_measure_three_over_the_right_range(self):
        path = self._write("Good.c", export("Good", ["0001", "0002", "0010"]))
        self.assertEqual(census.measure_export(path), (3, "0001", "0010"))

    def test_the_range_is_ordered_as_an_integer_not_as_hex_text(self):
        # 0x9 sorts after 0x10 as a string and before it as a number, and every
        # address in a real image is the same width -- so string order is right
        # by luck. This is the file where the luck runs out.
        path = self._write("Wide.c", export("Wide", ["0009", "0010", "0100"]))
        self.assertEqual(census.measure_export(path), (3, "0009", "0100"))

    def test_one_address_under_two_names_counts_two_separators(self):
        # The set-of-names shape `_c_markers()` exists to hold. A duplicate
        # address declared twice is two separator lines, so the figure a reader
        # re-derives with `grep -c` is 2 -- and collapsing it to 1 would make
        # the census disagree with the command quoted beside it while every
        # count in the tree still looked consistent.
        path = self._write("Dup.c", export("Dup", ["0001", "0001"],
                                          names=["FUN_0001", "ALIAS_0001"]))
        self.assertEqual(census.measure_export(path), (2, "0001", "0001"))
        self.assertEqual(sorted(decompile_native._c_markers(path)["0001"]),
                         ["ALIAS_0001", "FUN_0001"])

    def test_a_file_with_no_separator_is_refused(self):
        # Not zero. A file this tool cannot read a function out of has no
        # figure, and reporting 0 is how "the census covered less" comes to
        # read as "the census is clean".
        path = self._write("Bare.c", "// a file the exporter never wrote\n")
        self.assertIsNone(census.measure_export(path))

    def test_an_empty_file_is_refused(self):
        self.assertIsNone(census.measure_export(self._write("Empty.c", "")))

    def test_an_absent_file_is_refused(self):
        self.assertIsNone(census.measure_export(os.path.join(self.tmp, "No.c")))

    def test_the_marker_container_is_a_dict_keyed_on_address(self):
        # Structural, not temporal. The per-file container is what turns each
        # later lookup into a dict read rather than a scan of every declared
        # function, and §14a's 5.4 s regression was exactly that scan.
        path = self._write("Keyed.c", export("Keyed", ["0001", "0002"]))
        markers = decompile_native._c_markers(path)
        self.assertIsInstance(markers, dict)
        self.assertEqual(sorted(markers), ["0001", "0002"])
        self.assertTrue(all(isinstance(v, set) for v in markers.values()))

    def test_each_file_is_read_once_no_matter_how_many_functions_it_declares(self):
        # The read-once guard, counted rather than timed. 2,000 declarations in
        # one file is the shape of the 10,141-row case the guard exists for;
        # a per-row read would look identical in the output and cost 100 GB.
        path = self._write("Big.c", export("Big", ["%04x" % i for i in range(2000)]))
        calls = []
        real = census._c_markers

        def counting(p):
            calls.append(p)
            return real(p)

        census._c_markers = counting
        self.addCleanup(setattr, census, "_c_markers", real)
        for _ in range(2000):
            census.measure_export(path)
        self.assertEqual(len(calls), 2000)

    def test_the_provenance_header_is_read_from_a_prefix_not_a_second_pass(self):
        # The header is the only other thing this tool needs from a 56 MB file,
        # and it lives in the first six lines. Reading it whole is a second full
        # pass; a prefix is not. Asserted on the constant because the cost is
        # invisible in every other output this tool produces.
        self.assertLess(census._HEADER_PREFIX, 1 << 16)


class AttributionTests(unittest.TestCase):
    """Which binary an export belongs to, and the refusal when it cannot be.

    The refusal half is the one that matters. A confident wrong provenance for
    `GamingCenter3_Cross.c` would attribute 64,588 functions to whichever of the
    two same-stem binaries the tool happened to reach for, and nothing
    downstream would look wrong.
    """

    def test_the_header_pairs_each_path_with_its_digest_positionally(self):
        pairs = census.read_header_pairs(
            self._fixture(sources=["a.sys", "b.dll"], digests=["a" * 64, "b" * 64]))
        self.assertEqual(pairs, [("a.sys", "a" * 64), ("b.dll", "b" * 64)])

    def test_an_extract_prefix_and_a_fragment_both_yield_the_member_name(self):
        # `extract:<archive>#<member>`: neither the colon nor the hash is a path
        # separator, so a plain basename stops at the archive for one shape and
        # at the fragment for the other. Turning the hash into a separator is
        # what makes the member path come out whole.
        for source, want in (
                ("extract:a/bundle.msix#v1/msix/Thing.dll", "Thing.dll"),
                ("vendor/x/Thing.dll", "Thing.dll"),
                ("extract:a/bundle.msix#v1/msix/deep/Thing.dll", "Thing.dll")):
            self.assertEqual(census.binary_of_source(source), want, source)

    def test_a_source_that_ends_at_the_fragment_resolves_to_no_binary(self):
        # A `source:` with no member path is a shape this tree does not contain.
        # What matters is the direction it fails: the fragment parses as a file
        # name, no target is called that, and the row is refused rather than
        # attributed to a binary that does not exist.
        self.assertEqual(census.binary_of_source("extract:a/bundle.msix#v1"), "v1")
        self.assertIsNone(census.resolve_binary(
            "v1", [{"binary": "vendor/a/bundle.msix"}]))

    def test_the_extra_hash_attributes_to_exactly_one_binary(self):
        pairs = census.read_header_pairs(self._fixture(
            sources=RUN_SOURCES + [RETAINED_SOURCE],
            digests=RUN_DIGESTS + [RETAINED_DIGEST]))
        self.assertEqual(census.header_attribution(pairs, "GamingCenter3_Cross.dll"),
                         (RETAINED_SOURCE, RETAINED_DIGEST))
        # ...and the shared five are attributable too, which is what makes this
        # a pairing rather than a search for the one interesting entry.
        self.assertEqual(census.header_attribution(pairs, "ACPIDriverDll.dll"),
                         (RUN_SOURCES[1], RUN_DIGESTS[1]))

    def test_an_extra_hash_naming_nothing_is_refused_not_guessed(self):
        pairs = census.read_header_pairs(self._fixture(
            sources=RUN_SOURCES, digests=RUN_DIGESTS))
        self.assertIsNone(census.header_attribution(pairs, "GamingCenter3_Cross.dll"))

    def test_a_header_naming_one_binary_twice_is_refused(self):
        # Two hits are as unusable as zero, and picking the first would be a
        # confident answer derived from an ambiguity.
        pairs = [("a/Thing.dll", "1" * 64), ("b/Thing.dll", "2" * 64)]
        self.assertIsNone(census.header_attribution(pairs, "Thing.dll"))

    def test_a_path_and_digest_list_of_different_lengths_is_refused(self):
        # The pairing is positional, so a skewed line would attach a digest to
        # the wrong input with nothing looking wrong.
        self.assertIsNone(census.read_header_pairs(self._fixture(
            sources=["a.sys", "b.dll"], digests=["a" * 64])))
        self.assertIsNone(census.read_header_pairs(self._fixture(
            sources=["a.sys"], digests=[])))
        # A blank cell counts as absent: a digest column that reads as a hash
        # and is not one is worse than no digest column.
        self.assertIsNone(census.read_header_pairs(self._fixture(
            sources=["a.sys", "b.dll"], digests=["a" * 64, ""])))

    def test_a_file_with_no_provenance_line_is_refused(self):
        self.assertIsNone(census.read_header_pairs(self._fixture(text="// no\n")))

    def test_an_unreadable_file_yields_no_header_rather_than_an_exception(self):
        self.assertIsNone(census.read_header_pairs(
            os.path.join(tempfile.gettempdir(), "no-such-census-header.c")))

    def test_the_retained_label_names_the_dll_and_the_launcher_names_the_exe(self):
        # The two same-stem binaries exist to make this ambiguous and it is not:
        # `export_label()` maps each to a distinct label, so exactly one target
        # matches each. A label matching two would be the EXPORT LABEL COLLISION
        # the exporter already refuses.
        targets = decompile_native.load_targets()
        self.assertEqual(census.resolve_binary(RETAINED_LABEL, targets),
                         "GamingCenter3_Cross.dll")
        self.assertEqual(census.resolve_binary("GC3_launcher", targets),
                         "GamingCenter3_Cross.exe")

    def test_a_label_matching_no_target_is_refused(self):
        self.assertIsNone(census.resolve_binary(
            "NotAProgram", decompile_native.load_targets()))

    def test_a_label_matching_two_targets_is_refused(self):
        targets = [{"binary": "vendor/a/Thing.sys"}, {"binary": "vendor/b/Thing.sys"}]
        self.assertIsNone(census.resolve_binary("Thing", targets))

    def _fixture(self, sources=None, digests=None, text=None):
        tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, tmp, ignore_errors=True)
        path = os.path.join(tmp, "Fixture.c")
        with open(path, "w") as f:
            f.write(text if text is not None
                    else header("Fixture", sources, digests))
        return path


class RangeGroundTests(unittest.TestCase):
    """The range ground's limit, made executable.

    The committed tree does contain overlapping exports -- four of its six share
    image base `0x180000000` -- so
    `test_the_committed_tree_reports_the_retained_export_as_the_disjoint_one`
    can assert the real behaviour against the real tree. The fixtures here are
    the pair that tells the two behaviours apart without depending on which
    exports happen to be committed, so a future seventh binary at either image
    base does not decide whether this class still means anything.
    """

    def test_two_exports_at_one_image_base_do_not_attribute_to_each_other(self):
        # ACPIDriverDll.dll, UEFI_Firmware.dll and clrcompression.dll are all
        # PE32+ at 0x180000000 in the real tree and their ranges overlap, so a
        # range is not an attribution mechanism in this repository.
        measured = {"a": (5, "180001000", "1800010C0"),
                    "b": (7, "180001000", "1800010C0"),
                    "c": (3, "180001040", "180001080")}
        self.assertEqual(census.disjoint_exports(measured), set())

    def test_a_range_disjoint_from_every_other_is_reported_as_such(self):
        measured = {"a": (5, "180001000", "1800010C0"),
                    "b": (7, "180001000", "1800010C0"),
                    "c": (3, "180DE2000", "1818D1B40")}
        self.assertEqual(census.disjoint_exports(measured), {"c"})

    def test_touching_ranges_overlap(self):
        # Half-open would be a defensible reading; inclusive is what the printed
        # first/last columns are, and an endpoint shared between two exports is
        # exactly the ambiguity the refusal exists for.
        measured = {"a": (1, "0000", "0100"), "b": (1, "0100", "0200")}
        self.assertEqual(census.disjoint_exports(measured), set())

    def test_an_unmeasured_export_is_not_claimed_as_disjoint(self):
        measured = {"a": (1, "0000", "0100"), "b": (0, None, None)}
        self.assertEqual(census.disjoint_exports(measured), {"a"})

    def test_the_committed_tree_reports_the_retained_export_as_the_disjoint_one(self):
        # The claim the write-up makes, asserted as a claim and not as a census
        # of the tree: the retained export's range is disjoint from every
        # other's, and the exports sharing image base 0x180000000 are not
        # resolvable by range. A seventh binary can add a name to either set
        # without making this false, which is the difference between asserting
        # the claim and asserting the tree.
        rows, refusals = census.build_rows()
        self.assertEqual(refusals, [])
        disjoint = census.disjoint_exports(
            {r["export_label"]: (int(r["separators_declared"]),
                                 r["first_addr"], r["last_addr"])
             for r in rows})
        self.assertIn(RETAINED_LABEL, disjoint)
        for label in ("GC3_launcher", "ACPIDriverDll", "UEFI_Firmware",
                      "clrcompression"):
            self.assertNotIn(label, disjoint,
                             f'{label} is one of the PE32+ exports at a shared '
                             f'image base, so its range resolves nothing and '
                             f'claiming otherwise would be presenting ranges as '
                             f'an attribution mechanism in this tree')


class BuildAndRefuseTests(unittest.TestCase):
    """`build_rows` over whole trees: what it attributes, what it refuses."""

    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)

    def _tree(self, exports, manifest_rows):
        decompiled = os.path.join(self.tmp, "native")
        os.makedirs(decompiled, exist_ok=True)
        for name, addrs, kwargs in exports:
            write_export(decompiled, name, addrs, **kwargs)
        manifest = os.path.join(self.tmp, "manifest.csv")
        write_manifest(manifest, manifest_rows)
        return decompiled, manifest

    def test_an_in_project_row_is_measured_and_carries_the_manifest_figures(self):
        decompiled, manifest = self._tree(
            [("ACPIDriver", ["140001000", "140008060"], {})],
            [manifest_row("ACPIDriver.sys", 2, sha256="9" * 64,
                          source="vendor/control-center-3.9.18.0/ACPIDriver/ACPIDriver.sys")])
        rows, refusals = census.build_rows(decompiled, manifest)
        self.assertEqual(refusals, [])
        self.assertEqual(len(rows), 1)
        self.assertEqual(rows[0]["in_project"], "yes")
        self.assertEqual(rows[0]["count_basis"], "measured")
        self.assertEqual(rows[0]["project_functions"], "2")
        self.assertEqual(rows[0]["separators_declared"], "2")

    def test_a_row_whose_manifest_total_disagrees_with_the_file_is_refused(self):
        # In-project, so the manifest's total and the file's separators are the
        # same quantity, and a disagreement means the row is not a measurement
        # of a whole-program export. Refused rather than written: a `measured`
        # label over two disagreeing columns would launder the disagreement into
        # a fact, and `count_basis` exists to stop exactly that.
        decompiled, manifest = self._tree(
            [("ACPIDriver", ["140001000", "140008060"], {})],
            [manifest_row("ACPIDriver.sys", 7, sha256="9" * 64,
                          source="vendor/control-center-3.9.18.0/ACPIDriver/ACPIDriver.sys")])
        rows, refusals = census.build_rows(decompiled, manifest)
        self.assertEqual(rows, [])
        self.assertEqual(len(refusals), 1)
        self.assertIn("7 function(s)", refusals[0])
        self.assertIn("2 separator(s)", refusals[0])

    def test_a_not_in_project_row_is_measured_and_the_manifests_zeros_travel_with_it(self):
        decompiled, manifest = self._tree(
            [(RETAINED_LABEL, ["180DE2000", "1818D1B40"],
              {"sources": RUN_SOURCES + [RETAINED_SOURCE],
               "digests": RUN_DIGESTS + [RETAINED_DIGEST]})],
            [manifest_row("GamingCenter3_Cross.dll", 0, mode="not-in-project",
                          notes="337 MB buffer file")])
        rows, refusals = census.build_rows(decompiled, manifest)
        self.assertEqual(refusals, [])
        row = rows[0]
        self.assertEqual(row["in_project"], "no")
        self.assertEqual(row["count_basis"], "carried-from-run")
        # The zeros and the real number in adjacent columns. Neither is added to
        # the other: a function that failed to decompile emits no separator, so
        # the run's own total is not recoverable from the text.
        self.assertEqual(row["project_functions"], "0")
        self.assertEqual(row["separators_declared"], "2")
        self.assertEqual(row["binary_sha256"], RETAINED_DIGEST)

    def test_a_binary_with_no_manifest_row_is_refused(self):
        # Without the manifest row there are no project figures to carry, and
        # `in_project` would be a guess about a mode nobody has recorded.
        decompiled, manifest = self._tree(
            [("ACPIDriver", ["140001000"], {})], [])
        rows, refusals = census.build_rows(decompiled, manifest)
        self.assertEqual(rows, [])
        self.assertIn("no manifest row", refusals[0])

    def test_a_retained_export_is_carried_even_if_its_manifest_row_claims_a_project(self):
        # The exclusion has two sources and this is the case that separates them.
        # `retained_decompilations()` names the retained FILES and the label here
        # carries no `.c`, so a guard that compared the two directly is False for
        # every export on every tree -- and the exclusion falls back to the
        # manifest's `mode` alone, which is a second committed file disagreeing
        # with the driver's own constant. Here the row claims `rebuild-project`
        # and the program is still in PROJECT_EXCLUDED, so the basis must not be
        # `measured` and the separator count must not be checked against a
        # project total that was never produced.
        decompiled, manifest = self._tree(
            [(RETAINED_LABEL, ["180DE2000", "1818D1B40"],
              {"sources": RUN_SOURCES + [RETAINED_SOURCE],
               "digests": RUN_DIGESTS + [RETAINED_DIGEST]})],
            [manifest_row("GamingCenter3_Cross.dll", 7, mode="rebuild-project",
                          source=RETAINED_SOURCE)])
        rows, refusals = census.build_rows(decompiled, manifest)
        self.assertEqual(refusals, [])
        self.assertEqual(rows[0]["count_basis"], "carried-from-run")
        # The manifest says it is in the project, the driver says it is not, and
        # the census carries the manifest's reading while the check below is what
        # says the two committed files disagree.
        self.assertEqual(rows[0]["in_project"], "yes")
        with open(os.path.join(self.tmp, "c-census.csv"), "w", newline="") as f:
            f.write(census.render_csv(rows))
        problems = census.census_problems(os.path.join(self.tmp, "c-census.csv"),
                                          decompiled, manifest)
        self.assertTrue(any("PROJECT_EXCLUDED" in p for p in problems), problems)

    def test_a_header_and_a_target_list_that_disagree_are_refused(self):
        # Two committed files describing different bytes for one binary is a
        # provenance fault, and picking either one silently is how it becomes a
        # fact nobody checked. The basename has to stay put: the two files are
        # matched on the file name, so only the directory can differ.
        decompiled, manifest = self._tree(
            [("ACPIDriver", ["140001000"], {})],
            [manifest_row("ACPIDriver.sys", 1, sha256="9" * 64,
                          source="vendor/control-center-3.9.18.0/ACPIDriver/ACPIDriver.sys")])
        path = os.path.join(decompiled, "ACPIDriver.c")
        with open(path) as f:
            text = f.read()
