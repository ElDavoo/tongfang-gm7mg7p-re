class ManifestReconciliationTests(unittest.TestCase):
    """The `not-in-project` contradiction, and the three ways to bring it back.

    The whole point of the artefact: the manifest says `0,0,0,0,0` for a program
    whose retained export declares 64,588 functions, and nothing else run from
    the driver can see either number. So each of these mutates one column and
    asserts the census goes red and says which rule.
    """

    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)
        self.decompiled = os.path.join(self.tmp, "native")
        os.makedirs(self.decompiled)
        write_export(self.decompiled, RETAINED_LABEL, ["180DE2000", "1818D1B40"],
                     sources=RUN_SOURCES + [RETAINED_SOURCE],
                     digests=RUN_DIGESTS + [RETAINED_DIGEST])
        self.manifest = os.path.join(self.tmp, "manifest.csv")
        write_manifest(self.manifest, [
            manifest_row("GamingCenter3_Cross.dll", 0, mode="not-in-project",
                         notes="analysis database is 337 MB")])
        self.census_path = os.path.join(self.tmp, "c-census.csv")
        with open(self.census_path, "w", newline="") as f:
            f.write(census.render_csv(
                census.build_rows(self.decompiled, self.manifest)[0]))

    def check(self):
        return census.census_problems(self.census_path, self.decompiled,
                                      self.manifest)

    def rows(self):
        with open(self.census_path, newline="") as f:
            return list(csv.DictReader(f))

    def _rewrite(self, column, value, match=None):
        rows = self.rows()
        for r in rows:
            if match is None or r["export_label"] == match:
                r[column] = value
        with open(self.census_path, "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=census.CENSUS_COLUMNS,
                               lineterminator="\n")
            w.writeheader()
            w.writerows(rows)

    def test_the_committed_shape_is_clean(self):
        self.assertEqual(self.check(), [])

    def test_a_not_in_project_row_carrying_a_count_as_measured_is_red(self):
        # The failure this column exists to prevent: a non-zero number sitting
        # in a row whose manifest figures are zeros, labelled as if the two were
        # the same measurement, so a reader adds them.
        self._rewrite("count_basis", "measured")
        problems = self.check()
        self.assertTrue(any("not in the project" in p and "measured" in p
                            for p in problems), problems)

    def test_a_count_basis_outside_the_vocabulary_is_red(self):
        self._rewrite("count_basis", "looks-fine")
        problems = self.check()
        self.assertTrue(any("count_basis is" in p for p in problems), problems)

    def test_a_row_whose_project_figures_drift_from_the_manifest_is_red(self):
        # The manifest is a run-produced file and this column is a copy of it.
        # A census that can be edited into disagreeing with the manifest is a
        # census with two sources of truth and no gate on which is right.
        self._rewrite("project_functions", "64591")
        problems = self.check()
        self.assertTrue(any("project_functions" in p for p in problems), problems)

    def test_a_separator_count_that_does_not_match_the_file_is_red(self):
        self._rewrite("separators_declared", "99999")
        problems = self.check()
        self.assertTrue(any("separators_declared" in p for p in problems),
                        problems)

    def test_an_address_range_that_does_not_match_the_file_is_red(self):
        self._rewrite("last_addr", "1818D1B00")
        problems = self.check()
        self.assertTrue(any("last_addr" in p for p in problems), problems)

    def test_a_digest_that_contradicts_a_manifest_digest_is_red(self):
        # For the five in-project programs the manifest records a digest too, so
        # the header and the manifest can be checked against each other. Empty
        # is not a claim, which is why the retained row is exempt by
        # construction rather than by a carve-out.
        self._rewrite("binary_sha256", "0" * 64)
        problems = self.check()
        # No manifest digest for this program, so this one is caught by the
        # re-derivation instead -- and both paths must be red.
        self.assertTrue(problems)
        rows = [manifest_row("GamingCenter3_Cross.dll", 0, mode="not-in-project",
                             sha256="f" * 64, notes="x")]
        write_manifest(self.manifest, rows)
        self._rewrite("binary_sha256", "0" * 64)
        problems = self.check()
        self.assertTrue(any("different bytes" in p for p in problems), problems)

    def test_a_dropped_row_is_red_in_both_directions(self):
        # A census covering some of the tree is a check that has stopped
        # checking the rest, and the two halves are different mistakes: a row
        # naming a file that is gone, and a file with no row.
        rows = self.rows()
        with open(self.census_path, "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=census.CENSUS_COLUMNS,
                               lineterminator="\n")
            w.writeheader()
            w.writerows(rows + [dict(rows[0], path="windows/decompiled/native/Ghost.c")])
        problems = self.check()
        self.assertTrue(any("not on disk" in p for p in problems), problems)

        write_export(self.decompiled, "ACPIDriver", ["140001000"])
        write_manifest(self.manifest, [
            manifest_row("GamingCenter3_Cross.dll", 0, mode="not-in-project",
                         notes="x"),
            manifest_row("ACPIDriver.sys", 1, sha256="9" * 64,
                         source="vendor/control-center-3.9.18.0/ACPIDriver/ACPIDriver.sys")])
        problems = self.check()
        self.assertTrue(any("no census row" in p for p in problems), problems)

    def test_a_missing_census_file_is_reported_and_not_created(self):
        missing = os.path.join(self.tmp, "absent.csv")
        problems = census.census_problems(missing, self.decompiled, self.manifest)
        self.assertTrue(problems)
        self.assertFalse(os.path.exists(missing),
                         "--check must never bring the file it is checking into "
                         "existence; a check that writes its own subject reports "
                         "clean having asserted nothing")

    def test_a_header_this_tool_does_not_own_is_reported(self):
        path = os.path.join(self.tmp, "wrong.csv")
        with open(path, "w", newline="") as f:
            f.write("path,functions\n")
        self.assertTrue(census.census_problems(path, self.decompiled, self.manifest))

    def test_a_short_row_is_reported_rather_than_counted_as_smaller(self):
        # csv's forgiving reader ends a row early on a bad quote instead of
        # raising, the row comes back short, and every count taken from it is
        # then quietly smaller than the file. Strict is the point, and it is
        # partial: it catches the unterminated quote below, not a bare `"` in
        # the middle of a field, which it passes through verbatim. The
        # re-derivation's field-by-field comparison is what covers that half.
        path = os.path.join(self.tmp, "short.csv")
        with open(path, "w", newline="") as f:
            f.write(",".join(census.CENSUS_COLUMNS) + "\n")
            f.write('"unterminated,' + ",".join(["x"] * 12) + "\n")
        with self.assertRaises(csv.Error):
            census.read_census(path)


class CommittedTreeTests(unittest.TestCase):
    """The committed census against the committed `.c` files.

    Both directions, and the numbers come from the file rather than from a
    literal in this suite: the counts move when a legitimate re-export lands,
    and a test that held one would go red on the change that is supposed to be
    reviewable.
    """

    def committed(self):
        with open(CENSUS, newline="") as f:
            return list(csv.DictReader(f))

    def test_the_committed_census_re_derives_from_the_committed_c_files(self):
        problems = census.census_problems()
        self.assertEqual(problems, [], "\n".join(problems[:5]))

    def test_every_committed_c_has_exactly_one_row(self):
        rows = self.committed()
        on_disk = {rel for _abs, rel in
                   decompile_native.committed_c_files()}
        self.assertEqual({r["path"] for r in rows}, on_disk)
        self.assertEqual(len(rows), len({r["path"] for r in rows}))

    def test_the_census_header_is_this_tools_own(self):
        with open(CENSUS, newline="") as f:
            header = next(csv.reader(f))
        self.assertEqual(header, census.CENSUS_COLUMNS)

    def test_every_row_names_one_binary_and_one_export_label(self):
        for r in self.committed():
            self.assertEqual(
                decompile_native.export_label(r["binary"]), r["export_label"],
                f'{r["path"]}: the export label and the binary disagree, so this '
                f'row names a binary the exporter would not have written it for')

    def test_the_retained_export_row_is_the_not_in_project_one(self):
        rows = [r for r in self.committed() if r["export_label"] == RETAINED_LABEL]
        self.assertEqual(len(rows), 1)
        row = rows[0]
        self.assertEqual(row["binary"], "GamingCenter3_Cross.dll")
        self.assertEqual(row["in_project"], "no")
        self.assertEqual(row["count_basis"], "carried-from-run")
        self.assertEqual(row["project_functions"], "0")

    def test_the_retained_rows_figures_are_measured_off_the_file(self):
        # The re-derivation above already covers this globally; asserted per
        # row for the one the issue is about, so a failure names the artefact
        # rather than "c-census.csv line 4".
        row = next(r for r in self.committed()
                   if r["export_label"] == RETAINED_LABEL)
        got = census.measure_export(os.path.join(REPO, row["path"]))
        self.assertIsNotNone(got)
        self.assertEqual((str(got[0]), got[1], got[2]),
                         (row["separators_declared"], row["first_addr"],
                          row["last_addr"]))

    def test_the_census_is_derivable_into_a_temp_dir_byte_for_byte(self):
        # The property that makes --check a gate rather than a report: the
        # committed file is what this tool writes, so a hand-edited cell cannot
        # survive it. The tool's own line is swallowed so the suite's output
        # carries one `Ran N tests` summary and not a second one.
        with tempfile.TemporaryDirectory() as tmp:
            out = os.path.join(tmp, "c-census.csv")
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(census.main(["--write", "--census", out]), 0)
            with open(out) as f:
                written = f.read()
        with open(CENSUS) as f:
            self.assertEqual(written, f.read())

    def test_write_and_check_cannot_be_combined(self):
        # A run that both re-blessed the file and compared against it would
        # exit green on anything.
        with self.assertRaises(SystemExit) as raised:
            census.main(["--write", "--check"])
        self.assertIn("--write regenerates", str(raised.exception))

    def test_write_refuses_a_tree_it_cannot_measure(self):
        # Otherwise --write would commit an empty census, which --check then
        # reads as current, having compared nothing.
        with tempfile.TemporaryDirectory() as tmp:
            empty = os.path.join(tmp, "native")
            os.makedirs(empty)
            with self.assertRaises(SystemExit) as raised:
                census.main(["--write", "--census", os.path.join(tmp, "out.csv"),
                             "--decompiled-dir", empty])
            self.assertIn("refusing to write", str(raised.exception))
            self.assertFalse(os.path.exists(os.path.join(tmp, "out.csv")))

    def test_the_digest_and_the_census_are_different_claims_and_both_hold(self):
        # The census is not a replacement for the digest and does not replace
        # it: one says the file has not moved, the other says what is in it. A
        # row count that matched only one of them would be a coincidence.
        digests = {r["path"] for r in _committed_digests()}
        self.assertEqual(digests, {r["path"] for r in self.committed()})
        for r in self.committed():
            self.assertEqual(census.measure_export(
                os.path.join(REPO, r["path"]))[0],
                int(r["separators_declared"]))


def _committed_digests():
    with open(decompile_native.C_DIGESTS, newline="") as f:
        return list(csv.DictReader(f))


class AnchorTests(unittest.TestCase):
    """The driver's own `--check` carries the census, so the gate reads it.

    `decompile_native.py --check` is already invoked by the cheap gate, which is
    why this reconciliation needs no `.github/` change and no gate edit: a
    prepared patch nobody applies is a gate that does not run. Asserted here
    against the real tree so the delegation is load-bearing rather than
    decorative.
    """

    def test_the_driver_delegates_to_the_census_tool(self):
        self.assertEqual(decompile_native.census_problems(), [])

    def test_the_census_path_constant_sits_beside_the_digest_one(self):
        self.assertEqual(os.path.dirname(decompile_native.C_CENSUS),
                         os.path.dirname(decompile_native.C_DIGESTS))
        self.assertNotEqual(decompile_native.C_CENSUS, decompile_native.C_DIGESTS)

    def test_the_digests_file_is_unchanged_by_the_census_landing(self):
        # A census layer that quietly absorbed the digest layer would leave one
        # file doing two claims and no way to re-derive the other.
        #
        # Asserted as the claim -- every digest row names a committed `.c` --
        # and not as `len(rows) == 6`. The count is a value every landing export
        # has to bump by hand, and a seventh binary turning this red is a
        # nuisance, not a finding. The other direction (a `.c` landing without a
        # digest row) is held as a set equality by
        # `test_the_digest_and_the_census_are_different_claims_and_both_hold`.
        rows = _committed_digests()
        committed = {rel for _abs, rel in
                     decompile_native.committed_c_files()}
        for r in rows:
            self.assertIn(r["path"], committed,
                          f'{r["path"]} has a digest row but is not a committed '
                          f'.c under {decompile_native.DECOMPILED_DIR}')
            self.assertEqual(
                decompile_native.sha256_file(os.path.join(REPO, r["path"])),
                r["sha256"], r["path"])

    def test_the_import_is_directional_and_not_a_cycle(self):
        # census_native_c imports from decompile_native; the driver reaches back
        # with a function-local import. A module-level one would be a cycle, and
        # copying the separator grammar to avoid it would give the repository
        # two definitions of what a `// ==== ` line is -- so both facts are
        # asserted: the grammar is shared, not copied, and the back-reference is
        # deferred rather than absent.
        self.assertIs(census._c_markers, decompile_native._c_markers)
        self.assertIs(census.export_label, decompile_native.export_label)
        self.assertFalse(
            hasattr(decompile_native, "census_native_c"),
            "the driver imports the census tool at module scope, so importing "
            "it first would recurse. The back-reference has to stay inside the "
            "function that needs it.")


