#!/usr/bin/env python3
"""Unit checks for citation_gap_scan.py, the window arithmetic and the three
verdicts.

`citation_gap_scan.py --self-test` covers the live population end to end and
pins the figures `docs/findings/citation-gap-scan.md` quotes. This file covers
the pieces on their own, on synthetic windows, because the pieces fail
*differently* from the census and the census would hide it: a window built one
byte short decodes to nothing rather than to a wrong answer, a boundary taken
from the wrong scope moves the whole window, and a `db` count used as the
verdict would pass on this tree -- the looser form selects the same single pair
the chosen one does -- while being wrong about why.

The three shapes named in the plan each get a case here, over real committed
bytes: the 2-byte gap at `bank1,E57E` (the issue's worked example), the
zero-byte gap at `bank0,B5B2`, and a window that does not decode at all.
"""
import collections
import importlib.util
import os
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
spec = importlib.util.spec_from_file_location(
    'citation_gap_scan', HERE / 'citation_gap_scan.py')
scan = importlib.util.module_from_spec(spec)
spec.loader.exec_module(scan)

DECOMPILED = HERE.parent / 'decompiled'
LISTING = DECOMPILED / 'bank1' / 'E57E.asm'

# Loaded once here rather than per test: the three bank images are 192 KiB of
# the committed firmware and `verify_gap_text.load_images` reads them from the
# cache `verify_reassembly` builds, and unittest's warning filters turn the
# reader's unclosed-file ResourceWarning on where a plain script run leaves it
# off. Neither of those is this suite's business to fix -- both are shared
# files another agent may be touching -- so the suite loads once and says
# nothing.
_IMAGES = scan.G.load_images()


def insns(window, base=0):
    return scan.walk(window, base)


class WindowArithmetic(unittest.TestCase):
    """Where the window starts and stops, which is the whole of the claim that
    a boundary cut happened at all."""

    def test_end_is_the_last_instruction_plus_its_own_byte_count(self):
        # bank1/E57E.asm is a single `c0 07` -- `push 0x07` -- so the listing
        # ends at 0xE57E + 2 = 0xE580 and the gap the issue describes opens
        # there. A reader that took the last *address* rather than the last
        # address plus its length would window one byte in and decode
        # `07 12` as `inc @r0 / lcall ...`, which is the same two bytes read at
        # the wrong alignment.
        self.assertEqual(scan.listing_end(LISTING), 0xE580)

    def test_end_reads_the_byte_column_so_a_bare_ret_still_has_a_length(self):
        # bank0/B5D2.asm is one line, `22 - - ret`, and a bare `ret` is five
        # tokens where `mov A, #0x10` is six. A reader that counted tokens, or
        # that read the mnemonic, would either drop the line or give it no
        # length; either way the window would start inside the `ret`.
        self.assertEqual(
            scan.listing_end(DECOMPILED / 'bank0' / 'B5D2.asm'), 0xB5D3)
        self.assertEqual(
            scan.listing_end(DECOMPILED / 'bank0' / 'B5B2.asm'), 0xB5CC)

    def test_a_listing_with_no_instruction_line_has_no_end(self):
        # Not found by this method, not absent. A None here has to stay
        # distinguishable from 0, which is a real address, rather than
        # defaulting into a window at the bottom of the image.
        handle = tempfile.NamedTemporaryFile('w', suffix='.asm', delete=False)
        with handle as f:
            f.write("; bank0 @ 0000   only_a_header   [named]\n"
                    "; Ghidra 12.1.3 disassembly, generated by "
                    "build_ec_decompile.py -- do not edit.\n\n")
        try:
            self.assertIsNone(scan.listing_end(handle.name))
        finally:
            os.remove(handle.name)

    def test_next_entry_is_the_nearest_one_strictly_after_in_the_same_scope(self):
        by_scope = {'bank0': [0x1000, 0x1100, 0x1102, 0x2000],
                    'bank1': [0x1050, 0x1055]}
        # Strictly after: a row's own address is not its own next entry, and
        # the nearest entry is the one, not the first in the list.
        self.assertEqual(scan.next_entry(by_scope, 'bank0', 0x1100), 0x1102)
        self.assertEqual(scan.next_entry(by_scope, 'bank0', 0x1000), 0x1100)
        # A `common` row at 0x1100 is nearer than the `bank0` row at 0x1102 and
        # is a *different* scope, so it must not answer a bank0 question.
        self.assertIsNone(
            scan.next_entry({'common': [0x1100]}, 'bank0', 0x1050))
        self.assertIsNone(scan.next_entry(by_scope, 'bank1', 0x1055))
        self.assertIsNone(scan.next_entry({}, 'bank0', 0x1000))

    def test_the_slack_is_what_lets_a_straddling_lcall_complete(self):
        # The issue's worked example, over the committed bank-1 bytes. The
        # window runs three past the boundary because `lcall` is 3 bytes: at
        # 0xE580, two bytes of gap, the transfer only completes by reading
        # 0xE582 -- the byte the `bank1,E582` row itself calls contested. A
        # window stopping at the boundary decodes *nothing*, which is a
        # different answer and a wrong one.
        bank1 = _IMAGES['bank1']
        self.assertEqual(bank1[0xE580:0xE585], b"\x12\xe5\xd6\xd0\x07")
        whole, truncated = insns(bank1[0xE580:0xE585], 0xE580)
        self.assertFalse(truncated)
        self.assertEqual([t.split() for _a, _r, t, _u in whole],
                         [["lcall", "0xe5d6"], ["pop", "0x07"]])
        short, short_trunc = insns(bank1[0xE580:0xE582], 0xE580)
        self.assertEqual(short, [])
        self.assertTrue(short_trunc)

    def test_the_zero_byte_gap_window_is_the_neighbours_head(self):
        # bank0,B5B2 ends 0xB5CC and bank0,B5CC begins there, so the window is
        # three bytes of slack over the next function's own first instruction.
        # This is the shape 89 of the 105 citing rows have, and the reason the
        # issue's "bytes stranded between exports" framing is the exception.
        bank0 = _IMAGES['bank0']
        self.assertEqual(scan.listing_end(DECOMPILED / 'bank0' / 'B5B2.asm'),
                         0xB5CC)
        self.assertEqual(scan.next_entry(
            {'bank0': [0xB5B2, 0xB5CC]}, 'bank0', 0xB5B2), 0xB5CC)
        self.assertEqual(bank0[0xB5CC:0xB5CF], b"\x90\x08\x9c")
        got, _trunc = insns(bank0[0xB5CC:0xB5CF], 0xB5CC)
        self.assertEqual([t for _a, _r, t, _u in got],
                         ["mov  dptr,#0x089c"])


class OverrunGuard(unittest.TestCase):
    """`disasm8051.decode()` indexes `OPCODE_LEN[d[i]]` before its own bounds
    check, so a window whose last byte is a 1-byte opcode raises rather than
    stopping. A gap window ends on one routinely, which is why this tool walks
    the same tables itself."""

    def test_a_window_that_is_one_1_byte_opcode_decodes_and_stops(self):
        got, truncated = insns(b"\x22", 0xB5D2)
        self.assertEqual([t for _a, _r, t, _u in got], ["ret"])
        self.assertFalse(truncated)

    def test_an_instruction_that_does_not_fit_ends_the_walk_and_is_reported(self):
        # Two bytes are not enough for a 3-byte `lcall`, nor for a 3-byte
        # `mov dptr,#imm16`. Neither may be decoded from bytes that are not
        # there, and neither may raise.
        for window, base in ((b"\x12\xe5", 0xE580), (b"\x90\x08", 0xB5CC)):
            got, truncated = insns(window, base)
            self.assertEqual(got, [], window.hex())
            self.assertTrue(truncated, window.hex())
        # And the mixed shape: what does fit is decoded, and the walk stops at
        # the one that does not. The `ret` is kept rather than discarded, which
        # is the difference between a truncated window and a window that failed
        # to start.
        got, truncated = insns(b"\x22\x12\xe5", 0xB5D2)
        self.assertEqual([t for _a, _r, t, _u in got], ["ret"])
        self.assertTrue(truncated)

    def test_an_empty_window_decodes_to_nothing_and_is_not_a_truncation(self):
        # `truncated` says a *decoded instruction* did not fit. An empty buffer
        # has no instruction to have failed, so the two must stay
        # distinguishable -- a window that never started is not a window whose
        # head was cut off.
        got, truncated = insns(b"", 0xB5CC)
        self.assertEqual(got, [])
        self.assertFalse(truncated)

    def test_disasm8051_decode_still_raises_which_is_why_this_tool_does_not_use_it(self):
        # Asserted rather than assumed: if this stops being true the guard's
        # reason is gone and `walk()` should be replaced by a `decode()` call
        # rather than kept as a second walk.
        with self.assertRaises(IndexError):
            list(scan.D.decode(b"\x22", 0, 4, 0xB5D2))

    def test_the_tool_carries_no_second_opcode_table(self):
        # A length or mnemonic table of its own would be a second thing to keep
        # in step with `disasm8051.py`, and the drift would be silent in the
        # quiet direction. Sharing the committed tables is the whole reason
        # `walk()` exists rather than a call to `decode()`, so the absence is
        # asserted rather than left to a reader's attention.
        for name in ('OPCODE_LEN', 'REL_OPCODES', 'FLOW_OPCODES', 'BIT_SFR',
                     'mnemonic', 'paged_target', 'relative_target'):
            self.assertFalse(hasattr(scan, name), name)
        got, _trunc = insns(b"\x90\x08\x9c", 0xB5CC)
        self.assertEqual(got[0][2], scan.D.mnemonic(b"\x90\x08\x9c", 0, 0xB5CC))


class NotCodeCriterion(unittest.TestCase):
    """`not-code` is a byte test, not a `db` count, and the two are not the same
    statement."""

    def test_the_four_map_unassigned_bytes_are_the_criterion(self):
        # Stated from the MCS-51 opcode map. 0x06/0x07 and 0x16/0x17 are the
        # two gaps in the 0x00-0x1F row, and 0x18 (DEC R0) is the first
        # assigned byte above them -- asserted so a list that grew a fifth
        # entry by accident would be caught rather than quietly widening the
        # verdict.
        self.assertEqual(tuple(scan.UNASSIGNED), (0x06, 0x07, 0x16, 0x17))
        self.assertEqual(scan.D.mnemonic(b"\x18", 0, 0), "dec  r0")
        self.assertTrue(all(scan.D.mnemonic(bytes([b]), 0, 0).startswith("db ")
                            for b in scan.UNASSIGNED))

    def test_verdict_of_reads_the_flag_not_the_mnemonic_text(self):
        # A window whose walk lands on 0x17 is `not-code`; one that lands on
        # 0x22 is not. The two differ only in the byte, and the assertion is
        # that the text is never consulted -- a decoder that grew a case for
        # 0x17 would otherwise move a verdict by editing a table.
        self.assertEqual(
            scan.verdict_of([(0x3AF0, b"\x17", "db   0x17", True)]), "not-code")
        self.assertIsNone(
            scan.verdict_of([(0x3AF0, b"\x17", "mov  a", False)]))
        self.assertIsNone(
            scan.verdict_of([(0xB5D2, b"\x22", "ret", False)]))

    def test_a_db_that_is_not_a_map_unassigned_byte_is_still_not_verdict_not_code(self):
        # The reason the criterion is not a `db` count. `disasm8051`'s mnemonic
        # table is partial by design -- an instruction the map assigns but the
        # table does not carry prints as `db` too -- so a window landing on one
        # of those is unknown by this tool's decoder, which is not the same
        # answer as "not code". 0xD4 (`da A`) is assigned by the 8052 map and
        # absent from the table, so it is the two rules disagreeing, stated.
        self.assertTrue(scan.D.mnemonic(b"\xd4", 0, 0).startswith("db "))
        self.assertNotIn(0xD4, scan.UNASSIGNED)
        self.assertIsNone(scan.verdict_of([(0x9000, b"\xd4", "db   0xd4",
                                            False)]))


class TargetResolution(unittest.TestCase):
    """A window transfer counts as "to the named callee" only if it resolves
    through the same `Index.resolve` the graph uses, under the citing row's
    scope. Comparing raw addresses instead would let this tool disagree with
    `call_graph.py` about a bank listing reaching a `common` row."""

    def index(self):
        return scan.cg.Index([{"program": "common", "addr": "05E8", "name": "FUN_05e8"},
                              {"program": "bank0", "addr": "07D0", "name": "FUN_07d0"},
                              {"program": "bank0", "addr": "9A43", "name": "FUN_9a43"},
                              {"program": "bank1", "addr": "9A43", "name": "FUN_9a43"}])

    def test_a_bank_citer_reaching_a_common_address_resolves_to_the_common_row(self):
        self.assertEqual(
            scan.resolve_site(self.index(), "bank0", "lcall 0x05e8"),
            (("common", "05E8"), "05E8"))

    def test_an_address_with_two_scope_rows_resolves_to_the_callers_own(self):
        # 0x9A43 carries a bank0 and a bank1 row; under bank0 it is the bank0
        # one, and a bare-address comparison would not know which.
        self.assertEqual(
            scan.resolve_site(self.index(), "bank1", "lcall 0x9a43"),
            (("bank1", "9A43"), "9A43"))

    def test_a_transfer_that_is_not_a_transfer_resolves_to_nothing(self):
        for text in ("ret", "mov  dptr,#0x05e8", "push 0x05", "lcall label",
                     "lcall 0x", "lcall 0xzzzz"):
            self.assertIsNone(scan.resolve_site(self.index(), "bank0", text),
                              text)

    def test_all_four_transfer_forms_are_looked_for(self):
        # 0x5A43 is reached by 11 `ajmp` and zero `lcall` in the real census.
        # A window that carried the paged form has to be read, or the one
        # boundary cut that used a paged form would be reported as no-transfer.
        self.assertIsNotNone(scan.resolve_site(self.index(), "bank0",
                                               "ajmp 0x9a43"))


class ScopeCoverage(unittest.TestCase):
    """Three images and two of them are not the EC's common area."""

    def test_a_common_citer_reads_bank0_and_a_pd_citer_reads_pd(self):
        self.assertEqual(
            scan.next_entry({'common': [0x05E7]}, 'common', 0x05E6), 0x05E7)
        self.assertEqual(
            scan.next_entry({'pd': [0x104D]}, 'pd', 0x1041), 0x104D)
        images = _IMAGES
        self.assertEqual(images['common'] if 'common' in images else None, None)
        # `common` is an export grouping rather than a fourth image, and the
        # fallback is the one `verify_gap_text` already uses.
        self.assertIs(images.get('common') or images['bank0'], images['bank0'])

    def test_nearer_in_bank_reports_and_does_not_choose(self):
        # A `common` function is exported once for both banks, so at runtime
        # the executing bank's boundary is the one that exists. The tool counts
        # the case rather than silently picking a scope, which is the reading
        # `docs/findings/citation-gap-scan.md` states.
        by_scope = {'common': [0x0600], 'bank0': [0x05F0, 0x0700],
                    'bank1': [0x05E0, 0x0610]}
        self.assertEqual(
            scan.nearer_in_bank(by_scope, 'common', 0x05D0, 0x0600),
            'bank0:0x05F0 bank1:0x05E0')
        # Strictly between: the boundary itself and the row's own address are
        # not "nearer".
        self.assertEqual(scan.nearer_in_bank(by_scope, 'common', 0x0600,
                                             0x0600), '')
        # Not a `common` row, so the question does not arise.
        self.assertEqual(scan.nearer_in_bank(by_scope, 'bank0', 0x05D0,
                                             0x0600), '')
        self.assertEqual(scan.nearer_in_bank({'common': [0x0600]}, 'common',
                                             0x05D0, None), '')


class ReportTable(unittest.TestCase):
    """`--check` compares bytes, and a table whose rows parse equal while its
    bytes do not is a table this tool did not write."""

    def rows(self):
        return [
            {"callee_scope": "bank1", "callee_addr": "E5D6", "citer_scope": "bank1",
             "citer_addr": "E57E", "verdict": "boundary-cut", "gap": "2"},
            {"callee_scope": "bank0", "callee_addr": "B4A8", "citer_scope": "bank0",
             "citer_addr": "B5B2", "verdict": "no-transfer", "gap": "0"},
        ]

    def fill(self, rows):
        out = []
        for r in rows:
            out.append({c: r.get(c, "") for c in scan.COLUMNS})
        return out

    def test_the_rendered_table_is_a_dictreader_fixed_point(self):
        text = scan.render(self.fill(self.rows()))
        self.assertEqual(
            text, scan.render(list(__import__("csv").DictReader(
                text.splitlines()))))

    def test_identical_tables_compare_equal(self):
        text = scan.render(self.fill(self.rows()))
        self.assertEqual(scan.check_table(text, text), (0, []))

    def test_a_crlf_table_is_rejected_on_its_bytes_although_the_rows_match(self):
        import csv
        text = scan.render(self.fill(self.rows()))
        crlf = text.replace("\n", "\r\n")
        self.assertEqual(list(csv.DictReader(crlf.splitlines())),
                         list(csv.DictReader(text.splitlines())))
        rc, lines = scan.check_table(crlf, text)
        self.assertEqual(rc, 1)
        # Every row parses equal, so the diff is empty and the failure has to
        # say so rather than leave the reader with an exit code and no output.
        self.assertEqual(scan.diff_table(crlf, text), [])
        self.assertEqual(len(lines), 1)
        self.assertIn("bytes differ", lines[0])

    def test_a_changed_verdict_is_rejected_naming_the_row_and_the_column(self):
        rows = self.fill(self.rows())
        rows[0]["verdict"] = "no-transfer"
        rc, lines = scan.check_table(scan.render(rows),
                                     scan.render(self.fill(self.rows())))
        self.assertEqual(rc, 1)
        self.assertEqual(lines[0], "  bank1,E5D6 cited by bank1,E57E:")
        self.assertIn("verdict", lines[1])
        self.assertIn("recomputed 'boundary-cut'", lines[1])

    def test_a_dropped_row_is_rejected_on_the_count(self):
        have = self.fill(self.rows())
        rc, lines = scan.check_table(scan.render(have[:-1]), scan.render(have))
        self.assertEqual((rc, lines), (1, ["  row count: committed 1, "
                                           "recomputed 2"]))


class VerdictPartition(unittest.TestCase):
    """The three verdicts partition, and the per-pair columns do not add a
    fourth. A pair that is both 'cut' and 'the callee is already booked
    elsewhere' has to be one pair with two columns, or the split stops adding
    up and the report cannot be read."""

    def test_a_fixture_set_partitions_and_carries_both_columns(self):
        verdicts = ["boundary-cut", "no-transfer", "no-transfer",
                    "no-transfer", "not-code"]
        rows = [dict(verdict=v, neighbour_edge="bank1:E5A7 lcall" if i == 0 else "")
                for i, v in enumerate(verdicts)]
        tally = collections.Counter(r["verdict"] for r in rows)
        self.assertEqual(dict(tally), {"boundary-cut": 1, "no-transfer": 3,
                                       "not-code": 1})
        self.assertEqual(sum(tally.values()), len(rows))
        # Both signals on one row, one verdict: the columns are not buckets, so
        # the split still adds up to the population.
        cut = [r for r in rows if r["verdict"] == "boundary-cut"][0]
        self.assertEqual(cut["neighbour_edge"], "bank1:E5A7 lcall")
        self.assertEqual(sum(1 for r in rows if r["neighbour_edge"]), 1)


