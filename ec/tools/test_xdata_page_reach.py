#!/usr/bin/env python3
"""Offline checks for `xdata_page_reach.py`: the committed per-address table,
the verdict vocabulary, and the cross-checks that hold both to the tools it
joins.

No firmware upload, no hardware, no Windows, no network. Every input is a file
this repository already ships -- `ec/firmware/GMxMGxx_11.800` and
`ec/annotations/xdata-0exx-page-reach.csv` -- so the whole suite runs in a
cloud agent's turn.

**What stands in for what.** The tool answers "is this address reached, and by
which site" for the `0x0E00`-`0x0EFF` page, out of five passes the tree
already had. What can go wrong is not the arithmetic but the *vocabulary*: a
zero that reads as "absent" rather than "not found", a `reached` that means a
page was reached rather than an address, and a table that agrees with itself
because both sides were produced by the same wrong filter. The cases below are
those three.

**No assertion here is a count of this repository.** How many addresses the
table reaches, how many rows it has, how many suites exist -- none of those is
asserted, because each is a value every landing change moves and the line
carrying it is one every open branch edits (CLAUDE.md, "No totals of the
repository's own text"). What is asserted is a *property*: the committed table
is what the tool produces, a verdict is one of the tool's own two tokens, a
`reached` row names a site, the walk reach agrees with the other tool that
computes it, and nothing was written.

**The agreement is checked against the other tool, not against a literal.**
`xdata_span_survey.py`'s per-image counts, `computed_dptr_sites.py --page`'s
rows and `trace_xdata_refs.py`'s site cells are each re-derived by running
them, so a change in any of the tools shows up as disagreement rather than as a
number that quietly moved. The one place a literal is pinned is the walk reach
at `0x0E06`, and that case says why: it is pinned *and* cross-checked, because
a pair of tools that drift together agree with each other forever.

**The mutations are the reason the rest of the file means anything.** Every
check below would stay green against a table generated by a filter that
credits a whole page to its addresses, which is the overclaim the tool's own
docstring is about. So `--check` is pointed at a deliberately wrong file, the
verdict vocabulary is checked against the tool's own declaration, and the
read-only property is asserted over the committed tree.

Run it directly, or through `bash tools/run-tests.sh`, which discovers every
`test_*.py` in the tree.
"""
import csv
import io
import os
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.join(HERE, os.pardir, os.pardir)
EC = os.path.join(HERE, os.pardir)
FIRMWARE = os.path.join(EC, "firmware", "GMxMGxx_11.800")
REGISTERS = os.path.join(EC, "annotations", "registers.yaml")
TOOL = os.path.join(HERE, "xdata_page_reach.py")
TRACE = os.path.join(HERE, "trace_xdata_refs.py")
SURVEY = os.path.join(HERE, "xdata_span_survey.py")

TABLE = os.path.join(EC, "annotations", "xdata-0exx-page-reach.csv")

# The span the committed table is the product of. Named once, because the
# command, the `--check` and every case that reads the table have to agree on
# it and a range spelled in four places is four places to update.
SPAN = ("0x0E00", "0x0EFF")


def run_tool(*args):
    return subprocess.run([sys.executable, TOOL, *args],
                          capture_output=True, cwd=REPO)


def table_bytes():
    r = run_tool(FIRMWARE, *SPAN, "--csv")
    assert r.returncode == 0, r.stderr.decode()
    return r.stdout


def rows_of(raw):
    return list(csv.DictReader(io.StringIO(raw.decode(), newline="")))


def row_for(rows, addr):
    return next(r for r in rows if r["addr"] == addr)


def committed_rows():
    with open(TABLE, newline="") as f:
        return list(csv.DictReader(f))


# Read once: every case that wants the generated table wants the same one, and
# the generated table is what `--check` compares the committed one against.
GENERATED = table_bytes()
ROWS = rows_of(GENERATED)


def tool_module():
    """The tool imported, for the tokens it declares.

    Imported rather than re-spelled here so a vocabulary that grows is a
    vocabulary this suite sees: the cases below assert against `VERDICTS` as
    the tool declares it, and separately that every verdict the tool *emitted*
    is in it -- the first would pass against a tool that emitted nothing.
    """
    if HERE not in sys.path:
        sys.path.insert(0, HERE)
    import xdata_page_reach
    return xdata_page_reach


class CommittedTable(unittest.TestCase):
    """`--check`, and the reproduction it exists to hold."""

    def test_the_committed_table_is_reproduced_byte_for_byte(self):
        r = run_tool(FIRMWARE, *SPAN, "--csv", "--check", TABLE)
        self.assertEqual(r.returncode, 0, r.stderr.decode())
        self.assertIn("reproduces it byte for byte", r.stdout.decode())

    def test_check_is_red_on_a_table_that_drifted(self):
        """The mutation.

        `--check` is the only thing standing between a regenerated table and a
        hand-edited one, and it is the check that would catch a verdict flipped
        by hand -- so it is pointed at a table whose *verdict* was changed
        rather than one whose spacing was, and has to go red through its exit
        code. The verdict is the cell a reader acts on, so it is the one a
        hand edit would touch.
        """
        drifted = GENERATED.replace(b"0x0E06,reached",
                                    b"0x0E06,not-reached-by-this-method", 1)
        self.assertNotEqual(
            GENERATED, drifted,
            "the generated table no longer carries '0x0E06,reached', so this "
            "case has stopped testing the mutation")
        with tempfile.TemporaryDirectory() as d:
            path = os.path.join(d, "drifted.csv")
            with open(path, "wb") as f:
                f.write(drifted)
            r = run_tool(FIRMWARE, *SPAN, "--csv", "--check", path)
        self.assertEqual(r.returncode, 1)
        self.assertIn("differs from what this run produced", r.stderr.decode())
        self.assertIn("regenerate rather than edit", r.stderr.decode())

    def test_an_unreadable_path_is_reported_rather_than_compared(self):
        r = run_tool(FIRMWARE, *SPAN, "--csv", "--check",
                     os.path.join(HERE, "no-such-table.csv"))
        self.assertEqual(r.returncode, 1)
        self.assertEqual(r.stdout, b"")
        self.assertNotIn("Traceback", r.stderr.decode())

    def test_the_committed_file_is_what_this_run_produces(self):
        """The same property as bytes rather than as the `--check` exit code.

        `--check` reporting green is the tool's word for it; this reads the
        committed file directly, so a `--check` that had stopped comparing
        anything would leave this case red on its own.
        """
        with open(TABLE, "rb") as f:
            self.assertEqual(GENERATED, f.read())


class Verdicts(unittest.TestCase):
    """The two-token vocabulary, and what each token is allowed to mean."""

    def test_every_verdict_is_one_of_the_tools_own_tokens(self):
        """Closed vocabulary, checked against the declaration.

        Not "the column is non-empty": a third token invented later would
        satisfy that and would be a claim about the firmware this tool cannot
        support. `VERDICTS` is read from the tool, so adding a token there and
        emitting it is a deliberate act that this case then permits.
        """
        allowed = set(tool_module().VERDICTS)
        self.assertTrue(ROWS, "the generated table is empty")
        for row in ROWS:
            self.assertIn(row["verdict"], allowed, row["addr"])

    def test_no_token_claims_a_register_is_absent(self):
        """There is no token in the table that says "absent".

        The point of the name `not-reached-by-this-method` is that it is a
        statement about a scan. A tool that emitted `absent` would be making
        the claim `docs/findings.md` 4c records two of this repository's
        conclusions as having retracted, so the refusal is asserted here rather
        than left to the docstring: no emitted verdict may contain a word that
        asserts non-existence.
        """
        for row in ROWS:
            verdict = row["verdict"].lower()
            for word in ("absent", "unused", "dead", "nonexistent", "missing"):
                self.assertNotIn(word, verdict, row["addr"])

    def test_the_not_reached_token_is_not_a_registers_yaml_status(self):
        """The two vocabularies stay disjoint, from this side.

        `check_status_vocabulary.py` reads the declared list out of
        `registers.yaml`'s own header comment and fails an undeclared status,
        so a token of this tool's leaking into a `status:` cell is caught
        there. This is the other direction: a `status:` value that reached this
        tool's verdict column would grade a register here on a scale that says
        what is known about the byte, which is not what this scan measured.
        Declared values are parsed with `check_status_vocabulary`'s own
        parser rather than re-read, so the two cannot disagree about what is
        declared.
        """
        import check_status_vocabulary as V
        declared = V.declared_statuses(REGISTERS)
        self.assertTrue(declared, "registers.yaml declares no status values")
        values, suffixes = declared
        for token in tool_module().VERDICTS:
            self.assertNotIn(token, values)
            self.assertNotIn(token, suffixes)

    def test_a_reached_row_names_the_site_that_reached_it(self):
        """`reached` without a cited site would be the claim this table exists
        to avoid.

        The issue asked for every address reported as *reached, with the site
        that reaches it cited*, and the citation is the half that makes the
        verdict checkable by a reader. So the site column is asserted
        non-empty exactly where the verdict is `reached`, and the method column
        with it: a row that named a site without saying which pass found it
        would leave the reader unable to re-derive anything.
        """
        reached = tool_module().REACHED
        for row in ROWS:
            if row["verdict"] != reached:
                continue
            self.assertTrue(row["reach_site"], row["addr"])
            self.assertTrue(row["reach_method"], row["addr"])
            self.assertTrue(row["reach_cell"], row["addr"])

    def test_a_page_reach_does_not_make_an_address_reached(self):
        """The overclaim this tool's design is about, asserted as a property.

        A computed `mov DPH,a` reaches a *page*: the high byte is an immediate
        and the low one is a run-time value, so no address inside the page is
        named. Crediting the page to its addresses would make `reached` true
        of every address on a reached page and the column would carry no
        information at all -- and it would claim, for every byte of the page, a
        site that resolves none of them.

        So the two are separate columns, and a row may carry a `page_site` and
        still be `not-reached-by-this-method`. That combination is the point:
        it is the difference between "nothing here" and "nothing here that
        names this byte", and it is asserted here so a change that merged the
        two columns would go red.
        """
        unreached = tool_module().NOT_REACHED
        both = [r for r in ROWS
                if r["verdict"] == unreached and r["page_site"]]
        self.assertTrue(
            both,
            "no row is unreached-with-a-reached-page, so this suite is not "
            "exercising the distinction it exists to hold")
        for row in both:
            self.assertFalse(row["reach_site"], row["addr"])
            self.assertTrue(row["page_site_cell"], row["addr"])

    def test_the_page_columns_are_not_evidence_of_a_reach(self):
        """`page_site` and `page_possible` describe the *page*, never the byte.

        `page_possible` is the `addc DPH` residual's two-element page set: a
        page the scan could not rule out, which is weaker still than a page it
        reached. Both live outside the reach columns so a reader filtering on
        `verdict` cannot pick them up as evidence -- asserted by checking that
        no method token appears in a reach column for a row whose only
        population came from a page column.
        """
        methods = {tool_module().DIRECT, tool_module().WALK,
                   tool_module().COMPUTED, tool_module().INDIRECT}
        for row in ROWS:
            if not row["verdict"] == tool_module().NOT_REACHED:
                continue
            self.assertEqual(set(filter(None, row["reach_method"].split(";"))),
                             set(), row["addr"])
            self.assertTrue(methods, "the tool declares no reach methods")


class CrossToolAgreement(unittest.TestCase):
    """The table held to the tools it joins, each re-derived rather than
    pinned."""

    def test_the_direct_counts_are_the_span_surveys(self):
        """`direct_main_ec`/`direct_pd_image` against `xdata_span_survey.py`.

        Re-derived by running the other tool, so a change in either shows up as
        disagreement. Pinned as literals nowhere: a number here would be a
        figure every landing change to either tool moves.
        """
        r = subprocess.run([sys.executable, SURVEY, FIRMWARE, *SPAN, "--csv"],
                           capture_output=True, text=True, cwd=REPO)
        self.assertEqual(r.returncode, 0, r.stderr)
        for other in rows_of(r.stdout.encode()):
            row = row_for(ROWS, other["addr"])
            self.assertEqual(int(row["direct_main_ec"]), int(other["main_ec"]),
                             other["addr"])
            self.assertEqual(int(row["direct_pd_image"]), int(other["pd_image"]),
                             other["addr"])

    def test_every_direct_site_the_span_survey_counts_is_a_reached_row(self):
        """A count with no `reached` row would mean the table lost a site.

        The other direction of the same join: the survey counts byte patterns
        and this table resolves them, so every address it counts at all must
        come out `reached`. An address the survey counts zero of may still be
        reached -- by a walk or an indirect site -- which is why this is a
        one-way implication and not an equality.
        """
        reached = tool_module().REACHED
        for row in ROWS:
            if int(row["direct_main_ec"]) or int(row["direct_pd_image"]):
                self.assertEqual(row["verdict"], reached, row["addr"])

    def test_the_walk_reach_agrees_with_trace_xdata_refs(self):
        """The `walk` rows against the tool that computes the walk.

        `trace_xdata_refs.py --counts-only` counts each address's own
        `MOV DPTR` sites; it does not report the bytes a walk runs onto, so
        the comparison is the other way round and narrower: for every address
        this table credits to a `walk`, `trace_xdata_refs.py` is asked for the
        seed's own direction and this run has to carry that same text. The
        seed is the address one below the walk target, and its cell is the
        `walks N consecutive bytes` phrase whose N is what produced the
        reach -- so a `walk_span()` that drifted from `classify()` would put a
        reach on a byte no window covers.
        """
        walks = [r for r in ROWS if tool_module().WALK in r["reach_method"]]
        self.assertTrue(walks, "no address is reached by a walk in this span")
        for row in walks:
            seed = row_for(ROWS, "0x%04X" % (int(row["addr"], 16) - 1))
            for cell in row["reach_cell"].split(";"):
                self.assertIn(cell, seed["reach_cell"],
                              "%s walks onto from its seed's window"
                              % row["addr"])

    def test_a_walk_target_records_both_methods_and_not_just_one(self):
        """`0x0E06`, pinned *and* cross-checked.

        The class above re-derives the walk reach from the other tool, which
        cannot catch the case where both tools drift the same way -- the
        vacuous-green shape `docs/findings.md` 14b records. So the walk reach
        is pinned as a literal too, at the address that exists to show the two
        methods are kept apart: `0x0E06` carries **both** `direct` (it has a
        site of its own, at `bank0:0xF3AD`) and `walk` (the `0x0E05` site's
        window runs one byte onto it). A table that folded the walk into the
        direct count would print `direct` alone here and lose the second reach
        entirely -- which is the property the separate column is for.

        That both methods appear is also why the walk contributes no address
        the direct count missed *on this span*: the honest reading, and the
        tool's docstring says so rather than the walk pass being credited with
        a result it did not produce here.
        """
        row = row_for(ROWS, "0x0E06")
        methods = set(filter(None, row["reach_method"].split(";")))
        self.assertEqual(methods, {tool_module().DIRECT, tool_module().WALK})
        self.assertEqual(row["verdict"], tool_module().REACHED)
        self.assertIn("bank0:0xF284", row["reach_site"])
        self.assertIn("bank0:0xF3AD", row["reach_site"])

    def test_every_walk_target_on_this_span_also_has_a_site_of_its_own(self):
        """The walk pass's contribution on this span, as a property.

        Not a count: what is asserted is the shape, and it is asserted because
        it is the reading a reader would otherwise have to take on trust. Every
        address this table credits to a `walk` also has a `direct` site, so the
        walk changes no address's verdict here -- the finding is that the two
        walks on the page reach bytes that were already reached, not that the
        page has two more reachable bytes than the site count shows. A change
        that made a walk the *only* reach for an address would fail this and
        say so, which is when the write-up would have to be re-derived.
        """
        for row in ROWS:
            if tool_module().WALK not in row["reach_method"]:
                continue
            self.assertIn(tool_module().DIRECT, row["reach_method"], row["addr"])
            self.assertGreater(int(row["direct_main_ec"]), 0, row["addr"])

    def test_the_page_reach_is_the_computed_dptr_sites_own(self):
        """The `page_site` column against `computed_dptr_sites.py --page`.

        Run for the page the span sits in, so the site this table reports as
        reaching the page is the one that tool names, and the cell quoted in
        `page_site_cell` is that row's own `xaddr` text rather than prose
        written here. A page reported reached with no site behind it, or with
        a cell that does not match the tool's, would both be the tool
        inventing a finding.
        """
        page = int(SPAN[0], 16) >> 8
        r = subprocess.run([sys.executable, os.path.join(HERE,
                                                         "computed_dptr_sites.py"),
                            FIRMWARE, "--page", "0x%02X" % page, "--csv"],
                           capture_output=True, text=True, cwd=REPO)
        self.assertEqual(r.returncode, 0, r.stderr)
        computed = rows_of(r.stdout.encode())
        self.assertTrue(computed, "the other tool finds no computed site")
        reported = {s for row in ROWS for s in row["page_site"].split(";") if s}
        self.assertTrue(reported, "no row reports a reached page")
        for site in reported:
            region, _, addr = site.partition(":")
            runtime = int(addr, 16)
            match = [c for c in computed
                     if c["region"] == region
                     and c["runtime"] == "0x%04X" % runtime]
            self.assertTrue(match, "%s is not a site that tool reports" % site)
            for row in ROWS:
                if site in row["page_site"].split(";"):
                    self.assertIn(match[0]["xaddr"], row["page_site_cell"],
                                  row["addr"])


class ReadOnly(unittest.TestCase):
    """The tool writes nothing."""

    def test_a_run_leaves_the_committed_tree_byte_identical(self):
        """Over the committed files this tool's output is a product of.

        Not "it printed nothing to stderr": the property is about the tree, so
        every committed byte is compared before and after a run of both modes.
        A tool that wrote its CSV in place would pass every other case in this
        suite and fail this one, which is the only place the claim is checked.
        """
        watched = [TABLE, REGISTERS, os.path.join(EC, "annotations",
                                                   "ghidra-functions.csv")]
        before = {}
        for path in watched:
            with open(path, "rb") as f:
                before[path] = f.read()
        self.assertEqual(run_tool(FIRMWARE, *SPAN, "--csv").returncode, 0)
        self.assertEqual(run_tool(FIRMWARE, *SPAN).returncode, 0)
        for path in watched:
            with open(path, "rb") as f:
                self.assertEqual(f.read(), before[path], path)

    def test_the_csv_mode_writes_the_table_to_stdout_and_nowhere_else(self):
        """The committed table's bytes are what reaches stdout.

        `--csv` is the mode `--check` compares, so what it emits and what it
        compares have to be the same bytes; capturing them as bytes rather than
        text is what the csv module's own CRLF terminator requires, and
        universal-newline translation would silently compare a different thing.
        """
        self.assertEqual(GENERATED, table_bytes())
        self.assertTrue(GENERATED.endswith(b"\r\n"))


if __name__ == "__main__":
    unittest.main()
