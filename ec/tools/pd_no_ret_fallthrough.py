def sites_str(sites):
    """A `self_sites` cell as prose. The cell itself is `;`-separated because
    the csv module would quote a comma, and a quoted column in a census a
    reader greps is a worse trade than one separator nobody has to unescape."""
    return ", ".join(sites.split(";")) if sites else "nothing"


