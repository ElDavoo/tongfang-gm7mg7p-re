def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("firmware", nargs="?", default=FIRMWARE,
                    help="raw EC firmware image (default: the committed one)")
    ap.add_argument("--csv", action="store_true",
                    help="write one row per candidate on stdout")
    ap.add_argument("--check", action="store_true",
                    help="regenerate ../annotations/pd-no-ret-fallthrough.csv "
                         "and diff it")
    ap.add_argument("--self-test", action="store_true",
                    help="assert the pair's bytes, the two arms, the entry-site "
                         "census, the de-duplication and the two path/join "
                         "misreadings against the committed tree")
    ap.add_argument("--limit", type=int, default=None,
                    help="print at most N rows of the table (the CSV has them "
                         "all)")
    args = ap.parse_args(argv)

    with open(args.firmware, "rb") as f:
        d = f.read()
    off, magic = PD_MARKER
    if d[off:off + len(magic)] != magic:
        print(f"no {magic.decode()!r} marker at file 0x{off:05X} -- this is "
              f"not the image the recorded counts were taken from",
              file=sys.stderr)
        return 1
    pd = d[PD_BASE:PD_BASE + PD_LEN]

    _starts, listings, tails = read_listings()
    index = load_index()
    ann = load_annotations()
    rows, dec, byts = survey(pd, index, listings, tails, ann)

    if args.self_test:
        return self_test(pd, rows, dec, byts, index, listings, tails, ann)

    if args.csv:
        write_csv(rows)
        return 0

    if args.check:
        return check_table(csv_table(rows), OUT_CSV)

    print_arms(rows)
    print_table(rows, args.limit)
    print_sites(rows, dec, byts)
    print_answer(rows, pd)
    return 0


if __name__ == "__main__":
    sys.exit(main())
