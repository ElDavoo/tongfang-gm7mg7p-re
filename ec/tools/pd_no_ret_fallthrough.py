#!/usr/bin/env python3
"""Classify the `pd` listings whose "no ret" comment may be a function-boundary
artefact, and settle what `pd` 0x34EF actually does.

`ec/annotations/ghidra-functions.csv`'s `pd,34EF` row reads `set_dptr_0424`
with `type=unresolved` and the comment "A single `mov DPTR,#0x424` with no
ret, so the pointer's use is not decoded here." The three bytes it names are
the whole listing, and the next address is not a gap: `pd/34F2.asm` starts
`mov B,#0x60` and is a listing in its own right. So the row's clause is a
statement about where Ghidra's export put a function boundary, not about
where the code returns, and this tool measures which rows that is true of.

**The predicate that finds 0x34EF is the *byte* arm, and the predicate the
issue names is the *clause* arm. They are different questions and both are
printed.** The clause arm is a regex over the comment text -- a match on
prose, so a row whose comment happens not to carry the clause is invisible to
it and a row that does is in it whatever its bytes say. The byte arm is a
decode: the listing's last instruction is neither a return nor a transfer of
control, so control leaves the listing by falling past its end. The family is
the byte arm intersected with "`addr + size` is another listing's entry",
which is the part that makes the fall-through *into a boundary* rather than
off the end of the export.

**Three of the figures the issue was filed with do not reproduce, and the
tool's own counts are what the write-up quotes.** Its filter -- take the next
address as `addr + listing-index.csv`'s `size`, decode one instruction there,
keep the rows whose comment carries a "not decoded here" or "no ret" clause
and whose successor begins a `ljmp`/`jmp`/`sjmp`/`ajmp` -- finds four rows on
the committed tree, and 0x34EF is not one of them: 0x34F2 begins
`mov B,#0x60` and the `ljmp` is an instruction later. The byte arm is the
predicate that does contain 0x34EF. Its `198`-row clause population and the
`80` rows the clause arm and the byte arm agree on are the tool's, printed
with the predicate beside each so a reader can re-derive or reject them.

**`pd,34F2` is not merely 0x34EF's tail -- it is `lcall`ed in its own right
at 0x6782**, in the same listing `pd,6673` that holds the `lcall 0x34EF` at
0x67E0. So the pair is two entries sharing a tail rather than one routine
split by a function boundary, and that is what decides 0x34EF's verdict
below. `pd,3632`/`pd,3635` are the same shape (`lcall 0x3635` at 0x44A1
against `lcall 0x3632` at 0x8D50), which is a half-statement in `pd,3632`'s
existing comment rather than a licence to merge the two rows; that row is not
this tool's to edit and is not edited here.

**The entry census is a byte scan over the whole 64 KiB, de-duplicated by
site address, and it is `not found by this method` in both directions.** A
byte pattern cannot tell code from data, so a site it finds may be an operand
byte, and a target it does not find may still be reached by a paged or
relative form or from a byte the export never covers. The de-duplication is
not a nicety: a per-listing walk over the listings' own spans counts the 26
`lcall`/`ljmp` sites in 0x4C12-0x4D18 twice, because `pd/4D6F.asm` spans
0x4A12-0x4E58 and carries its own rows at those addresses *and* they are the
subject of `pd/4C12.asm`, `pd/4C19.asm`, `pd/4C20.asm` and `pd/4C27.asm`. One
address, two listings, one site -- and a census that reported 2066 where the
image holds 2040 in those spans would be wrong by a number it could not
explain.

**The two populations of *entry sites* are reported together and never
exchanged for one another.** The byte scan is the wide half; a walk over the
committed listings' own decoded instructions is the narrow one, and it is the
narrow one that assigns a verdict, because a decoded instruction cannot be an
operand byte. Where the two differ the row is still a candidate, per
`pd_entry_forms.py`'s standing rule and `CLAUDE.md`'s: a listing-scanned
absence is not *absent*.

Usage:
    python3 pd_no_ret_fallthrough.py
    python3 pd_no_ret_fallthrough.py --self-test
    python3 pd_no_ret_fallthrough.py --csv > ../annotations/pd-no-ret-fallthrough.csv
    python3 pd_no_ret_fallthrough.py --check

`../annotations/pd-no-ret-fallthrough.csv` is generated by the third of those
and held to the tree by the fourth, the arrangement `pd_entry_forms.py` and
`ec/annotations/pd-image.md` §0 record. It is **not registered in any gate**:
`.github/scripts/agent-gates.sh` is a pipeline file and this branch's token
has no `workflow` scope, so a gate call is a human's change. This tool is
instead runnable, cited standalone, and covered by `bash tools/run-tests.sh`'s
`test_*.py` glob.
"""
