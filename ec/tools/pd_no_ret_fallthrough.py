def read_listings():
    """(starts, {address: (bytes, text, file)}, {listing head: (first, last)})
    for the committed pd `.asm` files, over every instruction line rather than
    the listing's own extent.

    `pd_entry_forms.py`'s reader, kept so the two tools cannot disagree about
    what a committed listing says. Four committed filenames disagree with
    their first instruction (`0B85.asm` begins at 0x0B51, `4D6F.asm` at
    0x4A12 and two more), so every address is carried from the line and never
    from the file name -- and the third return is keyed on the listing's own
    *first instruction*, which is the one address a listing states and the
    only one `contiguous()` and the verdicts can be measured against."""
    out, tails = {}, {}
    for name in sorted(os.listdir(LISTINGS)):
        if not name.endswith(".asm"):
            continue
        head = last = None
        with open(os.path.join(LISTINGS, name), errors="replace") as f:
            for line in f:
                m = LINE_RE.match(line)
                if not m:
                    continue
                a = int(m.group(1), 16)
                out[a] = (
                    tuple(int(b, 16) for b in m.group(2).split() if b != "-"),
                    m.group(3).rstrip(), f"{PROGRAM}/{name}")
                if head is None:
                    head = a
                last = (out[a], a)
        if head is not None:
            tails[head] = (out[head], last)
    return sorted(out), out, tails


def load_index():
    """{listing file: row} for the pd rows of `listing-index.csv`, keyed on
    the `out_file` column rather than on `addr`.

    The `out_file` key is load-bearing and the `addr` column is not usable
    here: four committed pd index rows name an address that is not their
    listing's first instruction (`pd/4D6F.asm` holds 0x4A12-0x4E58 and is
    indexed at 0x4D6F, `pd/0B85.asm` and two more), so a join on `addr`
    silently drops four rows and reports a family that is four short of what
    the listings hold. `out_file` is a 1:1 match for every committed pd
    listing, and it is the column that says which file the row is about.

    The `size` column is read as the next address's offset and never as the
    listing's extent. That is right for the question here -- a row whose
    successor is another listing's entry is *by construction* contiguous with
    it -- and it is the reading `pd_entry_forms.py` records as a trap for a
    listing that is *not* contiguous, which is why `contiguous()` is measured
    per row below rather than assumed."""
    with open(INDEX_CSV, newline="") as f:
        return {r["out_file"]: r
                for r in csv.DictReader(f) if r["program"] == PROGRAM}


def load_annotations():
    """{address: row} for the pd rows of `ghidra-functions.csv`, with the
    address column normalised on the way in."""
    with open(ANNOTATIONS, newline="") as f:
        return {norm_addr(r["addr"]): r
                for r in csv.DictReader(f) if r["scope"] == PROGRAM}


def contiguous(listings, tails, addr):
    """Whether the listing beginning at `addr` covers its own bytes with no
    hole, from `addr` to the end of its last instruction.

    Measured rather than read off `size`, and asserted for `pd,34EF` in
    `--self-test`: the successor of a non-contiguous listing is not where
    `addr + size` says, so a "falls through into the next listing" reading
    would be an artefact of the index on exactly the rows where the export is
    already known to be a function-boundary guess. `pd_entry_forms.py` records
    the same trap for `pd,E2E4`, whose 28 instruction bytes are spread over a
    63-byte span."""
    _first, (last, stop) = tails[addr]
    if not last[0]:
        return False
    end = addr
    for a in sorted(listings):
        if a < addr:
            continue
        if a > stop:
            break
        if a > end:
            return False
        end = a + len(listings[a][0])
    return end == stop + len(last[0])


