sys.path.insert(0, HERE)

from disasm8051 import (OPCODE_LEN, REL_OPCODES, mnemonic,            # noqa: E402
                        paged_target, relative_target)
from trace_xdata_refs import PD_MARKER, offset_for_runtime             # noqa: E402

FIRMWARE = os.path.join(EC_DIR, "firmware", "GMxMGxx_11.800")
LISTINGS = os.path.join(EC_DIR, "decompiled", "pd")
INDEX_CSV = os.path.join(EC_DIR, "decompiled", "listing-index.csv")
ANNOTATIONS = os.path.join(EC_DIR, "annotations", "ghidra-functions.csv")
OUT_CSV = os.path.join(EC_DIR, "annotations", "pd-no-ret-fallthrough.csv")

PROGRAM = "pd"
PD_REGION = "pd-image"
PD_LEN = 0x10000

# The pd image's base in the dump, taken from `trace_xdata_refs.REGIONS` rather
# than written out again, because `PD_MARKER` is the *marker's* file offset and
# not the image's: the marker sits 0x40 bytes into a program that starts at
# 0x20000. A runtime address in this program is the offset from here, and using
# the marker instead reads 0x40 bytes early in every one of the 64 KiB -- which
# still decodes, at the wrong address, which is the worst of both.
PD_BASE = offset_for_runtime(0, PD_REGION)

RET = 0x22
RETI = 0x32
# Both returns, because both leave the listing and the question is what leaves
# the listing. A listing ending in `reti` falls into nothing whatever its
# comment says, and reading only 0x22 would put seven rows into the family for
# a reason that has nothing to do with the boundary.
RETURNS = frozenset((RET, RETI))

# The absolute transfer opcodes, and the paged and indirect families beside
# them. The paged pair is keyed on `op & 0x1F` exactly as `disasm8051.mnemonic`
# keys it, and the indirect `jmp @A+DPTR` is spelled out because neither
# `REL_OPCODES` nor the paged test reaches it. This tool enumerates no
# encoding of its own beyond that one: a fourth spelling of the map is a fourth
# thing to keep in step with the shared decoder.
ABS_OPCODES = frozenset((0x02, 0x12))
PAGED_OPCODES = frozenset(op for op in range(256) if (op & 0x1F) in (0x01, 0x11))
INDIRECT_OPCODES = frozenset((0x73,))
TRANSFER_OPCODES = frozenset(REL_OPCODES) | ABS_OPCODES | PAGED_OPCODES | INDIRECT_OPCODES

# The clause arm, over the annotation comment. Two clauses and not one because
# they are two different sentences a human wrote, and the issue names both: a
# listing whose pointer use is "not decoded here" is saying the same thing
# about the same boundary as one whose last instruction is "no ret". This is
# a text match over prose and the tool labels it as such wherever it prints a
# figure derived from it -- it is not a decode and settles nothing on its own.
CLAUSE_RE = re.compile(r"not decoded here|no ret", re.IGNORECASE)

# An instruction line is `<4 hex addr> <up to 3 byte columns, '-' padded>
# <mnemonic> <operands>`, and only the first column is the address. Anchored
# at the start of the line for the reason `pd_entry_forms.py` gives: the
# operand text carries four-hex-digit branch targets of its own, so an
# unanchored regex matches a target as readily as an address.
LINE_RE = re.compile(
    r"^([0-9A-Fa-f]{4})\s+((?:[0-9a-f]{2}|-)\s+(?:[0-9a-f]{2}|-)\s+"
    r"(?:[0-9a-f]{2}|-))\s+(\S.*)$")

# The `ghidra-functions.csv` address column is spelled two ways in one file,
# and an un-normalised join silently drops half the table rather than failing.
# `--self-test` asserts both spellings are present, because the failure this
# guards is silent and wrong rather than loud.
ADDR_PREFIX_RE = re.compile(r"^0[xX]")

VERDICTS = ("shared-tail", "falls-through-unentered", "boundary-wrong")

# What each verdict means, in the tool's own words rather than the write-up's.
# A reader who has the CSV and not the prose needs these.
VERDICT_GLOSS = {
    "shared-tail":
        "the successor is itself a transfer target, so the two listings are two "
        "entries over one tail rather than one routine cut in half",
    "falls-through-unentered":
        "the successor is contiguous and nothing transfers to it, so the two "
        "listings are one routine's worth of code with the boundary inside it",
    "boundary-wrong":
        "nothing transfers to the row's own address either: it is reached only "
        "by falling in from the previous listing, so the boundary is misdrawn "
        "and the real entry is elsewhere",
}

COLUMNS = ["addr", "name", "type", "size", "successor", "succ_name",
           "succ_size", "succ_first", "last_insn", "self_sites", "succ_sites",
           "byte_succ_sites", "verdict", "clause", "in_byte_arm"]

HEX_COLUMNS = {"addr": 4, "successor": 4}


def norm_addr(addr):
    """`addr` as an int, from either spelling the annotation CSVs use.

    `ghidra-functions.csv` carries `34EF` on some rows and `0x0003` on others,
    so a join done on the string would match the second half and quietly miss
    the first -- and the miss is silent, which is the whole reason this
    function exists rather than an `int(addr, 16)` at the call site.
    """
    return int(ADDR_PREFIX_RE.sub("", addr.strip()), 16)


