# The answer, as `--self-test` asserts it. Every figure is a property of the
# committed tree, re-derived here from the image and the committed tables
# rather than quoted, so a regenerated index that moved one of them fails
# instead of being held.
ORACLE = {
    # The two arms. Held apart on purpose: they are different questions, and
    # a single "candidates" figure would hide which predicate produced it.
    "clause_arm": 198,
    "byte_arm": 95,
    "both_arms": 80,
    "listings": 541,
    # The entry-site census, both populations.
    "byte_sites": 7266,
    "byte_targets": 1866,
    "listing_sites": 1923,
    "listing_targets": 1038,
    # The pair, in bytes rather than in counts.
    "pair": (0x34EF, 3, 0x34F2, 6),
    "pair_span": 9,
    "ret_at": 0x10C7,
    "call_34ef": (0x67E0, 0xCB40),
    "call_34f2": (0x6782,),
    # The double-count the de-duplication exists for.
    "overlap_span": (0x4C12, 0x4D18),
    "overlap_sites": 26,
    "overlap_sites_dedup": 2040,
}


def span_walk(pd, listings, tails):
    """(total, distinct) entry sites over every committed listing's own span,
    walked position by position -- the per-listing walk `--self-test` shows
    over-counting. Never used to decide anything; it exists so the
    de-duplication has a measurement behind it rather than a claim."""
    seen = {}
    for head in sorted(tails):
        (last, last_addr) = tails[head][1]
        for i in range(head, last_addr + len(last[0])):
            if pd[i] in ABS_OPCODES:
                seen[i] = seen.get(i, 0) + 1
    return sum(seen.values()), len(seen)


def self_test(pd, rows, dec, byts, index, listings, tails, ann) -> int:
    bad = 0

    def check(ok, text):
        nonlocal bad
        if not ok:
            bad += 1
        print(f"  {'ok  ' if ok else 'FAIL'}  {text}")

    print("pd_no_ret_fallthrough.py --self-test")

    fam = family(rows)
    cl = clause_rows(rows)
    both = [r for r in fam if r["clause"] == "yes"]

    check(len(cl) == ORACLE["clause_arm"],
          f"the clause arm is {ORACLE['clause_arm']} row(s) — a text match over "
          f"the comment, not a decode, and labelled as one wherever it is "
          f"printed")
    check(len(fam) == ORACLE["byte_arm"],
          f"the byte arm is {ORACLE['byte_arm']} row(s): the listing's last "
          f"instruction is neither a return nor a transfer and `addr + size` is "
          f"another listing's entry")
    check(len(both) == ORACLE["both_arms"] and 0x34EF in {r["addr"] for r in both},
          f"the two arms agree on {ORACLE['both_arms']} row(s), and `pd,34EF` is "
          f"one of them — so the byte arm is the predicate that finds it and the "
          f"issue's stated filter is not")

    # The two families the two arms produce are genuinely different sets, and
    # the byte arm is strictly the wider: a row whose comment does not carry
    # the clause is in it anyway, which is the whole argument for a decode arm
    # beside a text arm.
    check(len({r["addr"] for r in fam} - {r["addr"] for r in cl}) > 0,
          f"and the byte arm is not a subset of the clause arm: "
          f"{len(fam) - len(both)} row(s) qualify on their bytes while their "
          f"comment carries neither clause, which is what a text filter cannot "
          f"see")

    # The pair, on bytes.
    a, sa, b, sb = ORACLE["pair"]
    check(pd[a:a + sa] == b"\x90\x04\x24" and pd[b:b + sb] == b"\x75\xf0\x60\x02\x10\xbc",
          f"the bytes: `pd,0x{a:04X}` is `90 04 24` and `pd,0x{b:04X}` is "
          f"`75 f0 60 / 02 10 bc`, contiguous, so the span from 0x{a:04X} to "
          f"0x{a + ORACLE['pair_span'] - 1:04X} is {ORACLE['pair_span']} bytes "
          f"and not 0x{sb:02X} — {sb} is 0x{b:04X}'s own size")
    check(int(index[f"{PROGRAM}/{a:04X}.asm"]["size"]) == sa
          and int(index[f"{PROGRAM}/{b:04X}.asm"]["size"]) == sb,
          f"and `listing-index.csv` records size={sa} and size={sb} for the "
          f"pair, which is where the successor address comes from")
    check(pd[ORACLE["ret_at"]] == RET,
          f"`pd,10BC` ends in 0x{RET:02X} (`ret`) at "
          f"0x{ORACLE['ret_at']:04X}, so control does return to the address "
          f"after whichever `lcall` was made")

    # The two entries, and the claim the verdict rests on.
    call_a = tuple(int(s, 16) for s in
                   next(r for r in rows if r["addr"] == a)["self_sites"].split(";"))
    call_b = tuple(int(s, 16) for s in
                   next(r for r in rows if r["addr"] == a)["succ_sites"].split(";"))
    check(call_a == ORACLE["call_34ef"] and call_b == ORACLE["call_34f2"],
          f"`lcall 0x{a:04X}` is at "
          f"{', '.join('0x%04X' % s for s in call_a)} and `lcall 0x{b:04X}` is at "
          f"{', '.join('0x%04X' % s for s in call_b)} — every one a committed "
          f"instruction start, which is why the successor is a second entry and "
          f"not only 0x{a:04X}'s tail")
    check(next(r for r in rows if r["addr"] == a)["verdict"] == "shared-tail",
          f"so `pd,0x{a:04X}`'s verdict is `shared-tail`: two entries over one "
          f"tail, rather than one routine cut in half by the export")

    # The two populations, and the de-duplication behind the wide one.
    check(sum(len(v) for v in byts.values()) == ORACLE["byte_sites"]
          and len(byts) == ORACLE["byte_targets"],
          f"the byte scan finds {ORACLE['byte_sites']} `lcall`/`ljmp` site(s) "
          f"naming {ORACLE['byte_targets']} distinct target(s) — the wide half, "
          f"and every one of them a candidate, because a byte pattern cannot "
          f"tell code from data")
    check(sum(len(v) for v in dec.values()) == ORACLE["listing_sites"]
          and len(dec) == ORACLE["listing_targets"],
          f"the committed listings' own decoded instructions carry "
          f"{ORACLE['listing_sites']} site(s) naming {ORACLE['listing_targets']} "
          f"distinct target(s) — the narrow half, and the one verdicts are "
          f"assigned from")

    lo, hi = ORACLE["overlap_span"]
    total, distinct = span_walk(pd, listings, tails)
    covered = {a for a in listings if lo <= a <= hi}
    check(len(covered) > 1 and total == ORACLE["overlap_sites_dedup"]
          + ORACLE["overlap_sites"] and distinct == ORACLE["overlap_sites_dedup"],
          f"the de-duplication: a per-listing walk over the listings' own spans "
          f"finds {total} site(s) where the spans hold {distinct}, because "
          f"0x{lo:04X}-0x{hi:04X} is inside `pd/4D6F.asm`'s span *and* the "
          f"subject of {len(covered)} other listings — {ORACLE['overlap_sites']} "
          f"sites counted twice, and a census reporting {total} would be wrong "
          f"by a figure it could not explain")

    # The two silent misreadings, asserted rather than described.
    prefixed = [a for a, r in ann.items() if r["addr"].lower().startswith("0x")]
    bare = [a for a, r in ann.items() if not r["addr"].lower().startswith("0x")]
    raw = [int(r["addr"], 16) for r in csv.DictReader(
        open(ANNOTATIONS, newline="")) if r["scope"] == PROGRAM]
    check(prefixed and bare and len(prefixed) + len(bare) == len(ann)
          and sorted(raw) == sorted(ann),
          f"the join: `ghidra-functions.csv` spells its address column two ways "
          f"— {len(prefixed)} `pd` row(s) `0x`-prefixed and {len(bare)} bare — "
          f"and `int(addr, 16)` reads only the first, dropping the other "
          f"{len(bare)} silently rather than failing, so the column is "
          f"normalised on the way in and the two readings agree here")

    head_off = offset_for_runtime(a, PD_REGION)
    check(head_off == PD_BASE + a and head_off != PD_MARKER[0],
          f"the path index: runtime 0x{a:04X} is file 0x{head_off:05X}, so the "
          f"listing is {PROGRAM}/{a:04X}.asm — the base is 0x{PD_BASE:05X} and "
          f"not `PD_MARKER`'s 0x{PD_MARKER[0]:05X}, which is the marker 0x40 "
          f"bytes *inside* the image, and using it decodes cleanly at the "
          f"wrong address")

    check(pd[a:a + ORACLE["pair_span"]] != d_full(pd)[a:a + ORACLE["pair_span"]],
          f"and a pd runtime address is not a file offset: slicing the dump at "
          f"[0x{a:04X}:0x{a + ORACLE['pair_span']:04X}] reads the main EC's "
          f"common area, which is a different program and also decodes")

    print()
    print("self-test FAILED" if bad else "self-test passed")
    return 1 if bad else 0


def d_full(pd):
    """The bytes at 0x34EF-0x34F7 *of the main EC's common area*, as the last
    check needs them: the whole dump sliced at the pd runtime address, which is
    the misreading being ruled out. Re-read from the file rather than carried
    in, so the check is against the committed image and not against itself."""
    with open(FIRMWARE, "rb") as f:
        whole = f.read()
    return whole[:PD_LEN]


