def transfer_target(d, a, op):
    """The address a transfer instruction at `a` names, or None.

    The three encodings come from `disasm8051`, which is where each one's
    arithmetic lives: the 16-bit operand of 0x02/0x12 stored high byte first,
    the 2 KiB page an `ajmp`/`acall` computes from the *next* PC, and the rel8
    displacement measured from the instruction's last byte. Returns None for
    an opcode that is not a transfer, which is how one walk covers the whole
    listing without a second reader of the same map."""
    if op in ABS_OPCODES:
        return (d[a + 1] << 8) | d[a + 2]
    if (op & 0x1F) in (0x01, 0x11):
        return paged_target(op, d[a + 1], a)
    if op in REL_OPCODES:
        return relative_target(op, d[a + OPCODE_LEN[op] - 1], a)
    return None


def byte_sites(pd):
    """{target: [site, ...]} for every position in the image whose bytes spell
    an `lcall` or `ljmp`, de-duplicated by site address.

    Keyed on the site address, not on the listing it was found through, and
    that is the load-bearing part: a per-listing walk over the listings' own
    spans finds 26 sites in 0x4C12-0x4D18 twice, because `pd/4D6F.asm` spans
    0x4A12-0x4E58 and holds rows at those addresses while `pd/4C12.asm`,
    `pd/4C19.asm`, `pd/4C20.asm` and `pd/4C27.asm` are the same bytes under
    other names. A byte scan walks each position once by construction, so the
    de-duplication here is what makes the two halves comparable.

    A byte pattern cannot tell code from data, so every site is a candidate:
    an operand byte of a longer instruction spells one too."""
    out = {}
    for i in range(len(pd) - 2):
        if pd[i] in ABS_OPCODES:
            out.setdefault((pd[i + 1] << 8) | pd[i + 2], []).append(i)
    return out


def listing_sites(pd, listings):
    """{target: [site, ...]} over the committed listings' own *decoded*
    instructions.

    The narrow half of the pair `byte_sites()` and this report, and the one
    that assigns a verdict: a site here is an instruction start a committed
    listing states, so it cannot be an operand byte. It is also the half that
    cannot see a transfer in a committed gap, which is why the two are
    reported together and neither is counted as corroboration of the other."""
    out = {}
    for a in sorted(listings):
        raw = listings[a][0]
        if not raw:
            continue
        t = transfer_target(pd, a, raw[0])
        if t is not None:
            out.setdefault(t, []).append(a)
    return out


# --------------------------------------------------------------------------
# The census
# --------------------------------------------------------------------------

def verdict_for(self_sites, succ_sites):
    """`shared-tail`, `falls-through-unentered` or `boundary-wrong`.

    Decided on the decoded (listing) populations, never on the byte scan. The
    byte scan finds a `lcall`-shaped byte pair naming almost any address in
    the image, so on that population `shared-tail` is the answer for nearly
    every row and the verdict stops discriminating; the decoded one separates
    0x34EF from 0x0012 on the bytes rather than on the accident that some
    operand pair happens to spell `12 00 13`."""
    if not succ_sites:
        return "falls-through-unentered"
    if not self_sites:
        return "boundary-wrong"
    return "shared-tail"


def is_clause_arm(ann_row):
    """Whether the row's comment carries one of the two clauses. `True` for a
    row with no annotation at all would be a claim about the program, so it is
    `False` and the family is the byte arm's membership that carries the
    weight; `--self-test` holds both arms apart on the counts."""
    return ann_row is not None and CLAUSE_RE.search(ann_row["comment"]) is not None


def survey(pd, index, listings, tails, ann):
    """One pass, so the report, `--csv` and `--check` cannot disagree.

    Every committed listing is classified, not only the ones that match, so
    `--check` fails on a listing that has *become* a candidate rather than on
    one that has stopped being one -- the failure mode a census that only ever
    reports its members cannot have. The walk is over the listings and the
    index is consulted per listing file, for the reason `load_index()` gives.

    The verdict and the byte-arm test both read the *opcode*, which is the
    first byte of the listing's own last instruction -- not the whole byte
    tuple, and not the mnemonic text. A tuple is never in `RETURNS`, so
    comparing the tuple would put every listing in the family and report a
    number no reader could account for."""
    dec = listing_sites(pd, listings)
    byts = byte_sites(pd)
    rows = []
    for head in sorted(tails):
        first, (last, _last_addr) = tails[head]
        row = index.get(first[2])
        if row is None:
            continue
        succ = head + int(row["size"])
        succ_row = index.get(f"{PROGRAM}/{succ:04X}.asm")
        self_sites = dec.get(head, [])
        succ_sites = dec.get(succ, [])
        in_byte_arm = (last[0][0] not in RETURNS
                       and last[0][0] not in TRANSFER_OPCODES
                       and succ_row is not None
                       and contiguous(listings, tails, head))
        ann_row = ann.get(head) or ann.get(norm_addr(row["addr"]))
        rows.append({
            "addr": head,
            "name": (ann_row or {}).get("name", ""),
            "type": (ann_row or {}).get("type", ""),
            "size": int(row["size"]),
            "successor": succ,
            "succ_name": succ_row["name"] if succ_row else "",
            "succ_size": int(succ_row["size"]) if succ_row else 0,
            "succ_first": mnemonic(pd, succ, succ) if succ < PD_LEN else "",
            "last_insn": last[1],
            "self_sites": ";".join(f"0x{s:04X}" for s in self_sites),
            "succ_sites": ";".join(f"0x{s:04X}" for s in succ_sites),
            "byte_succ_sites": ";".join(f"0x{s:04X}" for s in byts.get(succ, [])),
            "verdict": (verdict_for(self_sites, succ_sites) if in_byte_arm
                        else ""),
            "clause": "yes" if is_clause_arm(ann_row) else "no",
            "in_byte_arm": "yes" if in_byte_arm else "no",
        })
    return rows, dec, byts


def family(rows):
    """The rows in the byte arm, in address order."""
    return [r for r in rows if r["in_byte_arm"] == "yes"]


def clause_rows(rows):
    """The rows in the clause arm."""
    return [r for r in rows if r["clause"] == "yes"]


