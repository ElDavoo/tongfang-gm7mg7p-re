#!/usr/bin/env python3
"""Offline checks for bank_call_regions.py and the committed table it writes.

`docs/findings/bank-call-regions-csv.md` is the argument; this holds the file it
argues for. Nothing here reads firmware beyond re-deriving from it, opens a
capture, or needs an EC: the two inputs are committed files, which is why the
fold in `docs/ci/agent-gates-disasm8051-self-test.patch` puts the tool in the
cheap tier.

**`--check` is driven in both directions.** A green run over the committed file
proves only that the file agrees with itself; the four doctored copies below are
what make the check mean something, and each was run with its mutation in place
before this suite was written, so every one of them is known to go red. A
tampered `entry_aligned` cell, a tampered `region_name`, a dropped row and a
re-ordered row, plus a **missing** file, which must fail rather than be created
— a `--check` that writes the file it is checking decides what the file says,
which is the arrangement `bucket_c_codemap.py` records as the one other
`--check` mode here deliberately refuses.

**`entry_aligned` is re-derived from the row's own two columns** in every row
that populates it, so the cell cannot be a hand-written value that happens to
agree with the YAML. That is what the `region_stride` and `entry_offset`
columns are for: a reader with one row and no YAML can check the answer.

**The oracle is transcribed here, not read back from the tool.** From
`docs/findings/ec-data-regions.md` §"The payoff": `0x055DC` and `0x06E83` are
entry-aligned, `0x06952` sits inside `common-690b-ff-triples` 71 bytes in and is
not, `0x00381` sits inside `common-032f-ljmp-table` 82 bytes in and is not, and
`0x021C6` is outside every listed region. `0x00686` is here for the third
answer: it is inside a region, and its cell is empty because that region is
`inferred` and does not pose the question. A tool that graded its own map
against itself would pass whatever the map said.

**What is deliberately not asserted.** No case here says any site *is* or is not
a call, a table entry or a phantom — `converges_from()`'s own docstring says a
site everybody syncs onto is not thereby real, and the module docstring's §4c
sentence is the statement of it. What is asserted is a relation: that the file
is what the image and the YAML produce, that both `file_offset` sets are the
ones the two censuses already carry, that `entry_aligned` is re-derivable from
its own row, and that `write_csv()` in the sibling tool still carries no region
string — which is what `test_data_regions.py` asserts from its side, and is
restated here so this file's contract does not need that suite edited.
"""
import csv
import importlib.util
import inspect
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).parent
# bank_call_regions imports audit_call_targets and data_regions by bare module
# name, so the tool directory goes on the path before the module is loaded.
sys.path.insert(0, str(HERE))
spec = importlib.util.spec_from_file_location(
    'bank_call_regions', HERE / 'bank_call_regions.py')
bcr = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bcr)

FIRMWARE = str(HERE.parent / 'firmware' / 'GMxMGxx_11.800')
COMMITTED_CSV = HERE.parent / 'annotations' / 'bank-call-regions.csv'
TOOL = str(HERE / 'bank_call_regions.py')
ANNOTATIONS = HERE.parent / 'annotations'

# The oracle, transcribed from docs/findings/ec-data-regions.md "The payoff".
# `None` for region_name means outside every listed region. See the docstring.
ORACLE = (
    (0x055DC, 'common-055a8-be-words', 'yes'),
    (0x00381, 'common-032f-ljmp-table', 'no'),
    (0x06952, 'common-690b-ff-triples', 'no'),
    (0x06E83, 'common-6e7d-be-words', 'yes'),
    (0x021C6, None, ''),
    (0x00686, 'common-0656-address-table', ''),
)

# Phrases the header comment block has to carry. Short ones rather than whole
# sentences, so a rewrap is not a red run; what is being held is that the block
# exists and says these things, not the wording it says them in.
HEADER_PHRASES = (
    'generated by ec/tools/bank_call_regions.py',
    'THREE-valued',
    'region_confidence',
    'UNDEFINED there, not',
    'not the same absence as',
    'NEVER means "a call"',
    'read-by-hand',
    'inferred-unchecked',
    'is not proof its site is a table entry',
)


def committed_rows(path=COMMITTED_CSV):
    """The committed table as dicts, past the `#` header comment block."""
    text = Path(path).read_text()
    return list(csv.DictReader([ln for ln in text.splitlines(True)
                                if not ln.startswith("#")]))


def check_against(path):
    """`--check` over `path`, as a subprocess. Returns the CompletedProcess."""
    return subprocess.run(
        [sys.executable, TOOL, FIRMWARE, "--check", "--csv-path", str(path)],
        capture_output=True, text=True)


class CheckTests(unittest.TestCase):
    """`--check`, driven in both directions: green on the tree, red on each edit.

    The doctored copies are written into a scratch directory rather than over
    the committed file, so a red run here cannot leave the repository's own
    table tampered with for the next case.
    """

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)

    def test_the_committed_table_passes_its_own_check(self):
        result = check_against(COMMITTED_CSV)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def _doctored(self, edit):
        """A scratch copy of the committed table with `edit(lines)` applied."""
        lines = Path(COMMITTED_CSV).read_text().splitlines(True)
        edited = edit(list(lines))
        self.assertNotEqual(edited, lines,
                            'the mutation did not change anything, so a red '
                            'run below would be testing the editor')
        path = Path(self.tmp.name) / 'doctored.csv'
        path.write_text(''.join(edited))
        return path

    @staticmethod
    def _rewrite_row(lines, match, column, value):
        """The one row whose `file_offset` is `match`, with `column` set.

        Rewritten through `csv.reader` rather than by string surgery, so the
        mutation lands in the named column even though `earlier_record`-style
        free text is not what this file carries -- a `str.replace` would be a
        second thing to get right, and it would silently do nothing to a column
        whose value does not occur, which is the passing-vacuously case.
        """
        header = next(csv.reader([next(ln for ln in lines
                                      if ln.startswith('file_offset,'))]))
        i = header.index(column)
        out = list(lines)
        for n, line in enumerate(out):
            if not line.startswith(match):
                continue
            cells = next(csv.reader([line]))
            cells[i] = value
            out[n] = ",".join(cells) + "\n"
            return out
        raise AssertionError(f'no row at {match}')

    def test_a_tampered_entry_aligned_cell_is_refused(self):
        path = self._doctored(lambda ls: self._rewrite_row(
            ls, '0x055DC,', 'entry_aligned', 'no'))
        result = check_against(path)
        self.assertEqual(result.returncode, 1)
        self.assertIn('0x055DC', result.stderr)

    def test_a_tampered_region_name_is_refused(self):
        path = self._doctored(lambda ls: self._rewrite_row(
            ls, '0x055DC,', 'region_name', 'common-ffff-nonesuch'))
        result = check_against(path)
        self.assertEqual(result.returncode, 1)
        self.assertIn('common-ffff-nonesuch', result.stdout + result.stderr)

    def test_a_dropped_row_is_refused(self):
        def drop(lines):
            out = list(lines)
            n = next(i for i, ln in enumerate(out) if ln.startswith('0x055DC,'))
            del out[n]
            return out
        result = check_against(self._doctored(drop))
        self.assertEqual(result.returncode, 1)

    def test_a_reordered_row_is_refused(self):
        def swap(lines):
            out = list(lines)
            n = next(i for i, ln in enumerate(out) if ln.startswith('0x055DC,'))
            out[n], out[n + 1] = out[n + 1], out[n]
            return out
        result = check_against(self._doctored(swap))
        self.assertEqual(result.returncode, 1)

    def test_a_family_outside_the_two_populations_is_refused(self):
        """Both halves report it, and the join does not raise out of it.

        `family` is what `--check`'s join reads to decide which census to compare
        against, so a third value has no population to belong to. The refusal
        and the join's own message are separate code paths and a mutation has to
        reach both.
        """
        path = self._doctored(lambda ls: self._rewrite_row(
            ls, '0x055DC,', 'family', 'relative'))
        result = check_against(path)
        self.assertEqual(result.returncode, 1)
        self.assertIn('neither census', result.stderr)
        self.assertIn("'relative'", result.stderr)

    def test_a_missing_file_fails_and_is_not_created(self):
        path = Path(self.tmp.name) / 'never-written.csv'
        result = check_against(path)
        self.assertEqual(result.returncode, 1)
        self.assertIn('does not exist', result.stderr)
        self.assertFalse(path.exists(),
                         '--check created the file it was checking, which is '
                         'what it exists to refuse')

    def test_check_and_self_test_are_refused_together(self):
        result = subprocess.run(
            [sys.executable, TOOL, FIRMWARE, "--check", "--self-test"],
            capture_output=True, text=True)
        self.assertEqual(result.returncode, 2)
        self.assertIn('four different claims', result.stderr)

    def test_a_bare_run_is_refused_rather_than_writing_something(self):
        """No mode means no claim to make, so the tool says so.

        `data_regions.py`'s `ap.error` rather than a default that prints: a bare
        run that silently emitted the table would be a fourth way of asking the
        same question, and one a reader could mistake for `--csv`.
        """
        result = subprocess.run(
            [sys.executable, TOOL, FIRMWARE], capture_output=True, text=True)
        self.assertEqual(result.returncode, 2)
        self.assertIn('give --write, --check, --self-test or --csv',
                      result.stderr)
        self.assertEqual(result.stdout, '')


class EntryAlignedTests(unittest.TestCase):
    """The cell is re-derivable from the row alone, and three-valued as stated."""

    def setUp(self):
        self.rows = committed_rows()

    def test_every_populated_cell_follows_from_its_own_two_columns(self):
        checked = 0
        for row in self.rows:
            if not row["entry_aligned"]:
                continue
            checked += 1
            self.assertEqual(
                row["entry_aligned"],
                "yes" if int(row["entry_offset"]) % int(row["region_stride"]) == 0
                else "no",
                f'{row["file_offset"]}: {row["entry_aligned"]} does not follow '
                f'from entry_offset {row["entry_offset"]} and region_stride '
                f'{row["region_stride"]}')
        self.assertGreater(checked, 0, 'no row populates entry_aligned, so '
                                       'this case cannot have failed')

    def test_an_empty_cell_with_a_region_only_where_the_grid_is_not_a_claim(self):
        empty = [r for r in self.rows if r["in_data_region"] == "yes"
                 and not r["entry_aligned"]]
        self.assertTrue(empty, 'no row has an empty entry_aligned inside a '
                               'region, so the three-valued cell is untested')
        for row in empty:
            self.assertNotEqual(row["region_confidence"], bcr.ALIGNABLE,
                                f'{row["file_offset"]} is empty on a '
                                f'{bcr.ALIGNABLE} region, where the cell is a '
                                f'claim the file does make')
        # And the converse: every read-by-hand region answers.
        for row in self.rows:
            if row["region_confidence"] == bcr.ALIGNABLE:
                self.assertIn(row["entry_aligned"], ("yes", "no"),
                              f'{row["file_offset"]} is {bcr.ALIGNABLE} and '
                              f'its cell is {row["entry_aligned"]!r}')

    def test_an_empty_cell_on_a_no_row_is_the_other_absence(self):
        """`in_data_region=no` and `yes`-with-empty are not the same absence.

        The three-valued cell is only meaningful because the two empties can be
        told apart from the row: one means no region was found and the question
        does not arise, the other that a region was found and the question is
        undefined for it. Both readings are also refused by `--check`, so a
        conflation cannot reach the file.
        """
        for row in self.rows:
            if row["in_data_region"] == "no":
                self.assertEqual(row["entry_aligned"], "")
                for column in ("region_name", "region_shape",
                               "region_confidence", "region_stride",
                               "entry_offset"):
                    self.assertEqual(row[column], "",
                                     f'{row["file_offset"]} is outside every '
                                     f'region but carries {column}')

    def test_the_oracle_from_the_findings_file(self):
        by_offset = {int(r["file_offset"], 16): r for r in self.rows}
        for off, region, aligned in ORACLE:
            with self.subTest(offset=off):
                row = by_offset.get(off)
                self.assertIsNotNone(row, f'0x{off:05X} is not in the file')
                self.assertEqual(row["region_name"], region or "")
                self.assertEqual(row["entry_aligned"], aligned)

    def test_no_cell_holds_a_python_value_written_as_a_string(self):
        """`str(None)` is the four letters `None`, not an empty cell.

        A region with a null stride is the case, and no committed region has
        one — `data_regions.py` refuses the combination outright — so this is
        what keeps a future `inferred-unchecked` entry from writing the string
        into a file where every other absent cell is empty. Driven over a
        scratch YAML rather than the committed one for the same reason the
        refusals use mutations: the point is the rule, not this dump.
        """
        import yaml
        regions = bcr.load_data_regions()
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / 'null-stride.yaml'
            path.write_text(yaml.safe_dump({"regions": [
                dict(r, stride=None, confidence="inferred-unchecked")
                if r["name"] == "common-055a8-be-words" else r
                for r in regions]}))
            built = bcr.rows(Path(FIRMWARE).read_bytes(), bcr.load_data_regions(
                str(path)))
        affected = [r for r in built if r["region_confidence"]
                    == "inferred-unchecked"]
        self.assertTrue(affected, 'the scratch YAML reached no row, so this '
                                  'case is testing nothing')
        for row in affected:
            self.assertEqual(row["region_stride"], "",
                             f'{row["file_offset"]}: a null stride rendered as '
                             f'{row["region_stride"]!r} rather than empty')
            self.assertEqual(row["entry_aligned"], "",
                             f'{row["file_offset"]}: a null stride answered '
                             f'the cell instead of leaving the question open')
        for row in built:
            for column, value in row.items():
                self.assertNotEqual(value, 'None',
                                    f'{row["file_offset"]}.{column} holds the '
                                    f'string "None"')

    def test_in_a_region_and_on_the_grid_are_different_answers(self):
        """The two questions the file exists to keep apart, on the real rows.

        `docs/findings/ec-data-regions.md` §"The payoff" argues the
        distinction from two named sites; this asserts the population carries
        both answers rather than only one, which is what a file with a single
        boolean could not do.
        """
        inside = [r for r in self.rows if r["in_data_region"] == "yes"]
        answered = [r for r in inside if r["entry_aligned"] in ("yes", "no")]
        self.assertIn("yes", {r["entry_aligned"] for r in answered})
        self.assertIn("no", {r["entry_aligned"] for r in answered},
                      'every answered row is entry-aligned, so the `no` half '
                      'of the cell is untested on this image')


class PopulationTests(unittest.TestCase):
    """Both `file_offset` sets are the censuses' own, as a join rather than a count.

    A literal here would be a value every census change had to edit, and the
    file would go red for a cause that has nothing to do with it. The
    relation moves when those files move, which is the property a count of the
    tree cannot have.
    """

    def setUp(self):
        self.rows = committed_rows()

    def _offsets(self, family):
        return {int(r["file_offset"], 16) for r in self.rows
                if r["family"] == family}

    def test_bucket_c_offsets_are_the_C_rows_of_bank_call_targets(self):
        with open(ANNOTATIONS / 'bank-call-targets.csv', newline="") as fh:
            census = {int(r["file_offset"], 16) for r in csv.DictReader(fh)
                      if r["bucket"] == "C"}
        self.assertEqual(self._offsets("bucket-c"), census)

    def test_paged_offsets_are_the_rows_of_the_paged_census(self):
        with open(ANNOTATIONS / 'bank-paged-call-targets.csv',
                  newline="") as fh:
            census = {int(r["file_offset"], 16)
                      for r in csv.DictReader(fh)}
        self.assertEqual(self._offsets("paged"), census)

    def test_every_row_is_one_of_the_two_families(self):
        self.assertEqual({r["family"] for r in self.rows}, set(bcr.FAMILIES))

    def test_the_key_is_strictly_increasing(self):
        """One sort key with no tie, which is what lets two branches both
        regenerate this file and merge in content rather than in prose.

        `family` is a column rather than part of the key because the two
        `file_offset` sets are disjoint by construction: a byte in
        `(0x02, 0x12)` has low five bits `0x02`/`0x12`, neither a paged opcode.
        """
        offsets = [int(r["file_offset"], 16) for r in self.rows]
        self.assertEqual(offsets, sorted(offsets))
        self.assertEqual(len(offsets), len(set(offsets)),
                         'two rows share a file_offset, so the key is not a key')


class SiblingContractTests(unittest.TestCase):
    """`write_csv()` still carries no region string, and the sibling does.

    `test_data_regions.py::test_audit_call_targets_leaves_write_csv_untouched`
    holds this from its own side. It is restated here so asserting it needs no
    edit to a shared suite -- and the point of the contract is precisely that a
    sibling lets it hold: the reason the column is not another one on
    `bank-call-targets.csv` is that `build_ec_decompile.py`'s
    `CALL_TARGET_COLUMNS` is asserted in a gate, and this file is the way to add
    the column without touching it.
    """

    def setUp(self):
        self.audit = importlib.import_module('audit_call_targets')

    def test_write_csv_carries_no_region_string(self):
        for name in ('write_csv', 'write_paged_csv', 'write_relative_csv'):
            source = inspect.getsource(getattr(self.audit, name))
            self.assertNotIn('in_data_region', source)
            self.assertNotIn('entry_aligned', source)

    def test_the_sibling_writer_carries_both(self):
        """The positive half of the same contract, on this file's own writer.

        `table()` delegates its cells to `rows()`, so the columns are asserted
        where they are actually built rather than in the function that happens
        to be named in the docstring.
        """
        source = inspect.getsource(bcr.rows)
        self.assertIn('in_data_region', source)
        self.assertIn('entry_aligned', source)
        self.assertIn('in_data_region', bcr.COLUMNS)
        self.assertIn('entry_aligned', bcr.COLUMNS)

    def test_the_three_committed_censuses_are_not_this_tools_output(self):
        """`--write` cannot land on one of the three per-site tables.

        The narrower thing this file could have broken, and the one worth a
        check: that the new writer's default path is a *fourth* file. That each
        of the three still reproduces itself byte for byte is
        `audit_call_targets.py --self-test`'s own assertion, and that self-test
        runs in the cheap gate — re-deriving it here would assert a tool against
        itself from a suite that is not the one gating it.
        """
        self.assertNotEqual(bcr.BUCKET_C_CENSUS, Path(bcr.DEFAULT_CSV).name)
        self.assertNotEqual(bcr.PAGED_CENSUS, Path(bcr.DEFAULT_CSV).name)
        for census in (bcr.BUCKET_C_CENSUS, bcr.PAGED_CENSUS):
            self.assertTrue((ANNOTATIONS / census).exists(), census)


class HeaderBlockTests(unittest.TestCase):
    """The `#` block above the header: present, and carrying the caveats.

    A committed artefact needs somewhere to keep its provenance and the meaning
    of a three-valued cell without a per-row column for either, and this is the
    file a reader opens to ask what `entry_aligned` means. `csv.DictReader` on
    the whole file reads the block as the header and produces one column called
    `# bank-call-regions.csv -- generated by ...`, so the consumers here strip
    it first -- `call_graph_gaps.py`'s `read_rows()` gives the same reason.
    """

    def setUp(self):
        self.text = Path(COMMITTED_CSV).read_text()

    def test_the_block_is_present_and_names_the_tool_and_both_modes(self):
        head = [ln for ln in self.text.splitlines() if ln.startswith("#")]
        self.assertTrue(head, 'the committed table has no `#` header block')
        block = "\n".join(head)
        self.assertIn('--write', block)
        self.assertIn('--check', block)

    def test_the_block_carries_the_meaning_of_the_three_valued_cell(self):
        block = "\n".join(ln for ln in self.text.splitlines()
                          if ln.startswith("#"))
        missing = [p for p in HEADER_PHRASES if p not in block]
        self.assertFalse(missing,
                         f'the header block does not say: {missing}')

    def test_the_block_is_not_read_as_data(self):
        rows = committed_rows()
        self.assertTrue(rows)
        self.assertEqual(rows[0]["file_offset"][:2], '0x')
        self.assertNotIn('file_offset', rows[0].keys() - set(bcr.COLUMNS))

    def test_the_block_is_byte_identical_to_what_the_writer_emits(self):
        """So it cannot be dropped or reworded without `--check` going red.

        The comment block and the table are one value in `table()`, so the
        check's byte comparison covers the block; this is the case that says so
        rather than leaving it to be inferred.
        """
        d = Path(FIRMWARE).read_bytes()
        regions = bcr.load_data_regions()
        self.assertEqual(bcr.table(d, regions), self.text)


class ToolTests(unittest.TestCase):
    """The shipped modes, driven as a subprocess the way the gate would."""

    def test_self_test_passes_on_the_committed_image(self):
        result = subprocess.run(
            [sys.executable, TOOL, FIRMWARE, "--self-test"],
            capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def test_write_reproduces_the_committed_table_byte_for_byte(self):
        """`--write` is a regeneration, not an edit: running it changes nothing.

        Run against a scratch copy rather than the committed path, so a
        `--write` that had drifted would be a red run here rather than a silent
        rewrite of the repository's own table by the test suite.
        """
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / 'written.csv'
            result = subprocess.run(
                [sys.executable, TOOL, FIRMWARE, "--write",
                 "--csv-path", str(path)], capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            self.assertEqual(path.read_text(), Path(COMMITTED_CSV).read_text())

    def test_csv_agrees_with_the_committed_file(self):
        result = subprocess.run(
            [sys.executable, TOOL, FIRMWARE, "--csv"],
            capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stdout, Path(COMMITTED_CSV).read_text())

    def test_an_image_without_the_pd_marker_is_refused(self):
        with tempfile.TemporaryDirectory() as tmp:
            other = Path(tmp) / "not-the-ec.bin"
            other.write_bytes(b"\x00" * 0x20040)
            result = subprocess.run(
                [sys.executable, TOOL, str(other), "--check"],
                capture_output=True, text=True)
            self.assertEqual(result.returncode, 1)
            self.assertIn("ITE8850-PD", result.stderr)


if __name__ == '__main__':
    unittest.main()
