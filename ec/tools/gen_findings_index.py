#!/usr/bin/env python3
"""Print an index of the write-ups under `docs/findings/`.

**Not committed** (2026-10-04). `docs/findings/INDEX.md` was this tool's output,
checked in: every write-up added a line to it, so 218 of 272 commits to main
between 2026-09-27 and 2026-10-04 touched it, and it was the single most
conflicted file in the agent pipeline's conflict runs. The listing is a function
of the directory, so a reader -- human or agent -- runs this tool, or `ls`.
`--check` now holds the one property the index needed from each write-up: a
`# ` title to list it by.

What follows is the tool's earlier history.

**Why this is generated rather than written.** The alternative to freezing
`docs/findings.md` is an index that every change appends to, and an index
nobody appends to by hand goes stale within a week. A generated one is a
function of the tree: two branches that both add a write-up and both regenerate
produce the same file, so the conflict is resolved once in the content and never
in the prose. That is the difference between a shared file that collides and a
shared file that is merely shared.

**Why there is no count line.** The index used to open with `N write-ups.`.
Every pull request that adds a write-up changes that line, so any two in flight
conflicted on it even when their rows merged cleanly, and a clean merge left it
one short and `--check` red. Six of the blocking review findings on the open
pull requests of 2026-09-30 were that line. The rows are sorted by file name
and merge on their own; the count is `--check`'s output, where nobody commits
it.

**What it reads.** The first `# ` heading of every `*.md` directly under
`docs/findings/`, minus this index and the census write-up that is a table of
the repository's own pins rather than a finding. Nothing else is read, so the
index cannot disagree with the tree except by being out of date, and `--check`
is what says so.

`--check` exits 1 when the committed index differs from what this run produces,
which is the form the gate wants; with no flag it prints the index.
"""

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, os.pardir, os.pardir))
FINDINGS_DIR = os.path.join("docs", "findings")
INDEX = "INDEX.md"

# Not findings: the index itself, and the pin census, which is a table of the
# repository's citations rather than a conclusion about the machine. Both are
# reachable from `docs/findings.md` and neither belongs in a list of findings.
SKIP = {INDEX, "test-line-pin-census.md"}

HEADING = re.compile(r"^#\s+(.*\S)\s*$")


def entries(repo, titled_only=False):
    """-> [(filename, title)] sorted by filename, for every write-up.

    `titled_only` reports a missing title as None instead of a title made up
    from the file name, which is what `--check` needs.
    """
    root = os.path.join(repo, FINDINGS_DIR)
    out = []
    for name in sorted(os.listdir(root)):
        if not name.endswith(".md") or name in SKIP:
            continue
        path = os.path.join(root, name)
        if not os.path.isfile(path):
            continue
        title = None
        with open(path, encoding="utf-8") as handle:
            for line in handle:
                if line.startswith("# "):
                    title = line[2:].strip()
                    break
                if line.strip():
                    # A file that opens with prose before its heading is still a
                    # write-up; keep looking rather than record no title.
                    continue
        if titled_only:
            out.append((name, title))
        else:
            out.append((name, title or name[:-3].replace("-", " ")))
    return out


def render(repo):
    found = entries(repo)
    lines = [
        "# Findings index",
        "",
        "**Generated by `ec/tools/gen_findings_index.py` — do not edit.** Every",
        "write-up under `docs/findings/`, by file name. `docs/findings.md` is",
        "frozen at §97 and is the record of what came before this directory was",
        "the place a finding went; `check_findings_frozen.py` holds that.",
        "",
    ]
    for name, title in found:
        lines.append("- [`%s`](%s) — %s" % (name, name, title))
    lines.append("")
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--repo", default=REPO, help="repository root")
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if a write-up has no `# ` title")
    args = parser.parse_args(argv)

    if not args.check:
        sys.stdout.write(render(args.repo))
        return 0

    committed = os.path.join(args.repo, FINDINGS_DIR, INDEX)
    if os.path.exists(committed):
        print("docs/findings/INDEX.md is committed again; it is this tool's "
              "output and is not kept in the tree (every write-up added a line "
              "to it, so it conflicted on nearly every pull request). Delete it.")
        return 1
    untitled = [name for name, title in entries(args.repo, titled_only=True)
                if title is None]
    if untitled:
        print("write-up(s) with no `# ` title to index them by: "
              + ", ".join(untitled))
        return 1
    print("every write-up under docs/findings/ has a title")
    return 0


if __name__ == "__main__":
    sys.exit(main())
