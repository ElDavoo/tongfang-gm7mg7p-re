#!/usr/bin/env python3
"""Offline checks for census_evidence_citations.py: committed files and fixtures.

The tool is a census, so its failure mode is not a crash and not a red run --
it is a **number that looks like a result**. A reverse direction whose join key
is spelled differently from the forward direction's reports every listing in
`ec/decompiled/` as uncited and prints it as a coverage figure; a class
computed by subtracting two totals instead of differencing two sets goes wrong
the first time either side moves alone, and prints the same number it printed
yesterday. Neither is visible from the exit code, which is 0 with findings in
hand by design.

So what is pinned here is the derivation and the refusals, in the shape
`pd_unannotated_census.py`'s `--self-test` takes: run `census()` itself over a
fixture tree whose answer is known, rather than re-deriving its expressions
beside it. A self-test that re-derives the answer next to the code certifies
the derivation, not the tool -- that is how an earlier version of that census
passed while `census()` reported every shared `common`/`pd` address as
unshared.

**The claims, and none of them is a number.** The four classes are disjoint and
sum to the uncited set; the uncited set is a set difference over matched
addresses and the other mismatch is reported rather than netted; the reverse
direction's key is the column's own spelling of a path; `out_file` resolves
against `ec/decompiled/` and `evidence` against the repository root, in one
file; and a forward direction that found something and one that found nothing
are distinguishable from the output even though both exit 0.

**A deliberately-broken control, in both tools at once.** A cell naming a path
that is not on disk has to turn `check_testdata_index.py` red *and* print as a
`missing` here. A check that has never been shown to fail is a check nothing
has tested, and the two tools reading one column is the arrangement this whole
change is about, so the demonstration is of both halves together.

**Nothing here reads a capture, an EC, or a laptop.** Every path is a
hand-written string in a `tempfile`, and the last class reads committed files
with `open()`.
"""
import contextlib
import importlib.util
import io
import os
import re
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).parent
# The tool imports its two readers as siblings, so the directory has to be on
# the path the same way their own suites put it there.
sys.path.insert(0, str(HERE))
spec = importlib.util.spec_from_file_location(
    'census_evidence_citations', HERE / 'census_evidence_citations.py')
cec = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cec)

# The header the reader looks the column up by. It is read **by name** and not
# by position -- `evidence` is column 7 of 8 in one committed CSV and column 10
# of 12 in another -- so the fixtures here are not all this width on purpose.
ANNOTATION_HEADER = "scope,addr,name,comment,evidence,basis"

# A listing's own header. Three comment lines and a blank, because the reader
# skips `;` lines and reads the rest by column, and a fixture without the plate
# would be testing a listing shape nothing in the repository has.
PLATE = ("; {area} @ {addr}   a fixture listing\n"
         "; Ghidra disassembly, generated by ec/tools/build_ec_decompile.py "
         "-- do not edit.\n"
         "; This is the machine code.\n\n")


class ScratchRepo:
    """A throwaway repository: an annotation CSV, a decompiled tree, an index.

    Laid out as a repository because that is what both halves resolve against --
    `evidence` at the root and `out_file` under `ec/decompiled/` -- so a fixture
    that only looked like the right shape would be testing the shape.

    The tree is assembled in memory and written by `commit()`, so a case can
    describe the whole population it wants -- four classes, an orphan row, a
    document citation -- and then ask the tool about it, rather than arranging
    it on disk one `write` at a time and being unable to say what the fixture
    was.
    """

    def setUp(self):
        self.root = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.root)
        self.annotations = os.path.join(self.root, "ec", "annotations")
        self.decompiled = os.path.join(self.root, "ec", "decompiled")
        os.makedirs(self.annotations)
        self.rows, self.listings, self.exports = [], [], []

    def listing(self, area, addr, fill=False, decompile=True, export=True):
        """Put a committed listing (and, unless told not to, its `.c`) on disk.

        `fill` writes the `0xFF` run `citation_callers.is_fill` answers yes to,
        in the listing's own spelling -- `ff - -   mov   R7, A` -- rather than
        a hand-rolled marker the predicate would not read. `export` adds the
        listing's `.c` to `index.csv`'s `out_file`, which is the column the
        "not yet exported" class is a predicate over.
        """
        body = "7401  ff - -   mov      R7, A\n" if fill else \
            "00a1  22 - -   ret\n"
        directory = os.path.join(self.decompiled, area)
        os.makedirs(directory, exist_ok=True)
        with open(os.path.join(directory, addr + ".asm"), "w") as f:
            f.write(PLATE.format(area=area, addr=addr) + body)
        if decompile:
            with open(os.path.join(directory, addr + ".c"), "w") as f:
                f.write("/* a fixture decompile */\n")
        self.listings.append((area, addr))
        if export:
            self.exports.append((area, addr, "%s/%s.c" % (area, addr)))
        return addr

    def row(self, area, addr, evidence):
        """Add an annotation row citing `evidence`, which may be empty."""
        self.rows.append((area, addr, "fn_%s" % addr.lower(), evidence))
        return addr

    def note(self, rel="ec/annotations/notes.md"):
        """A document a row can cite, so the forward direction stays clean."""
        path = os.path.join(self.root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write("# a document, not a listing\n")
        return rel

    def commit(self, index_header=("program", "addr", "name", "out_file")):
        """Write both CSVs, and return the `Census` the tool derives from them."""
        with open(os.path.join(self.annotations, cec.ANNOTATIONS_CSV), "w") as f:
            f.write(ANNOTATION_HEADER + "\n")
            for area, addr, name, evidence in self.rows:
                f.write("%s,%s,%s,a comment,%s,hand-decoded\n"
                        % (area, addr, name, evidence))
        os.makedirs(self.decompiled, exist_ok=True)
        with open(os.path.join(self.decompiled, cec.INDEX_CSV), "w") as f:
            f.write(",".join(index_header) + "\n")
            for area, addr, out in self.exports:
                f.write("%s,%s,fn_%s,%s\n" % (area, addr, addr.lower(), out))
        return cec.census(self.root)

    def classes(self, found, area, name):
        """{addr: the class it fell in} for one area, keyed by address."""
        return {os.path.basename(p)[:-4]: name
                for p in found.classes[area][name]}


def run_tool(root, argv=()):
    """(exit code, stdout, stderr) for one run of the census over `root`.

    `main()` reads the module global `REPO` and has no flag pointing it
    elsewhere, so a fixture tree is reached by patching that one global -- which
    works only because `census()` defaults `repo` at call time. A `repo=REPO`
    def-time default would bind before the patch and every case in this file
    would be a case about the committed tree while reading as a case about a
    `tempfile`.
    """
    out, err = io.StringIO(), io.StringIO()
    saved, was = sys.argv, cec.REPO
    sys.argv = ['census_evidence_citations.py'] + list(argv)
    cec.REPO = root
    try:
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            rc = cec.main()
    finally:
        sys.argv = saved
        cec.REPO = was
    return rc, out.getvalue(), err.getvalue()


class TheForwardDirectionIsTheImportedReader(ScratchRepo, unittest.TestCase):
    """Both tools read one column, and it is `check_testdata_index`'s reader.

    The census is not a second reader of an `evidence` column, and the case that
    would catch a second one is a token the shared rule declines to read: an
    address range is `unresolved` here exactly as it is in the check, and a
    reader of its own would have had to invent an answer for it.
    """

    def test_a_token_the_path_rule_refuses_is_unresolved_in_both_tools(self):
        # The same cell, read by both, through `evidence_pointers()`. Asserted
        # against that function's own return rather than a copy of it, so the
        # case is a claim about the two tools agreeing rather than about a
        # number either of them computed the same way twice.
        ctti = importlib.import_module("check_testdata_index")
        self.note()
        self.listing("common", "00CF")
        self.row("common", "00CF", "0x0700-0x07FF")
        found = self.commit()
        theirs = ctti.evidence_pointers(
            cec.ANNOTATIONS_CSV, self.annotations, self.root)
        self.assertEqual((found.forward.tokens, len(found.forward.unresolved)),
                         (theirs.tokens, len(theirs.unresolved)))
        self.assertEqual([token for _, token, _ in found.forward.unresolved],
                         ["0x0700-0x07FF"])
        self.assertEqual(found.forward.unresolved[0][2],
                         theirs.unresolved[0][2])

    def test_a_citation_naming_a_path_that_is_not_there_is_a_missing(self):
        self.listing("common", "00CF")
        self.row("common", "00CF", "ec/decompiled/common/DEAD.asm")
        found = self.commit()
        self.assertEqual([token for _, token, _ in found.forward.missing],
                         ["ec/decompiled/common/DEAD.asm"])
        self.assertEqual(found.forward.unresolved, [])

    def test_a_document_citation_is_counted_and_resolved_and_not_a_listing(self):
        # The distinction the reverse direction turns on, stated here so it is
        # the forward half's answer before it is the other half's question: a
        # row citing a write-up has cited something real, and it has not cited
        # a listing.
        rel = self.note()
        self.listing("common", "00CF")
        self.row("common", "00CF", rel)
        found = self.commit()
        self.assertEqual((found.document, found.forward.missing), ([rel], []))
        self.assertIn(".md", cec.suffixes(found.document))


class OneBrokenCitationTurnsBothToolsRed(ScratchRepo, unittest.TestCase):
    """The deliberately-broken control, in both halves at once.

    A cell naming a path that is not on disk has to be a `missing` here **and**
    a red run in `check_testdata_index.py`. The two are the arrangement this
    whole change is about -- one column, one reader, two tools -- so a
    demonstration of either half alone would leave open the only question worth
    asking: whether the census's forward half really is that reader, or a
    second one that agrees today.

    The census exits 0 over the same tree. That is not an inconsistency and it
    is the decision: findings in hand are what a census prints, and only a run
    that located nothing turns it non-zero.
    """

    def run_check(self):
        """(exit code, stdout, stderr) for one run of the check over `root`.

        `main()` reads `TESTDATA`, `INDEX` and `REPO` as module globals and has
        no flag pointing any of them elsewhere, so a scratch repository is
        reached by patching all three -- the third being what the widened
        annotation source resolves against, so a run that patched only the
        first two would answer about the committed tree while reading as a case
        about a `tempfile`.
        """
        ctti = importlib.import_module("check_testdata_index")
        out, err = io.StringIO(), io.StringIO()
        saved = (sys.argv, ctti.TESTDATA, ctti.INDEX, ctti.REPO)
        sys.argv = ['check_testdata_index.py', '--check']
        ctti.TESTDATA = os.path.join(self.root, "testdata")
        ctti.INDEX = os.path.join(ctti.TESTDATA, "README.md")
        ctti.REPO = self.root
        try:
            with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
                rc = ctti.main()
        finally:
            (sys.argv, ctti.TESTDATA, ctti.INDEX,
             ctti.REPO) = saved
        return rc, out.getvalue(), err.getvalue()

    def test_a_citation_naming_nothing_is_a_missing_here_and_a_red_run_there(self):
        self.listing("common", "00CF")
        self.row("common", "00CF", "ec/decompiled/common/DEAD.asm")
        self.commit()
        # The check's own subject, empty: the finding under test is the
        # annotation citation and nothing in the fixture tree may add a second.
        os.makedirs(os.path.join(self.root, "testdata"))
        with open(os.path.join(self.root, "testdata", "README.md"), "w") as f:
            f.write("| File | Feeds | What it constructs |\n| --- | --- | --- |\n")

        rc, out, err = run_tool(self.root)
        self.assertEqual(rc, 0, err)
        self.assertIn("1 evidence path token(s): 0 resolved, 1 missing, "
                      "0 unresolved", out)

        rc, out, err = self.run_check()
        self.assertEqual(rc, 1, out)
        self.assertIn("the `evidence` column names "
                      "`ec/decompiled/common/DEAD.asm`", err)
        self.assertIn("which is not on disk", err)
        self.assertIn("1 citation(s) in ec/annotations/"
                      "ghidra-functions.csv", err)


class TheFourClassesPartitionTheUncitedSet(ScratchRepo, unittest.TestCase):
    """One listing in each class, and the arithmetic that says they are classes.

    A census that reported "822 uncited" and a per-class table that summed to
    something else would look identical from the output, and the second is what
    a reader checks the first against. So the claim is the partition, asserted
    on a tree whose contents are named here, and separately on the committed one
    in `TheCommittedTree`.
    """

    def build(self):
        """A tree holding one listing in each class, plus one cited listing."""
        other = "ec/decompiled/common/00CF.asm"
        self.note()
        self.listing("common", "00CF")                     # cited: not uncited
        self.row("common", "00CF", other)
        self.listing("common", "00CE")                     # unannotated
        self.listing("common", "00CD")                     # names no .asm
        self.row("common", "00CD", "ec/annotations/notes.md")
        self.listing("common", "00CC")                     # names another
        self.row("common", "00CC", other)
        self.listing("common", "00CB", fill=True)          # deliberate 0xFF
        self.row("common", "00CB", other)
        self.listing("common", "00CA", decompile=False,
                     export=False)                          # not yet exported
        self.row("common", "00CA", other)
        return self.commit()

    def test_each_listing_lands_in_exactly_the_class_it_was_built_for(self):
        found = self.build()
        self.assertEqual(self.classes(found, "common", cec.UNANNOTATED),
                         {"00CE": cec.UNANNOTATED})
        self.assertEqual(self.classes(found, "common", cec.CITED_ELSEWHERE),
                         {"00CD": cec.CITED_ELSEWHERE,
                          "00CC": cec.CITED_ELSEWHERE})
        self.assertEqual(self.classes(found, "common", cec.FILL),
                         {"00CB": cec.FILL})
        self.assertEqual(self.classes(found, "common", cec.NOT_EXPORTED),
                         {"00CA": cec.NOT_EXPORTED})

    def test_the_two_exits_into_cited_elsewhere_are_counted_apart(self):
        # The issue names "a listing can have an annotation row whose `evidence`
        # cell names a different file" and `pd_unannotated_census.py` measures
        # the narrower one (67 rows naming no `.asm` at all). One class, two
        # counters, because they are different defects with the same headline
        # and folding them would lose which one a reader has to go and fix.
        found = self.build()
        self.assertEqual(dict(found.elsewhere),
                         {cec.NO_ASM: 1, cec.ANOTHER: 1})

    def test_the_classes_are_disjoint_and_sum_to_the_uncited_set(self):
        found = self.build()
        seen = []
        for name in cec.CLASSES:
            seen += found.classes["common"][name]
        self.assertEqual(len(seen), len(set(seen)), "two classes claim a listing")
        self.assertEqual(sorted(seen), sorted(found.uncited))
        self.assertNotIn(cec.listing_key("common", "00CF"), seen,
                         "a listing an `evidence` cell names is not uncited")

    def test_a_listing_nobody_annotated_is_not_a_row_naming_no_listing(self):
        # The two mismatches, and the reason this is a set difference rather
        # than a subtraction of two totals: a row at an address with no listing
        # behind it is a claim about a function the export no longer holds, and
        # it is reported beside the population rather than netted against it.
        # Subtract two totals and the two cancel on the day they happen to be
        # equal in size, which is the day a reader stops believing the figure.
        self.listing("common", "00CF")
        self.row("common", "00CF", "ec/decompiled/common/00CF.asm")
        self.listing("common", "00CE")
        self.row("common", "C0C0", "ec/annotations/notes.md")
        found = self.commit()
        self.assertEqual(self.classes(found, "common", cec.UNANNOTATED),
                         {"00CE": cec.UNANNOTATED})
        self.assertEqual(found.orphans, [("common", "C0C0")])
        self.assertEqual([os.path.basename(p) for p in found.uncited],
                         ["00CE.asm"])

    def test_the_same_address_in_two_scopes_is_two_listings(self):
        # The key is `(scope, addr)` and not `addr`: `common/7401` and
        # `pd/7401` are two functions in two programs, and a census keyed on
        # the address alone reports one of them annotated by the other's row.
        # `pd_unannotated_census.py` calls this the conflation it is scoped
        # around, and the listing filename is the key, so this is the same
        # disagreement one level up.
        self.listing("common", "7401")
        self.listing("pd", "7401")
        self.row("common", "7401", "ec/decompiled/common/7401.asm")
        found = self.commit()
        self.assertEqual(self.classes(found, "pd", cec.UNANNOTATED),
                         {"7401": cec.UNANNOTATED})
        self.assertEqual(found.classes["common"][cec.UNANNOTATED], [])


class TheTwoBasesInOneFile(ScratchRepo, unittest.TestCase):
    """`out_file` at `ec/decompiled/`, `evidence` at the repository root.

    `check_fixture_pointer_cells.py`'s docstring records the fact this is the
    second half of: the two pointer columns of `ec/decompiled/index.csv` are
    rooted at different places, so a reader of one column has to say which it
    used. A reader of `out_file` at the root would call every row of it absent
    and would then put every listing in the tree into "not yet exported" --
    which is a coverage figure, printed.
    """

    def test_an_out_file_named_from_the_decompiled_root_is_the_one_that_counts(self):
        # The fixture writes `common/00CF.c` in the index and puts the file at
        # `<repo>/ec/decompiled/common/00CF.c`, which is the only place it
        # exists. Read at the root it is absent, and the listing with it.
        self.listing("common", "00CF")
        self.row("common", "00CF", "ec/decompiled/common/DEAD.asm")
        found = self.commit()
        # The citation is broken on purpose, so that the listing is uncited and
        # the class it falls in is decided by the *other* column. Exported
        # means not "not yet exported", whichever way the `evidence` column went.
        self.assertEqual(found.out_file_tokens, 1)
        self.assertEqual(found.out_file_missing, 0)
        self.assertEqual(self.classes(found, "common", cec.NOT_EXPORTED), {})

    def test_a_listing_whose_c_is_not_in_the_index_is_not_yet_exported(self):
        self.listing("common", "00CF")
        self.row("common", "00CF", "ec/decompiled/common/DEAD.asm")
        self.listing("common", "00CE", decompile=False, export=False)
        self.row("common", "00CE", "ec/decompiled/common/DEAD.asm")
        found = self.commit()
        self.assertEqual(self.classes(found, "common", cec.NOT_EXPORTED),
                         {"00CE": cec.NOT_EXPORTED})

    def test_the_report_names_both_bases(self):
        self.listing("common", "00CF")
        self.row("common", "00CF", "ec/decompiled/common/00CF.asm")
        found = self.commit()
        out = io.StringIO()
        cec.report(found, out=out)
        text = out.getvalue()
        self.assertIn("`out_file` resolves against", text)
        self.assertIn("`evidence` against the repository root", text)


class TheCensusExitsZeroAndSaysWhenItFoundNothing(ScratchRepo,
                                                  unittest.TestCase):
    """The exit-code contract, both sides, because a census is not a check.

    A census that gated on what it found would go red the next time a decompile
    export lands a listing nobody has read yet, which is the ordinary state of
    an unfinished reconstruction rather than a defect. So findings exit 0 -- and
    the counterpart matters just as much: a run that read **nothing** must not
    be able to say so with a 0, or "found nothing wrong" and "found nothing" are
    the same answer. `census_test_line_pins.py` sets the convention this copies.
    """

    def test_a_population_with_findings_in_hand_exits_zero(self):
        # One cited listing and one not, which is the shape the committed tree
        # has: a census that found something uncited and something cited is a
        # successful run, and the uncited half is the finding.
        self.listing("common", "00CF")
        self.row("common", "00CF", "ec/decompiled/common/00CF.asm")
        self.listing("common", "00CE")
        self.commit()
        rc, out, err = run_tool(self.root)
        self.assertEqual(rc, 0, err)
        self.assertIn("1 named by none", out)
        self.assertIn("not named by this method, never absent", out)

    def test_a_run_that_read_no_token_says_so_and_exits_non_zero(self):
        os.makedirs(self.decompiled)
        with open(os.path.join(self.decompiled, cec.INDEX_CSV), "w") as f:
            f.write("program,addr,name,out_file\n")
        rc, out, err = run_tool(self.root)
        self.assertEqual(rc, 1, out)
        self.assertIn("no `evidence` token was read at all", err)
        self.assertIn("a broken census, not an empty one", err)

    def test_a_run_that_found_no_listing_says_so_and_exits_non_zero(self):
        self.note()
        self.row("common", "00CF", "ec/annotations/notes.md")
        self.commit()
        rc, out, err = run_tool(self.root)
        self.assertEqual(rc, 1, out)
        self.assertIn("no committed .asm was found", err)
        self.assertIn("a broken census, not an empty one", err)

    def test_the_transcript_carries_both_directions_and_the_uncited_table(self):
        self.listing("common", "00CF")
        self.row("common", "00CF", "ec/decompiled/common/00CF.asm")
        self.listing("common", "00CE")
        self.commit()
        rc, out, err = run_tool(self.root)
        self.assertEqual(rc, 0, err)
        self.assertIn("forward, every token resolved against the repository "
                      "root", out)
        self.assertIn("reverse, every committed .asm named by no token", out)
        # The four class columns, printed even where a class is empty: a 0 that
        # is computed is an answer and a 0 that is a subtraction is a
        # coincidence, and a table that dropped an empty column would not say
        # which it was.
        for name in cec.CLASSES:
            self.assertIn(name, out)
        self.assertRegex(
            out, r"(?m)^  common\s+\d+\s+\d+\s+1\s+0\s+0\s+0\s*$")
        self.assertIn("1 named by an `evidence` cell", out)

    def test_verbose_names_every_uncited_listing_with_its_class(self):
        self.listing("common", "00CF")
        self.row("common", "00CF", "ec/decompiled/common/00CF.asm")
        self.listing("common", "00CE")
        self.commit()
        rc, out, err = run_tool(self.root, ["--verbose"])
        self.assertEqual(rc, 0, err)
        self.assertRegex(out, r"(?m)^ {4}unannotated\s+"
                             r"ec/decompiled/common/00CE\.asm$")
        self.assertNotIn("ec/decompiled/common/00CF.asm", out)


class TheCommittedTree(unittest.TestCase):
    """The real annotation CSV, over both directions, as claims and not counts.

    `CLAUDE.md` names the trap four times: **a test that asserts a count of the
    tree is a value every merge has to edit**, and 822 is exactly that. So what
    is held here is the *relation* -- the forward tally adds up, the four
    classes are disjoint and sum to the uncited set, the uncited set is what is
    left of the listings once the named ones are removed -- which stays true as
    the tree moves, and a derivation that quietly stopped holding would fail
    every one of them.

    The class is the only one that reads a committed file, and it is the last
    in the file for the reason `TheReachedSomethingRule` in the sibling suite
    is documented at length: a case that reached nothing and a tree that has
    nothing to report look the same from the outside.
    """

    @classmethod
    def setUpClass(cls):
        cls.found = cec.census()

    def test_the_forward_tally_adds_up(self):
        forward = self.found.forward
        self.assertGreater(forward.tokens, 0)
        self.assertEqual(cec.resolved(forward),
                         forward.tokens - len(forward.missing)
                         - len(forward.unresolved))
        # Every cell carries a value, and a `;`-joined cell is the reason the
        # token count is kept apart from the cell count at all -- so on this
        # tree the token count is the larger of the two or the reader dropped a
        # `;`. Neither figure is pinned: both are values every annotation moves.
        self.assertEqual(self.found.empty, 0)
        self.assertGreaterEqual(forward.tokens, forward.cells)

    def test_the_reverse_direction_is_the_complement_of_the_named_set(self):
        total = sum(len(addrs) for addrs in self.found.listed.values())
        self.assertEqual(total, len(self.found.uncited) + len(self.found.named))
        # And the named set is drawn from the listings, not from the addresses
        # a row carries: two rows at one address, or a row whose `evidence`
        # names a listing in another scope, must not move this count.
        self.assertTrue(all(key.startswith("ec/decompiled/")
                            for key in self.found.named))

    def test_the_four_classes_are_disjoint_and_sum_to_the_uncited_set(self):
        seen = []
        for area in sorted(self.found.classes):
            for name in cec.CLASSES:
                seen += self.found.classes[area][name]
        self.assertEqual(len(seen), len(set(seen)))
        self.assertEqual(sorted(seen), sorted(self.found.uncited))

    def test_the_per_area_counts_add_up_to_the_totals(self):
        for area in sorted(self.found.classes):
            per_area = sum(len(self.found.classes[area][c])
                           for c in cec.CLASSES)
            self.assertEqual(per_area, len(
                [p for p in self.found.uncited
                 if p.split(os.sep)[2] == area]),
                "a per-area column and the uncited set disagree")
            self.assertLessEqual(per_area, len(self.found.listed[area]))

    def test_the_committed_citation_rows_have_a_listing(self):
        # The other mismatch, on the real tree: a row at an address with no
        # listing behind it is a claim about a function the export no longer
        # holds. Reported, and not netted against the uncited set -- which is
        # what makes the two figures independent rather than two halves of one.
        self.assertEqual(self.found.orphans, [])

    def test_the_run_exits_zero_and_prints_both_directions(self):
        rc, out, err = run_tool(cec.REPO)
        self.assertEqual(rc, 0, err)
        self.assertIn("forward, every token resolved", out)
        self.assertIn("reverse, every committed .asm named by no token", out)
        self.assertIn("carries both bases in one file", out)
        self.assertIn("never absent", out)

    def test_the_areas_printed_are_the_areas_on_disk(self):
        for area in self.found.classes:
            self.assertIn(area, self.found.listed)
        self.assertTrue(self.found.classes, "no area was walked at all")


