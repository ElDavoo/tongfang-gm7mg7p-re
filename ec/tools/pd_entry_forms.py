def print_body(d, index, first, last, raw, gaps):
    row = index_row(index, first)
    covered = BODY[1] - BODY[0] - sum(b - a for a, b in gaps)
    print("## 1. The body, and where its length comes from")
    print()
    print(f"  0x{first:04X} to 0x{last:04X} ({last - first + 1} bytes), from the "
          f"committed listing's own instruction stream")
    print(f"  the listing's instruction bytes sum to {len(raw)} -- the same "
          f"figure as listing-index.csv's size, which is the trap")
    print(f"  listing-index.csv reads size={row['size']} for {PROGRAM},0x{first:04X}, "
          f"so reading it as an extent stops at 0x{first + int(row['size']) - 1:04X} "
          f"and never reaches the `ret`")
    print(f"  {covered} of the {last - first + 1} bytes are covered by an "
          f"instruction; {len(gaps)} committed gap(s) inside the span:")
    for a, b in gaps:
        print(f"    0x{a:04X}-0x{b - 1:04X}  ({b - a} bytes)  "
              f"{d[a:b].hex(' ')}")
    print(f"  the last byte is 0x{d[last]:02X} (`ret`) and the first "
          f"is 0x{d[first]:02X}")
    print()


def print_candidates(rows):
    external = [r for r in rows if r["origin"] == "outside"]
    internal = [r for r in rows if r["origin"] == "inside"]
    print("## 2. The entry set")
    print()
    print(f"  {len(rows)} candidate(s) by byte scan over the image's {PD_LEN} "
          f"bytes; {len(external)} of them sit outside the body and can enter "
          f"it, and the other {len(internal)} are the body's own branches")
    print(f"  {sum(1 for r in external if r['landing'] == 'first-byte')} of the "
          f"{len(external)} reaches the body's first byte; "
          f"{sum(1 for r in external if r['landing'] == 'inner')} reaches "
          f"strictly inside it")
    print()
    print("| site | form | target | lands | frame | in a committed listing it is |")
    print("|---|---|---|---|---:|---|")
    for r in external:
        print(f"| `0x{r['site']:04X}` | {r['form']} | `0x{r['target']:04X}` "
              f"| {r['landing']} | {r['frame_onto']}/"
              f"{r['frame_onto'] + r['frame_over']} | {r['note']} |")
    print()
    print("The frame column is `converges_from()` and settles nothing on its own"
          " -- its own docstring says to read the pair, and a site nobody syncs"
          " onto is not thereby misframed. The last column is the other half.")
    print()
    if internal:
        listed = sum(1 for r in internal if r["population"] == "listing")
        print(f"The other {len(internal)} candidate(s) are branches whose *site* "
              f"is inside the body -- {listed} of them in a committed listing "
              f"and {len(internal) - listed} in the committed gap -- so they are "
              f"the routine's own control flow rather than entries into it. They "
              f"are in `pd-entry-forms.csv` because the byte scan finds them and "
              f"a reader counting rows should not have to wonder why it did.")
        print()


def print_tables(eligible, discarded, found):
    print("## 3. The index tables, and the scope filter")
    print()
    print(f"  {eligible} row(s) eligible after the scope filter, {discarded} "
          f"discarded by it")
    print(f"  {len(found)} transfer(s) into the body anywhere in an eligible "
          f"table's bytes")
    for path, site, form, target in found:
        print(f"    {path} 0x{site:04X} {form} 0x{target:04X}")
    print()
    print("Eligibility is measured from the file offset a row names, not from"
          " which tool wrote it: the two EC tables and the pd table share an"
          " address space, and a `common` row at 0xE2E4 is a different image's"
          " byte. `docs/findings/pd-common-address-spaces.md` is the write-up.")
    print()


def print_verdict(rows):
    external = [r for r in rows if r["origin"] == "outside"]
    first = [r for r in external if r["landing"] == "first-byte"]
    inner = [r for r in external if r["landing"] == "inner"]
    print("## 4. The answer")
    print()
    for r in first:
        print(f"  **One entry found by this method: `{r['form']} 0x{r['target']:04X}` "
              f"at `0x{r['site']:04X}`**, landing on the body's first byte at "
              f"{r['frame_onto']}/{r['frame_onto'] + r['frame_over']}, in a "
              f"committed listing.")
    print()
    if inner:
        print(f"  {len(inner)} candidate(s) spell a transfer landing strictly "
              f"inside, and the pair rules out "
              f"{'both' if len(inner) > 1 else 'it'}:")
        for r in inner:
            print(f"    `0x{r['site']:04X}` spells `{r['form']} 0x{r['target']:04X}`"
                  f" -- {r['note']}.")
    else:
        print(f"  **No candidate lands strictly inside 0x{BODY[0] + 1:04X}-"
              f"0x{BODY_LAST:04X}.**")
    print()
    print("  That is *not found by this method*, and the difference is the"
          " headline rather than a footnote: the committed listings cover a"
          " quarter of the image, the byte scan is the wider half and finds"
          " every byte pattern there is, and a candidate is a candidate until"
          " both halves agree.")
    print()


def csv_table(rows):
    """`pd-entry-forms.csv` as a string, for `--check` to diff.

    A string rather than a write to stdout, for the reason
    `pd_image_census.csv_table()` gives: `--check` compares the same bytes this
    prints, and the committed file is the product of the command this module
    documents. Written with the csv module's own dialect, so the committed file
    carries its CRLF terminator and `--check` reads it with `newline=""` --
    universal-newline translation would rewrite every row and report a
    difference on every run, which is a check nobody trusts."""
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(COLUMNS)
    for row in rows:
        w.writerow(csv_values(row))
    return buf.getvalue()


def check_table(generated, path):
    """Exit code for `--check`: 0 when this run reproduces `path` exactly."""
    try:
        with open(path, newline="") as f:
            on_disk = f.read()
    except OSError as e:
        print(f"note: {e}", file=sys.stderr)
        return 1
    if generated == on_disk:
        print(f"{os.path.relpath(path, REPO)}: this run reproduces it byte for "
              f"byte ({generated.count(chr(10))} lines)")
        return 0
    print(f"note: {os.path.relpath(path, REPO)} differs from what this run "
          f"produced; the file is the product of the command in this module's "
          f"docstring, so regenerate rather than edit", file=sys.stderr)
    for line in difflib.unified_diff(on_disk.splitlines(),
                                     generated.splitlines(),
                                     "committed", "generated", lineterm="",
                                     n=0):
        print(line, file=sys.stderr)
    return 1


def write_csv(rows):
    w = csv.writer(sys.stdout)
    w.writerow(COLUMNS)
    for row in rows:
        w.writerow(csv_values(row))


