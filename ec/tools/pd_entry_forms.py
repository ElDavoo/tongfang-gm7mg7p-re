from disasm8051 import (OPCODE_LEN, REL_OPCODES, converges_from,      # noqa: E402
                        paged_target, relative_target)
from trace_xdata_refs import PD_MARKER, offset_for_runtime             # noqa: E402

FIRMWARE = os.path.join(EC_DIR, "firmware", "GMxMGxx_11.800")
LISTINGS = os.path.join(EC_DIR, "decompiled", "pd")
INDEX_CSV = os.path.join(EC_DIR, "decompiled", "listing-index.csv")
OUT_CSV = os.path.join(EC_DIR, "annotations", "pd-entry-forms.csv")

# The three index-table tables, and which of them can carry a pd target. Not a
# shortcut: `index-table-entries.csv` and `index-table-spans.csv` are
# `decode_index_table.py` output over the main EC image, and their numbers
# overlap the pd image's at every address. The scope filter below measures it
# from the file offsets they name rather than trusting which tool wrote them.
INDEX_TABLE_CSVS = (
    os.path.join(EC_DIR, "annotations", "index-table-entries.csv"),
    os.path.join(EC_DIR, "annotations", "index-table-spans.csv"),
    os.path.join(EC_DIR, "annotations", "pd-index-table-spans.csv"),
)

PROGRAM = "pd"
PD_REGION = "pd-image"
RET = 0x22

# The pd image's base in the dump, taken from `trace_xdata_refs.REGIONS` rather
# than written out again, because `PD_MARKER` is the *marker's* file offset and
# not the image's: the marker sits 0x40 bytes into a program that starts at
# 0x20000. A runtime address in this program is the offset from here, and using
# the marker instead reads 0x40 bytes early in every one of the 64 KiB -- which
# still decodes, at the wrong address, which is the worst of both.
PD_BASE = offset_for_runtime(0, PD_REGION)
PD_LEN = 0x10000

# The body, half-open. Both ends are named bytes rather than derived numbers:
# 0xE2E4 is the first byte of the listing and 0xE322 the `ret` that terminates
# it, and `--self-test` asserts both against the committed image.
BODY = (0xE2E4, 0xE323)
BODY_FIRST, BODY_LAST = BODY[0], BODY[1] - 1

# An instruction line is `<4 hex addr> <up to 3 byte columns, '-' padded>
# <mnemonic> <operands>`, and only the first column is the address. Anchored at
# the start of the line for the reason the module docstring gives: the operand
# text carries four-hex-digit branch targets of its own.
LINE_RE = re.compile(
    r"^([0-9A-Fa-f]{4})\s+((?:[0-9a-f]{2}|-)\s+(?:[0-9a-f]{2}|-)\s+"
    r"(?:[0-9a-f]{2}|-))\s+(\S.*)$")
# The same shape, deliberately unanchored, for the self-test that says why the
# anchor is there.
LOOSE_ADDR_RE = re.compile(r"[0-9A-Fa-f]{4}")

# The absolute transfer opcodes, {opcode: mnemonic}. The paged pair is keyed on
# `op & 0x1F` and the rel8 family comes from `disasm8051.REL_OPCODES`, so this
# tool enumerates no encoding of its own: a fourth spelling of the map is a
# fourth thing to keep in step with the shared decoder.
ABS_OPCODES = {0x02: "ljmp", 0x12: "lcall"}
# The `cjne` bucket, taken from the shared map rather than re-spelled. The 8051
# encodes `CJNE` at 0xB4-0xBF, and `counter_sweep_entry.py` carries the tuple
# (0xB4, 0xB5, 0xBA, 0xBF) -- an observation of the four opcodes *its* byte scan
# turned up, not the map. Reading 0x0BBA, the rel8 displacement of the
# `cjne R3,#0xFE,0x0BBD` at 0x0BB8, as anything but a `cjne` displacement is the
# error this bucket exists to name, so the set is derived from
# `disasm8051.REL_OPCODES` where all twelve of them live.
CJNE_OPCODES = frozenset(op for op, name in REL_OPCODES.items() if name == "cjne")

# The `status` column's vocabulary, and it is borrowed rather than coined: these
# are `counter_sweep_entry.py`'s SITE_BUCKETS keys, the values that tool already
# writes for the same question -- what this byte is, given the committed
# listings -- asked of a different body. `registers.yaml`'s `status:` values
# are the wrong vocabulary here and the tool says so in its own column heading:
# `confirmed-working` is a live-behaviour claim, and nothing in this repository
# can make one about a PD image on a runner with no machine.
#
#   start    -- the site is an instruction start in a committed listing
#   cjne     -- the rel8 displacement of a `cjne` (0xb4/0xb5/0xba/0xbf), which
#               a byte scan reads as a 3-byte instruction's opcode
#   relative -- the rel8 displacement of another PC-relative branch
#   absolute -- the low target byte of an `ljmp`/`lcall`, the operand is stored
#               high byte first so the low byte is the instruction's last
#   other    -- an immediate operand of an instruction that is not a branch
#   gap      -- in a committed gap, covered by no listing
SITE_STATUSES = ("start", "cjne", "relative", "absolute", "other", "gap")

# The three `target_shape` values, likewise `counter_sweep_entry.py`'s: whether
# the target is an instruction start in a committed listing, and if not, why
# not. A target that is not one is what disqualifies a well-framed call whose
# bytes point inside an instruction.
TARGET_SHAPES = ("instruction-start", "mid-instruction", "no-listing")

COLUMNS = ["form", "population", "site", "file_offset", "site_listing",
           "target", "landing", "origin", "frame_onto", "frame_over",
           "status", "target_shape", "note"]

# The address columns, rendered the way the sibling tables carry them and the
# way a reader is going to paste one into `disasm8051.py --at`: as hex. Written
# as a bare integer a 16-bit address is a decimal number that looks like a file
# offset and is not one, which is the misreading `--self-test` asserts.
HEX_COLUMNS = {"site": 4, "file_offset": 5, "target": 4}


def csv_values(row):
    """One row as the CSV carries it, with the address columns in hex."""
    out = []
    for c in COLUMNS:
        out.append(f"0x{row[c]:0{HEX_COLUMNS[c]}X}" if c in HEX_COLUMNS
                   else row[c])
    return out


