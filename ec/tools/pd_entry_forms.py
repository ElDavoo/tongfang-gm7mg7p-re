def read_listings():
    """(starts, {runtime address: (bytes, text, file)}) for the committed pd
    `.asm` files.

    `counter_sweep_entry.py`'s reader, plus the file each line came from. The
    extra column is the evidence half of the pair this tool reports, and a
    reader that dropped it would leave a candidate naming a site with no way to
    check which committed listing says so."""
    out = {}
    for name in sorted(os.listdir(LISTINGS)):
        if not name.endswith(".asm"):
            continue
        with open(os.path.join(LISTINGS, name), errors="replace") as f:
            for line in f:
                m = LINE_RE.match(line)
                if not m:
                    continue
                out[int(m.group(1), 16)] = (
                    tuple(int(b, 16) for b in m.group(2).split() if b != "-"),
                    m.group(3).rstrip(), f"{PROGRAM}/{name}")
    return sorted(out), out


def owner_of(addr, starts, listings):
    """(owner address, byte index) for the instruction covering `addr`, or
    (None, None) when `addr` is in a committed gap between two listings."""
    lo = bisect.bisect_left(starts, addr)
    if lo < len(starts) and starts[lo] == addr:
        return addr, 0
    if lo == 0:
        return None, None
    owner = starts[lo - 1]
    if lo == len(starts) or owner + len(listings[owner][0]) <= addr:
        return None, None
    return owner, addr - owner


def site_shape(addr, starts, listings):
    """(status, owner, opcode, text, index, listing) for `addr` against the
    committed listings, in `counter_sweep_entry.py`'s SITE_BUCKETS vocabulary."""
    owner, idx = owner_of(addr, starts, listings)
    if owner is None:
        return "gap", None, None, None, None, None
    raw, text, name = listings[owner]
    if idx == 0:
        return "start", owner, raw[0], text, 0, name
    op = raw[0]
    last = idx == OPCODE_LEN[op] - 1
    # `last` is load-bearing, not decoration. The 3-byte forms put an operand
    # byte in the middle, so a displacement is only the *last* byte -- and
    # 0x02/0x12 store their 16-bit operand high byte first, so the low target
    # byte, the one a byte scan reads as the far end of an address, is the last
    # byte too. Without the guard the buckets would swallow bytes no byte scan
    # can mistake for a target.
    if op in CJNE_OPCODES and last:
        return "cjne", owner, op, text, idx, name
    if op in REL_OPCODES and last:
        return "relative", owner, op, text, idx, name
    if op in ABS_OPCODES and last:
        return "absolute", owner, op, text, idx, name
    return "other", owner, op, text, idx, name


# --------------------------------------------------------------------------
# The body, from the listing's own instruction stream
# --------------------------------------------------------------------------

def body_from_listing(listings):
    """(first, last, bytes, gaps) for the routine the committed export carries
    at `BODY_FIRST`: its first instruction, the `ret` that terminates it, the
    concatenation of its instruction bytes, and the address ranges inside the
    span that no committed listing covers.

    Read off the listing rather than off `listing-index.csv`, whose `size`
    column is the byte count and not the extent -- see the module docstring.
    The gaps are returned because the span is not contiguous, and a reader that
    only had `size` would not know there was a hole in the middle of the
    routine rather than assume the routine ended where the count did."""
    starts = sorted(a for a in listings if BODY[0] <= a < BODY[1])
    if not starts:
        raise SystemExit(f"no committed listing instruction inside "
                         f"0x{BODY[0]:04X}-0x{BODY[1] - 1:04X}")
    raw = bytearray()
    gaps, cur = [], None
    for a in starts:
        if cur is not None and a > cur:
            gaps.append((cur, a))
        raw += bytes(listings[a][0])
        cur = a + len(listings[a][0])
    last = starts[-1] + len(listings[starts[-1]][0]) - 1
    return starts[0], last, bytes(raw), gaps


# --------------------------------------------------------------------------
# Transfer forms
# --------------------------------------------------------------------------

def transfers(d, lo, hi, into):
    """Every (site, form, target) whose target lands in `into`, over d[lo:hi].
    `site` and `target` are offsets into `d`, not runtime addresses.

    The three encodings come from `disasm8051`: the 16-bit operand of 0x02/0x12
    stored high byte first, the 2 KiB page an `ajmp`/`acall` computes from the
    *next* PC, and the rel8 displacement measured from the instruction's last
    byte. This is a byte pattern match over the whole window and nothing more --
    it does not know an instruction begins where it begins, which is what the
    listing cross-check is for."""
    out = []
    for i in range(lo, hi):
        op = d[i]
        if op in ABS_OPCODES and i + 3 <= hi:
            target = (d[i + 1] << 8) | d[i + 2]
            if into[0] <= target < into[1]:
                out.append((i, ABS_OPCODES[op], target))
        if (op & 0x1F) in (0x01, 0x11) and i + 2 <= hi:
            name = "ajmp" if op & 0x1F == 0x01 else "acall"
            target = paged_target(op, d[i + 1], i)
            if into[0] <= target < into[1]:
                out.append((i, name, target))
        if op in REL_OPCODES and i + OPCODE_LEN[op] <= hi:
            target = relative_target(op, d[i + OPCODE_LEN[op] - 1], i)
            if into[0] <= target < into[1]:
                out.append((i, REL_OPCODES[op], target))
    return sorted(out)


def listing_transfers(listings, into):
    """The same enumeration over the committed listings' own instruction stream:
    one entry per *decoded* transfer, so no operand byte can appear.

    This is a separate pass rather than a filter on the byte scan because it is
    the narrower of the two claims and the one that can be trusted outright: a
    line in a committed `.asm` is an instruction start, and the listing says so
    without this tool having decided it."""
    out = []
    for addr in sorted(a for a in listings if into[0] <= a < into[1]):
        raw, text, name = listings[addr]
        if not raw:
            continue
        op = raw[0]
        target = None
        if op in ABS_OPCODES and len(raw) >= 3:
            target = (raw[1] << 8) | raw[2]
        elif (op & 0x1F) in (0x01, 0x11) and len(raw) >= 2:
            target = paged_target(op, raw[1], addr)
        elif op in REL_OPCODES and len(raw) == OPCODE_LEN[op]:
            target = relative_target(op, raw[-1], addr)
        if target is not None and into[0] <= target < into[1]:
            form = (ABS_OPCODES.get(op)
                    or ("ajmp" if op & 0x1F == 0x01 else "acall")
                    or REL_OPCODES[op])
            out.append((addr, form, target, text, name))
    return out


def survey(pd, starts, listings):
    """One pass, so the tables, the CSV and --check cannot disagree."""
    rows = []
    for site, form, target in transfers(pd, 0, len(pd), BODY):
        status, owner, sop, stext, sidx, sname = site_shape(site, starts,
                                                            listings)
        t_owner, t_idx = owner_of(target, starts, listings)
        onto, over = converges_from(pd, site)
        rows.append({
            "form": form,
            "population": "listing" if status == "start" else "bytes",
            "site": site,
            "file_offset": PD_BASE + site,
            "site_listing": sname or "",
            "target": target,
            "landing": "first-byte" if target == BODY[0] else "inner",
            "origin": "inside" if BODY[0] <= site < BODY[1] else "outside",
            "frame_onto": onto,
            "frame_over": over,
            "status": status,
            "target_shape": ("instruction-start" if t_idx == 0 else
                             ("no-listing" if t_owner is None
                              else "mid-instruction")),
            "note": note_for(status, owner, sidx, sop, stext, sname,
                             t_owner, t_idx, listings),
        })
    rows.sort(key=lambda r: (r["target"], r["site"]))
    return rows


ORDINAL_SUFFIX = {1: "st", 2: "nd", 3: "rd"}


def ordinal(n):
    """1 -> '1st'. The listing column says which *byte* of an instruction a
    site is, and '2th byte' is the sort of thing that makes a reader distrust
    the column that carries it."""
    suffix = ("th" if 10 <= n % 100 <= 20
              else ORDINAL_SUFFIX.get(n % 10, "th"))
    return f"{n}{suffix}"


def note_for(status, owner, sidx, sop, stext, sname, t_owner, t_idx, listings):
    """The one sentence naming which committed instruction accounts for a
    site, and then for its target.

    Both halves get one, because a candidate that is a displaced reading of the
    committed bytes is only a candidate *because* of it:
    `bank1-e582-entry-framing.md` is the argument, and the alternative decode it
    names is what makes the reading a reading rather than an unsupported site.
    A site in a committed gap gets its target half too, because "nothing here
    covers it" is the weaker half of the answer and the target is often the
    one that settles it."""
    if t_owner is None:
        tail = "no committed listing covers the target either"
    elif t_idx == 0:
        tail = f"the target is an instruction start, `{listings[t_owner][1]}`"
    else:
        tail = (f"the target is the {ordinal(t_idx + 1)} byte of "
                f"`{listings[t_owner][1]}` at 0x{t_owner:04X}")
    if status == "gap":
        return f"no committed listing covers the site; {tail}"
    if status == "start":
        return f"an instruction start in {sname}; {tail}"
    return (f"{ordinal(sidx + 1)} byte of the {OPCODE_LEN[sop]}-byte "
            f"`{stext}` at 0x{owner:04X} in {sname}; {tail}")


def load_index():
    with open(INDEX_CSV, newline="") as f:
        return list(csv.DictReader(f))


def index_row(index, addr):
    for r in index:
        if r["program"] == PROGRAM and int(r["addr"], 16) == addr:
            return r
    return None


# --------------------------------------------------------------------------
# The index tables, with the scope filter measured rather than assumed
# --------------------------------------------------------------------------

def pd_scoped(row, offset_col):
    """Whether a table row names a file offset inside the pd extent.

    Measured from the offset the row carries rather than from which tool wrote
    the file, because the whole subject is that the same 16-bit address means
    two different bytes in two images and only the file offset tells them
    apart. A row with no usable offset is not pd-scoped, and says so."""
    try:
        off = int(row[offset_col], 16)
    except (KeyError, TypeError, ValueError):
        return False
    return PD_BASE <= off < PD_BASE + PD_LEN


def table_rows(pd):
    """(eligible, discarded) rows across the three index-table CSVs, and the
    transfers their bytes spell.

    The whole span of an eligible table is scanned, not just its entries at
    the reader's stride: a dispatch entry this tool cannot frame is exactly the
    case where a narrower read would miss something, and the spans are small."""
    eligible, discarded, found = 0, 0, []
    for path in INDEX_TABLE_CSVS:
        with open(path, newline="") as f:
            for row in csv.DictReader(f):
                col = "table_file_offset" if "table_file_offset" in row \
                    else "entry_file_offset"
                if not pd_scoped(row, col):
                    discarded += 1
                    continue
                eligible += 1
                lo = int(row[col], 16) - PD_BASE
                hi = (int(row["table_end"], 16) - PD_BASE
                      if "table_end" in row else lo + 1)
                for site, form, target in transfers(pd, max(lo, 0),
                                                    min(hi, len(pd)), BODY):
                    found.append((os.path.basename(path), site, form, target))
    return eligible, discarded, sorted(found)


