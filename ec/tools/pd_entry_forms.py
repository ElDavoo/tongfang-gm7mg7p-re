# The answer, as --self-test asserts it. A figure a reader can check against
# the image and the committed listings without running anything.
ORACLE = {
    "body_span": 63,
    "listing_bytes": 28,
    "index_size": 28,
    "gap": (0xE2F8, 0xE31B),
    "candidates": 11,
    "external": 3,
    "external_first_byte": 1,
    "external_inner": 2,
    "entry": (0xDA78, 0xE2E4, "lcall"),
    "inner": ((0x0BBA, 0xE322, "ljmp", "cjne"),
              (0xE68B, 0xE2EF, "ajmp", "gap")),
    "eligible_table_rows": 28,
    "table_transfers": 0,
    "listings_covering_body": 1,
}


def self_test(d, index, starts, listings, rows, first, last, raw, gaps,
              eligible, discarded, found) -> int:
    bad = 0

    def check(ok, text):
        nonlocal bad
        if not ok:
            bad += 1
        print(f"  {'ok  ' if ok else 'FAIL'}  {text}")

    print("pd_entry_forms.py --self-test")

    # The two vocabularies are borrowed, so the check is that this tool stayed
    # inside them: a `status` a reader has not seen in
    # `counter_sweep_entry.py`'s table would make the CSV unreadable against it,
    # and a value invented here is the thing a second copy of a map invites.
    check(all(r["status"] in SITE_STATUSES for r in rows)
          and all(r["target_shape"] in TARGET_SHAPES for r in rows)
          and {r["status"] for r in rows} <= set(SITE_STATUSES),
          f"every row's status and target_shape is a value of "
          f"{SITE_STATUSES} and {TARGET_SHAPES} -- the vocabularies "
          f"`counter_sweep_entry.py` already writes, not a second set of names")

    check(d[PD_BASE + first] != RET and d[PD_BASE + last] == RET
          and last - first + 1 == ORACLE["body_span"],
          f"the body is 0x{first:04X}-0x{last:04X}, {ORACLE['body_span']} bytes, "
          f"ending in 0x{RET:02X} (`ret`) and not beginning with one")

    row = index_row(index, first)
    check(len(raw) == ORACLE["listing_bytes"]
          and row is not None and int(row["size"]) == ORACLE["index_size"],
          f"the listing's instruction bytes sum to {ORACLE['listing_bytes']} and "
          f"listing-index.csv records size={ORACLE['index_size']} for "
          f"{PROGRAM},0x{first:04X} -- equal, and not the span")

    check(gaps == [ORACLE["gap"]]
          and d[PD_BASE + ORACLE["gap"][0]:PD_BASE + ORACLE["gap"][1]] ==
          b"\xea\x12\xb1\x68\xe0\xfe\xa3\xe0\xff\x64\x01\x4e\x60\x15\xef\xf4"
          b"\x70\x03\xee\x64\x01\x60\x0c\xef\xf4\x70\x03\xee\x64\x02\x60\x03"
          b"\x7f\x00\x22",
          f"and the span is not contiguous: {ORACLE['gap'][1] - ORACLE['gap'][0]} "
          f"bytes at 0x{ORACLE['gap'][0]:04X}-0x{ORACLE['gap'][1] - 1:04X} are in "
          f"no committed listing, which is what reading `size` as an extent hides")

    body_lists = {listings[owner_of(x, starts, listings)[0]][2]
                  for x in range(BODY[0], BODY[1])
                  if owner_of(x, starts, listings)[0] is not None}
    check(body_lists == {f"{PROGRAM}/E2E4.asm"}
          and len(body_lists) == ORACLE["listings_covering_body"],
          f"exactly {ORACLE['listings_covering_body']} committed listing covers "
          f"any address in 0x{BODY[0]:04X}-0x{BODY[1] - 1:04X}, and it is "
          f"{sorted(body_lists)[0]}")

    external = [r for r in rows if r["origin"] == "outside"]
    check(len(rows) == ORACLE["candidates"] and len(external) == ORACLE["external"],
          f"{ORACLE['candidates']} candidate(s) by byte scan, "
          f"{ORACLE['external']} of them outside the body")

    site, target, form = ORACLE["entry"]
    entry = [r for r in rows if r["site"] == site and r["target"] == target]
    check(len(entry) == 1 and entry[0]["form"] == form
          and entry[0]["status"] == "start"
          and entry[0]["landing"] == "first-byte"
          and entry[0]["target_shape"] == "instruction-start"
          and entry[0]["population"] == "listing",
          f"exactly one candidate is a committed instruction start, and it is "
          f"`{form} 0x{target:04X}` at 0x{site:04X} landing on the body's first "
          f"byte")

    inner = sorted((r for r in external if r["landing"] == "inner"),
                   key=lambda r: r["site"])
    check(len(inner) == ORACLE["external_inner"]
          and [(r["site"], r["target"], r["form"], r["status"]) for r in inner]
          == [tuple(t) for t in ORACLE["inner"]],
          f"the {ORACLE['external_inner']} candidates landing strictly inside "
          f"are 0x{inner[0]['site']:04X} -> 0x{inner[0]['target']:04X} "
          f"({inner[0]['form']}, {inner[0]['status']}) and "
          f"0x{inner[1]['site']:04X} -> 0x{inner[1]['target']:04X} "
          f"({inner[1]['form']}, {inner[1]['status']}) -- one accounted for by a "
          f"committed instruction, one in no listing at all")

    check([r["target_shape"] for r in inner] == ["instruction-start",
                                                  "mid-instruction"],
          "and the two targets read differently against the committed listings: "
          "0xE322 is an instruction start (the `ret` that ends the body) while "
          "0xE2EF is the second byte of the `mov B,#0x60` at 0xE2EE, so the "
          "first is retired by the *site* half and the second by the target "
          "half -- which is why the pair is reported and neither half alone")

    listed = listing_transfers(listings, BODY)
    listed_sites = {a for a, _f, _t, _x, _n in listed}
    check(listed_sites <= {r["site"] for r in rows if r["status"] == "start"},
          f"the listing population ({len(listed)} transfer(s) in committed "
          f"pd listings targeting the body) is a subset of the byte population, "
          f"which is what makes the two comparable")

    check(eligible == ORACLE["eligible_table_rows"] and not found,
          f"{eligible} index-table row(s) are pd-scoped and {discarded} are not, "
          f"and no byte of an eligible table spells a transfer into the body")

    # The two silent misreadings, asserted rather than described.
    sample = f"E2EC     60 2d -  jz       0xe31b"
    loose = LOOSE_ADDR_RE.findall(sample)
    anchored = LINE_RE.match(sample)
    check(len(loose) == 2 and loose[0] == "E2EC" and loose[1] == "e31b"
          and anchored is not None and anchored.group(1) == "E2EC",
          f"the listing regex: an unanchored four-hex-digit search on one "
          f"instruction line returns the branch target as well as the address "
          f"({loose}, and {loose[1]} is an operand, not a second instruction), "
          f"so the parse is anchored at the line start")

    head_off = offset_for_runtime(BODY[0], PD_REGION)
    right_listing = os.path.join(LISTINGS, f"{BODY[0]:04X}.asm")
    wrong_listing = os.path.join(LISTINGS, f"{head_off:05X}.asm")
    check(head_off == PD_BASE + BODY[0] and head_off != PD_MARKER[0]
          and os.path.isfile(right_listing) and not os.path.isfile(wrong_listing),
          f"the path index: runtime 0x{BODY[0]:04X} is file 0x{head_off:05X}, so "
          f"the listing is {PROGRAM}/{BODY[0]:04X}.asm and "
          f"{PROGRAM}/{head_off:05X}.asm does not exist -- keying listings by "
          f"the file offset reports all {len(rows)} candidates unframed. Note "
          f"the base is 0x{PD_BASE:05X} and not PD_MARKER's "
          f"0x{PD_MARKER[0]:05X}, which is the marker inside the image")

    check(d[BODY[0]:BODY[1]] != d[PD_BASE + BODY[0]:PD_BASE + BODY[1]],
          f"and slicing the {len(d) // 1024} KiB dump at [0x{BODY[0]:04X}:"
          f"0x{BODY[1]:04X}] reads the main EC's common area, not this program "
          f"-- different bytes, and both decode")

    print()
    print("self-test FAILED" if bad else "self-test passed")
    return 1 if bad else 0


