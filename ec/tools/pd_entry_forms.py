def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("firmware", nargs="?", default=FIRMWARE,
                    help="raw EC firmware image (default: the committed one)")
    ap.add_argument("--csv", action="store_true",
                    help="write one row per candidate on stdout")
    ap.add_argument("--check", action="store_true",
                    help="regenerate ../annotations/pd-entry-forms.csv and diff it")
    ap.add_argument("--self-test", action="store_true",
                    help="assert the body, the entry set, the inner candidates "
                         "and the two path/regex misreadings against the "
                         "committed tree")
    args = ap.parse_args(argv)

    d = open(args.firmware, "rb").read()
    off, magic = PD_MARKER
    if d[off:off + len(magic)] != magic:
        print(f"no {magic.decode()!r} marker at file 0x{off:05X} -- this is "
              f"not the image the recorded counts were taken from",
              file=sys.stderr)
        return 1
    pd = d[PD_BASE:PD_BASE + PD_LEN]

    starts, listings = read_listings()
    index = load_index()
    first, last, raw, gaps = body_from_listing(listings)
    rows = survey(pd, starts, listings)
    eligible, discarded, found = table_rows(pd)

    if args.self_test:
        return self_test(d, index, starts, listings, rows, first, last, raw,
                         gaps, eligible, discarded, found)

    if args.csv:
        write_csv(rows)
        return 0

    if args.check:
        return check_table(csv_table(rows), OUT_CSV)

    print_body(pd, index, first, last, raw, gaps)
    print_candidates(rows)
    print_tables(eligible, discarded, found)
    print_verdict(rows)
    return 0


if __name__ == "__main__":
    sys.exit(main())
