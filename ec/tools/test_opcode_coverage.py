class TheManualOracle(unittest.TestCase):
    """The third oracle, and the question it exists to answer.

    Ghidra and r2 are not two independent readings of the opcode map: they
    share a lineage, and `docs/findings.md` already records where that lineage
    departs from the manual. So a 0-disagreements figure against both of them
    cannot distinguish "two decoders corroborate this row" from "one decoder's
    map, counted twice" -- the rows have to be compared against the manual as
    well, and a row the manual assigns *nothing* has to come out as a third
    state rather than a green one.

    Which is what these cases check, and -- just as much -- that the manual
    oracle can *fail*. A third comparison that can only ever agree is not an
    oracle, and 0 disagreements from a table transcribed by the same hand as
    the write-up would be worth nothing.
    """

    # Rows pinned from the MCS-51 instruction set rather than from
    # `disasm8051.OPCODE_LEN`, so this is a check and not a tautology: if the
    # two ever disagree, these say which transcription is wrong. Chosen to span
    # every length class and every block boundary the 16-entry rows have --
    # a literal 256 bytes copied wrong once will not pass all of them.
    SPOT_CHECKS = {
        0x00: 1,   # nop
        0x02: 3,   # ljmp addr16
        0x10: 3,   # jbc bit,rel   -- the 3-byte bit form next to the 1-byte
        0x13: 1,   # rrc a            block, which is where a slip shows
        0x30: 3,   # jnb bit,rel
        0x43: 3,   # orl direct,#data
        0x75: 3,   # mov direct,#data
        0x82: 2,   # anl c,bit
        0x85: 3,   # mov direct,#data
        0x90: 3,   # mov dptr,#data16
        0x94: 2,   # subb a,#data
        0x95: 2,   # subb a,direct
        0x96: 1,   # subb a,@r0    -- the whole 0x9X row: 2, 2, 1, 1, 1 is a
        0x97: 1,   # subb a,@r1       transcription error that a spot check
        0x98: 1,   # subb a,r0        on only the ends of it cannot see
        0xB4: 3,   # cjne a,#data,rel
        0xB5: 3,   # cjne a,direct,rel
        0xC0: 2,   # push direct
        0xC1: 2,   # clr bit -- the row disasm8051.py states from the manual
        0xD5: 3,   # djnz direct,rel
        0xD8: 2,   # djnz r7,rel   -- 2, while the row above is 3
        # **0xA8-0xAF is here because it is the row this table got wrong
        # twice.** The transcription carried 2 across the whole block, a
        # byte-for-byte copy of the 0x78 row (`mov r0,#data`); a correction
        # then set it to 1, on the reading that the block is `XCH A,Rn` --
        # which is the instruction at 0xC8-0xCF, not here. `0xA8`-`0xAF` is
        # `MOV Rn,direct`, 2 bytes, and the committed corpus frames it that
        # way at every instruction start. Both wrong versions are in the
        # write-up beside the one this table now carries.
        #
        # The 0xC8 row is pinned below for the same reason and is what makes
        # the pair readable: `XCH A,Rn` at 1 there and `MOV Rn,direct` at 2
        # here, in one table, so a slip between the two rows is visible.
        0xA8: 2,   # mov r0,direct -- 2; 0xC8 below is the XCH A,Rn at 1
        0xAF: 2,   # mov r7,direct -- 2; the 0x78 row's mirror image
        0xC8: 1,   # xch a,r0      -- 1, and this is where XCH A,Rn lives
        0xE4: 1,   # clr a
        0xE5: 2,   # mov a,direct
        0xF4: 1,   # cpl a
        0xF5: 2,   # mov direct,a
    }

    def test_the_spot_checked_rows_are_what_the_manual_says(self):
        for op, want in sorted(self.SPOT_CHECKS.items()):
            self.assertEqual(want, C.MCS51_LEN[op],
                             "MCS51_LEN[0x%02X] disagrees with the manual" % op)

    def test_the_table_covers_every_opcode_value(self):
        self.assertEqual(256, len(C.MCS51_LEN))
        # No length outside the three the instruction set can produce.
        self.assertTrue(all(0 <= n <= 3 for n in C.MCS51_LEN))

    def test_exactly_one_value_is_unassigned_and_it_is_0xa5(self):
        # Stated as the exact set, not a count: a second accidental 0 would
        # still satisfy a length test, and a 0 is the one entry in this table
        # that means "no opinion" rather than a number. It was three rows until
        # `0x96`/`0x97` were given the `SUBB A,@Ri` lengths the MCS-51 map
        # assigns them; the write-up carries the correction.
        self.assertEqual((0xA5,), C.MANUAL_UNASSIGNED)

    def test_the_real_table_and_the_manual_now_agree_on_every_row(self):
        # **This used to be eight disagreements, and the eight were the
        # finding.** `MCS51_LEN` was transcribed with `2` across `0xA8`-`0xAF`,
        # a byte-for-byte copy of the `0x78` row; a later correction set it to
        # `1`, on the reading that the block is `XCH A,Rn` -- the instruction
        # at `0xC8`-`0xCF`, which this table still carries at 1. The block is
        # `MOV Rn,direct`, two bytes, and the committed corpus frames it that
        # way at every instruction start (`a8af_operand_role.py`).
        #
        # So the oracle's zero is now 255 rows of corroboration rather than 247
        # plus eight of echo, and this asserts it -- with the eight rows still
        # *named* by `corrected_manual_rows()` rather than simply gone, since a
        # corrected row and a row that was never in question look identical
        # from the outside.
        self.assertEqual([], C.manual_divergences())
        self.assertEqual([(op, 0xA8, 0xAF) for op in range(0xA8, 0xB0)],
                         [(op, lo, hi) for op, lo, hi in
                          C.corrected_manual_ranges()])

    def test_the_corrected_block_agrees_with_the_real_table(self):
        # The point of the correction: the block must not be reported as a
        # disagreement *and* not quietly dropped. Asserted as a relation
        # between the two tables, so a future transcription slip in either
        # direction fails here rather than in a `--divergence` exit code nobody
        # is watching.
        for lo, hi, _why in C.CORRECTED_MANUAL_ROWS:
            for op in range(lo, hi + 1):
                self.assertEqual(C.MCS51_LEN[op], D.OPCODE_LEN[op],
                                 "0x%02X" % op)

    def test_a_patched_table_is_found_by_the_manual_too(self):
        # The oracle has to be able to fail. Patch one row the manual assigns
        # (`ljmp`, 3 bytes) and one row it does not (`0xA5`, no entry): only
        # the first may come back, and its reported length must be the manual's.
        wrong = bytearray(D.OPCODE_LEN)
        wrong[0x02] = 2
        wrong[0xA5] = 3
        self.assertEqual([(0x02, 2, 3)], C.manual_divergences(opcode_len=bytes(wrong)))

    def test_divergence_exits_zero_on_an_unmodified_tree(self):
        # The issue's acceptance test, and a property rather than a figure:
        # the three oracles agree on every row, so the mode exits 0 -- while
        # still *naming* the rows a correction settled, which is the half that
        # is easy to lose and the reason `--divergence` is not simply a
        # disagreement counter.
        #
        # Runs against the committed corpus rather than a fixture: this is the
        # one case whose subject is the tree as it stands, and the point is
        # that nothing about an ordinary merge turns the mode red.
        err, out = io.StringIO(), io.StringIO()
        old_err, old_out = sys.stderr, sys.stdout
        try:
            sys.stderr, sys.stdout = err, out
            rc = C.main(["--divergence"])
        finally:
            sys.stderr, sys.stdout = old_err, old_out
        said = out.getvalue()
        self.assertEqual(0, rc, said)
        self.assertIn("had wrong and no longer does", said)
        # Named, and named by range, so the report does not print the same
        # sentence eight times.
        self.assertIn("0xa8-0xaf", said)

    def test_an_unassigned_row_is_neither_agreement_nor_disagreement(self):
        # The whole reason the column is tri-state. 0xA5's table length is 1
        # and the manual has nothing to say; folding that into True is the
        # overclaim, and folding it into False is the "found and wrong" the
        # calibration rule forbids.
        rows, _ = _read()
        table = {r["hex"]: r for r in
                 C.coverage_rows(rows, corpus=_empty_corpus())}
        self.assertIsNone(table["0xa5"]["manual_len"])
        self.assertIsNone(table["0xa5"]["manual_agrees"])
        # And a row the manual does assign, as the control: the states differ.
        self.assertEqual(3, table["0x02"]["manual_len"])
        self.assertTrue(table["0x02"]["manual_agrees"])
        # 0x96/0x97 were the rows this used to check, on a transcription that
        # read the manual's `X a,@Ri` family as stopping at 0x66. It does not:
        # the 0x90-0x9F row carries all eight SUBB forms, so these two are
        # ordinary assigned rows now and must read as one.
        for hexop in ("0x96", "0x97"):
            self.assertEqual(1, table[hexop]["manual_len"], hexop)
            self.assertTrue(table[hexop]["manual_agrees"], hexop)

    def test_the_rows_nothing_corroborates_are_reported_as_such(self):
        # The one row, with the listing-start count that makes the row a
        # finding rather than a footnote. On the fixture 0xA5 appears nowhere,
        # which is the "not found by this method" case and must not be counted
        # as agreement either.
        rows, _ = _read()
        shared = C.shared_map_rows(C.coverage_rows(rows,
                                                   corpus=_empty_corpus()))
        self.assertEqual(["0xa5"], [r["hex"] for r in shared])
        self.assertTrue(all(r["listing_starts"] == 0 for r in shared))


def _fake_r2(body):
    d = tempfile.mkdtemp()
    p = os.path.join(d, "r2")
    with open(p, "w") as fh:
        fh.write("#!/bin/sh\ncat <<'EOF'\n%s\nEOF\n" % body)
    os.chmod(p, 0o755)
    return p


