SETUP_GUID = "EC87D643-EBA4-4BB5-A1E5-3F3E36B20DA9"
CPUSETUP_GUID = "B08F97FF-E6E8-4193-A997-5E9E9B0ADB32"
UNIWILL_GUID = "9F33F85C-13CA-4FD1-9C4A-96217722C593"


class TreeCase(unittest.TestCase):
    """A listing tree in a temporary directory, built from inline listings."""

    def setUp(self):
        self.root = tempfile.mkdtemp(prefix="setup_offset_xrefs_")
        self.addCleanup(shutil.rmtree, self.root, True)
        self.listings = os.path.join(self.root, "listings")
        os.makedirs(self.listings)
        with open(os.path.join(self.root, "load-map.csv"), "w") as fh:
            fh.write("program,kind,image_bytes,image_sha256,load_addr,entry\n")

    def add_module(self, name, listings):
        """Write `listings` into the tree, and name the module in the load map."""
        directory = os.path.join(self.listings, name)
        os.makedirs(directory)
        for fname, body in listings.items():
            with open(os.path.join(directory, fname), "w") as fh:
                fh.write(body)
        with open(os.path.join(self.root, "load-map.csv"), "a") as fh:
            fh.write("%s,PE32,1,deadbeef,,0x0\n" % name)

    def run_tool(self, *argv):
        """main()'s output and exit code, over the temporary tree."""
        buf = io.StringIO()
        args = list(argv) + ["--listings", self.listings,
                             "--loadmap", os.path.join(self.root, "load-map.csv")]
        with redirect_stdout(buf):
            code = xrefs.main(args)
        return buf.getvalue(), code


def listing(module, func, body):
    """A listing file's text, with the header the exporter writes."""
    return ("; %s @ 00000100   %s\n"
            "; Ghidra 12.1.3 disassembly, generated by a test -- do not edit.\n"
            "; Source: none\n"
            "; This is the machine code. The decompiled C for this address is\n"
            "; 00000100.c in the same tree; where the two disagree, this file is\n"
            "; right and the C is a reading of it.\n\n" % (module, func)
            + body)


def getvar_frame(module, func, guid, size, access=None):
    """A function that reads one variable and touches `access`.

    The five-argument `GetVariable` shape: handle, GUID pointer, attributes,
    size pointer, data buffer at `[RSP + 0x20]`. The GUID and size slots sit
    below the buffer so that building them is not itself an access into it.
    `access` is appended after the call and is the instruction whose offset
    the tool should place.
    """
    words = xrefs.guid_to_dwords(guid)
    lines = [
        "00000100 48 8d ac 24 f0 ff ff - - -    lea      RBP, [RSP + -0x110]",
        "00000107 48 83 ec 00 01 00 00 - - -    sub      RSP, 0x100",
        "0000010d 48 8d 44 24 40 - - - - -    lea      RAX, [RSP + 0x40]",
        "00000112 48 89 44 24 20 - - - - -    mov      qword ptr [RSP + 0x20], RAX",
        "00000117 4c 8d 4c 24 f0 - - - - -    lea      R9, [RSP + -0x10]",
        "0000011c 48 c7 44 24 f0 f0 00 00 00  mov      qword ptr [RSP + -0x10], 0x%x"
        % size,
        "00000124 48 8d 54 24 e0 - - - - -    lea      RDX, [RSP + -0x20]",
    ]
    addr = 0x160
    for i, word in enumerate(words):
        lines.append("%08x c7 44 24 %02x %02x %02x %02x %02x  mov      "
                     "dword ptr [RSP + -0x%x], 0x%x"
                     % (addr, 0xE0 - 4 * i,
                        word & 0xFF, (word >> 8) & 0xFF,
                        (word >> 16) & 0xFF, (word >> 24) & 0xFF,
                        0x20 - 4 * i, word & 0xFFFFFFFF))
        addr += 8
    lines += [
        "00000190 48 8b 05 b0 0f 00 00 - - -    mov      RAX, qword ptr [0x1000]",
        "00000197 ff 50 48 - - - - - - - -      call     qword ptr [RAX + 0x48]",
    ]
    if access:
        lines.append(access)
    return listing(module, func, "\n".join(lines) + "\n")


