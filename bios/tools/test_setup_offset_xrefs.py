# --------------------------------------------------------------------------
# The committed tree, and the answers the write-up cites
# --------------------------------------------------------------------------

class CommittedTests(unittest.TestCase):
    """The published facts, re-derived from the committed listings."""

    def listing(self, *parts):
        return os.path.join(xrefs.DEFAULT_LISTINGS, *parts)

    def sites(self, *parts):
        _m, func, sites, _un = xrefs.analyse_listing(self.listing(*parts))
        return func, sites

    def test_setup_0x7d7_is_the_write_docs_findings_publishes(self):
        # docs/findings.md section 8: `OemOcDxe`'s `SyncOcVariables` copies
        # `UniWillVariable[0x33]` into `Setup[0x7D7]`, at `[RBP + 0xab7]`
        # against a `[RBP + 0x2e0]` buffer. Found by subtraction, not restated.
        func, sites = self.sites("OemOcDxe", "000007A8.asm")
        self.assertEqual(func, "SyncOcVariables")
        hits = [s for s in sites if any(o == 0x7D7 for o, _w in s.offsets)]
        self.assertTrue(hits, "Setup[0x7D7] resolved to nothing")
        for site in hits:
            for (off, _w), accesses in site.offsets.items():
                if off == 0x7D7:
                    self.assertTrue(any(is_dst for _a, is_dst in accesses),
                                    "the published access is a store")

    def test_the_oc_module_reads_cpusetup_and_setup_by_their_guids(self):
        _func, sites = self.sites("OemOcDxe", "000007A8.asm")
        named = sorted({s.named[0] for s in sites if s.guid})
        self.assertEqual(named, ["CpuSetup", "Setup"])

    def test_the_committed_listing_tree_has_no_module_without_a_name(self):
        # A listing whose header did not parse would silently drop its module
        # from every table, so each module is checked to appear at least once.
        seen = set()
        for prog in xrefs.read_load_map(xrefs.DEFAULT_LOADMAP):
            directory = os.path.join(xrefs.DEFAULT_LISTINGS, prog)
            if not os.path.isdir(directory):
                continue
            for name in sorted(os.listdir(directory)):
                if not name.endswith(".asm"):
                    continue
                module, _f, _s, _u = xrefs.analyse_listing(
                    os.path.join(directory, name), prog)
                seen.add(module)
        self.assertTrue(seen)
        self.assertNotIn("?", seen)

    def test_check_passes_over_the_committed_tree(self):
        buf = io.StringIO()
        with redirect_stdout(buf):
            code = xrefs.main(["--check"])
        self.assertEqual(code, 0, buf.getvalue())

    def test_self_test_passes(self):
        buf = io.StringIO()
        with redirect_stdout(buf):
            code = xrefs.main(["--self-test"])
        self.assertEqual(code, 0, buf.getvalue())

    def test_the_charge_offsets_the_issue_names_are_the_ones_queried(self):
        # The bare run answers the issue's question, so the default query set
        # has to be those offsets rather than a convenient subset.
        self.assertEqual(
            sorted(xrefs.CHARGE_OFFSETS),
            sorted([("Setup", 0x4F3), ("Setup", 0x3D2), ("Setup", 0x65D),
                    ("CpuSetup", 0xC3), ("UniWillVariable", 0x30),
                    ("UniWillVariable", 0x31), ("UniWillVariable", 0x32)]))

    def test_setup_is_marked_as_the_form_engine(self):
        # The scoping is in the output rather than in a note, because a reader
        # in `Setup` is the form engine's own store and not a charge consumer.
        self.assertEqual(xrefs.FORM_ENGINE, "Setup")
        buf = io.StringIO()
        with redirect_stdout(buf):
            xrefs.main(["--offset", "Setup:0x4F3"])
        self.assertIn("HII form engine", buf.getvalue())


