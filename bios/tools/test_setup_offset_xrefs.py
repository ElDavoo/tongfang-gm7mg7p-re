class GuidTests(unittest.TestCase):
    """`guid_from_dwords`, which is where mixed-endian goes wrong."""

    def test_the_setup_guid_from_its_own_immediates(self):
        self.assertEqual(
            xrefs.guid_from_dwords([0xec87d643, 0x4bb5eba4, 0x3e3fe5a1, 0xa90db236]),
            SETUP_GUID)

    def test_the_cpusetup_guid_from_its_own_immediates(self):
        self.assertEqual(
            xrefs.guid_from_dwords([0xb08f97ff, 0x4193e6e8, 0x9e5e97a9, 0x32db0a9b]),
            CPUSETUP_GUID)

    def test_a_partial_guid_is_none_rather_than_a_half_one(self):
        # Half a GUID is not a GUID, and returning the half would let a site
        # with three of four stores match a store on a coincidence.
        self.assertIsNone(xrefs.guid_from_dwords([0xec87d643, 0x4bb5eba4,
                                                  None, 0xa90db236]))
        self.assertIsNone(xrefs.guid_from_dwords([0xec87d643]))
        self.assertIsNone(xrefs.guid_from_dwords([]))

    def test_the_three_fields_are_not_all_little_endian(self):
        # Data3 is big-endian inside the second dword: reading it little-endian
        # gives 4BB5 as B54B, which is a plausible-looking wrong answer.
        words = xrefs.guid_to_dwords(SETUP_GUID)
        self.assertEqual(words, [0xec87d643, 0x4bb5eba4, 0x3e3fe5a1, 0xa90db236])

    def test_round_trip(self):
        for name, var in sorted(xrefs.VARIABLES.items()):
            self.assertEqual(
                xrefs.guid_from_dwords(xrefs.guid_to_dwords(var["guid"])),
                var["guid"], name)

    def test_the_sizes_the_table_holds_are_the_ifr_dumps(self):
        # Not a count of anything: a per-store property, and the one a
        # regenerated dump would move.
        want = {"Setup": 0x7D8, "CpuSetup": 0x2BB, "SetupVolatileData": 0x97}
        for store, size in sorted(want.items()):
            self.assertEqual(xrefs.VARIABLES[store]["size"], size, store)


