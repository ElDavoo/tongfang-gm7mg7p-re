"""Offline checks for `setup_offset_xrefs.py`: its frame arithmetic, its
refusals, and the charge-offset answers its write-up rests on.

Two halves, and the split is the point. The first drives the tool's own
`main()` over hand-built listings in a temporary tree, where every answer is
known because the fixture was written to be known -- which is the only way to
pin the parts that are easy to get subtly wrong and that the committed
listings cannot reveal, because they have no second answer to check against.
The second reads the committed tree and asserts the facts
`docs/findings/setup-charge-offset-readers.md` cites, so a re-export that
moved a site fails here rather than quietly changing what the write-up says.

Both halves read committed text. Nothing here opens the ROM, runs Ghidra or
UEFIExtract, or reads a setup variable, and no case is a claim about what this
machine's firmware does at runtime.
"""
