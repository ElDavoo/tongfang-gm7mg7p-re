class NamingTests(unittest.TestCase):
    """`name_for` and `sites_for`, which decide what a row is allowed to claim."""

    def test_a_guid_and_a_size_name_one_store(self):
        self.assertEqual(
            xrefs.name_for(SETUP_GUID, 0x7D8), ("Setup", "guid+size"))

    def test_the_two_stores_sharing_a_guid_are_told_apart_by_size(self):
        # `Setup` and `SetupVolatileData` share EC87D643-..., so the size is
        # the only thing that separates them.
        self.assertEqual(xrefs.name_for(SETUP_GUID, 0x97)[0], "SetupVolatileData")
        self.assertEqual(xrefs.name_for(SETUP_GUID, 0x7D8)[0], "Setup")

    def test_a_guid_with_no_size_names_both_stores_it_could_be(self):
        # Assigning it to one on sort order would be a wrong answer rather than
        # a missing one, so neither table may claim it.
        name, how = xrefs.name_for(SETUP_GUID, None)
        self.assertEqual(name, "Setup/SetupVolatileData")
        self.assertIn("no size", how)

    def test_a_size_alone_is_not_enough_to_name_a_store(self):
        name, how = xrefs.name_for(None, 0xB4)
        self.assertEqual(name, "UniWillVariable")
        self.assertTrue(how.startswith("size only"))

    def test_a_size_only_site_is_left_out_of_the_store_tables(self):
        # It is not evidence about `UniWillVariable` specifically, so a row
        # under that heading would claim more than the listing shows.
        site = xrefs.Site(0x100, "RAX", None, 0xB4, -0xC0)
        self.assertEqual(xrefs.sites_for([site], "UniWillVariable"), [])

    def test_a_shared_guid_site_is_left_out_of_both_tables(self):
        site = xrefs.Site(0x100, "RAX", SETUP_GUID, None, -0xC0)
        self.assertEqual(xrefs.sites_for([site], "Setup"), [])
        self.assertEqual(xrefs.sites_for([site], "SetupVolatileData"), [])

    def test_a_guid_and_size_site_is_in_its_table(self):
        site = xrefs.Site(0x100, "RAX", SETUP_GUID, 0x7D8, -0xC0)
        self.assertEqual(xrefs.sites_for([site], "Setup"), [site])


