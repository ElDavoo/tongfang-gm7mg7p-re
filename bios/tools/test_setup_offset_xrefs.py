class BaseTests(TreeCase):
    """The arithmetic, on listings whose offsets are known by construction."""

    #: The frame every fixture here is built in. `lea RBP, [RSP + -0x110]`
    #: then `sub RSP, 0x100` leaves RSP at -0x100, so a buffer based at
    #: `[RSP + 0x40]` sits at -0xC0 and `[RSP + 0x533]` is offset 0x4F3 of it.
    RSP = -0x100
    BUF_DISP = 0x40
    BASE = RSP + BUF_DISP
    OFF_4F3 = RSP + 0x533 - BASE

    def test_an_rsp_relative_base_gives_the_offset_by_subtraction(self):
        self.assertEqual(self.OFF_4F3, 0x4F3)
        self.add_module("OemFake", {
            "00000100.asm": getvar_frame(
                "OemFake", "fake_reader", SETUP_GUID, 0x7D8,
                access="00000199 80 bc 24 33 05 00 00 - - -    cmp      "
                       "byte ptr [RSP + 0x533], 0x1")})
        out, _code = self.run_tool("--offset", "Setup:0x4F3")
        self.assertIn("OemFake/00000100.asm", out)
        self.assertIn("reads", out)
        self.assertNotIn("no reader found", out)

    def test_an_rbp_relative_base_gives_the_same_offset(self):
        # `OemOcDxe` uses this form; a method that only handled the RSP one
        # would find nothing in the module the known answer lives in.
        #
        # The GUID and size slots sit at `[RBP - 0x40]` and below rather than
        # at `[RBP - 0x20]`: with this prologue `RBP - 0x20` and `[RSP + 0x20]`
        # are the *same* frame address, so a GUID store there would land on
        # the fifth argument and the base would be lost. A fixture that hid
        # that collision would be testing a function no compiler emits.
        body = (
            "00000100 55 - - - - - - - - -          push     RBP\n"
            "00000101 48 8d ac 24 40 fe ff ff - - -  lea      RBP, [RSP + -0x1c0]\n"
            "00000108 48 81 ec 00 02 00 00 - - - -  sub      RSP, 0x200\n"
            "0000010e 48 8d 85 e0 02 00 00 - - - -  lea      RAX, [RBP + 0x2e0]\n"
            "00000115 48 89 44 24 20 - - - - -    mov      qword ptr [RSP + 0x20], RAX\n"
            "0000011a 4c 8d 8d d0 fd ff ff - - - -  lea      R9, [RBP + -0x30]\n"
            "00000121 48 c7 85 d0 fd ff ff d8 07 00  mov      qword ptr [RBP + -0x30], 0x7d8\n"
            "0000012b 48 8d 95 c0 fd ff ff - - - -  lea      RDX, [RBP + -0x40]\n"
            "00000132 c7 85 c0 fd ff ff 43 d6 87 ec  mov      dword ptr [RBP + -0x40], 0xec87d643\n"
            "0000013c c7 85 c4 fd ff ff a4 eb b5 4b  mov      dword ptr [RBP + -0x3c], 0x4bb5eba4\n"
            "00000146 c7 85 c8 fd ff ff a1 e5 3f 3e  mov      dword ptr [RBP + -0x38], 0x3e3fe5a1\n"
            "00000150 c7 85 cc fd ff ff 36 b2 0d a9  mov      dword ptr [RBP + -0x34], 0xa90db236\n"
            "0000015a 48 8b 05 b0 0f 00 00 - - -    mov      RAX, qword ptr [0x1000]\n"
            "00000161 ff 50 48 - - - - - - - -      call     qword ptr [RAX + 0x48]\n"
            "00000164 80 bd d3 07 00 00 00 00 00 -  cmp      byte ptr [RBP + 0x7d3], 0x1\n")
        self.add_module("OemFakeRbp", {"00000100.asm": listing("OemFakeRbp",
                                                              "rbp_reader", body)})
        out, _code = self.run_tool("--offset", "Setup:0x4F3")
        self.assertIn("OemFakeRbp/00000100.asm", out)
        self.assertNotIn("no reader found", out)

    def test_a_mov_rbp_rsp_frame_recovers_the_guid(self):
        # The other common x64 prologue, and the one `OemGlobalNvsDxe` uses.
        # `mov RBP, RSP` is not a `lea`, so a frame model that only handles the
        # `lea` leaves `frame.rbp` None for the whole function: every
        # `[RBP + disp]` operand is untracked and a GUID sitting four
        # instructions above the call is reported as unrecoverable. That is not
        # a missing reader, it is a GUID the listing carries.
        #
        # The geometry is `OemGlobalNvsDxe/0000057C.asm`'s: `push RBP` twice
        # then `mov RBP, RSP` leaves RBP at -0x10 with RSP at -0x10, so the
        # GUID at `[RBP - 0x18]` is at -0x28 and the buffer at
        # `[RBP + 0x2e0]` is at 0x2d0. The access is `RBP + 0x2e0 + 0x4F3`.
        words = xrefs.guid_to_dwords(SETUP_GUID)
        guid_lines = []
        for i, word in enumerate(words):
            disp = 0xE8 - 4 * i
            guid_lines.append(
                "%08x c7 85 %02x ff ff ff %02x %02x %02x %02x  mov      "
                "dword ptr [RBP + -0x%x], 0x%x"
                % (0x59B + 8 * i, disp & 0xFF,
                   word & 0xFF, (word >> 8) & 0xFF,
                   (word >> 16) & 0xFF, (word >> 24) & 0xFF,
                   0x18 - 4 * i, word & 0xFFFFFFFF))
        body = (
            "00000100 55 - - - - - - - - -          push     RBP\n"
            "00000101 57 - - - - - - - - -          push     RDI\n"
            "00000102 48 8b ec - - - - - - -        mov      RBP, RSP\n"
            "00000105 48 81 ec 80 00 00 00 - - -    sub      RSP, 0x80\n"
            + "\n".join(guid_lines) + "\n"
            "000005c3 4c 8d 4d c0 - - - - - -       lea      R9, [RBP + -0x40]\n"
            "000005de 48 c7 45 b8 d8 07 00 00 - -   mov      "
            "qword ptr [RBP + -0x48], 0x7d8\n"
            "000005e6 48 8d 45 c8 - - - - - -       lea      RAX, [RBP + -0x38]\n"
            "000005ea 48 89 44 24 20 - - - - -    mov      "
            "qword ptr [RSP + 0x20], RAX\n"
            "00000751 48 8d 55 e8 - - - - - -       lea      RDX, [RBP + -0x18]\n"
            "00000755 48 89 7c 24 20 - - - - - -    mov      "
            "qword ptr [RSP + 0x20], RDI\n"
            "0000075e 48 8b 05 33 0c 00 00 - - -    mov      RAX, "
            "qword ptr [0x00001368]\n"
            "00000787 ff 50 48 - - - - - - - -      call     "
            "qword ptr [RAX + 0x48]\n")
        self.add_module("OemFakeMovRbp", {
            "00000100.asm": listing("OemFakeMovRbp", "mov_rbp_reader", body)})
        out, _code = self.run_tool("--module", "OemFakeMovRbp")
        self.assertIn(SETUP_GUID, out)
        self.assertIn("Setup", out)
        self.assertNotIn("no GUID recoverable at this site", out)

    def test_a_mov_rbp_rsp_frame_gives_the_offset_by_subtraction(self):
        # The same prologue, checked for the arithmetic rather than only for
        # the GUID: base `RBP + 0x2e0` with `RBP` at -0x10 is frame address
        # 0x2d0, so `RBP + 0x7d3` is `Setup[0x4F3]` of it.
        body = (
            "00000100 55 - - - - - - - - -          push     RBP\n"
            "00000101 48 8b ec - - - - - - -        mov      RBP, RSP\n"
            "00000104 48 8d 85 e0 02 00 00 - - - -  lea      RAX, [RBP + 0x2e0]\n"
            "0000010b 48 89 44 24 20 - - - - -    mov      "
            "qword ptr [RSP + 0x20], RAX\n"
            "00000110 4c 8d 8d d0 fd ff ff - - - -  lea      R9, [RBP + -0x30]\n"
            "00000117 48 c7 85 d0 fd ff ff d8 07 00  mov      "
            "qword ptr [RBP + -0x30], 0x7d8\n"
            "00000121 48 8d 95 c0 fd ff ff - - - -  lea      RDX, [RBP + -0x40]\n"
            "00000128 c7 85 c0 fd ff ff 43 d6 87 ec  mov      "
            "dword ptr [RBP + -0x40], 0xec87d643\n"
            "00000132 c7 85 c4 fd ff ff a4 eb b5 4b  mov      "
            "dword ptr [RBP + -0x3c], 0x4bb5eba4\n"
            "0000013c c7 85 c8 fd ff ff a1 e5 3f 3e  mov      "
            "dword ptr [RBP + -0x38], 0x3e3fe5a1\n"
            "00000146 c7 85 cc fd ff ff 36 b2 0d a9  mov      "
            "dword ptr [RBP + -0x34], 0xa90db236\n"
            "00000150 48 8b 05 b0 0f 00 00 - - -    mov      RAX, "
            "qword ptr [0x1000]\n"
            "00000157 ff 50 48 - - - - - - - -      call     "
            "qword ptr [RAX + 0x48]\n"
            "0000015a 80 bd d3 07 00 00 00 00 00 -  cmp      "
            "byte ptr [RBP + 0x7d3], 0x1\n")
        self.add_module("OemFakeMovRbpOff", {
            "00000100.asm": listing("OemFakeMovRbpOff", "mov_rbp_offset", body)})
        out, _code = self.run_tool("--offset", "Setup:0x4F3")
        self.assertIn("OemFakeMovRbpOff/00000100.asm", out)
        self.assertNotIn("no reader found", out)

    def test_a_register_copy_of_the_base_is_followed(self):
        # Plain base subtraction misses `[RBX + off]` entirely, so this is the
        # case that says whether provenance tracking is doing anything.
        #
        # The copy has to come before the table load: `mov RAX, qword ptr
        # [0x1000]` on the way to the call overwrites RAX, and copying after
        # it would copy a value the tool has already lost.
        body = getvar_frame(
            "OemFakeCopy", "copy_reader", UNIWILL_GUID, 0xB4,
            access="0000019b 80 3c 18 01 - - - - - - -    cmp      "
                   "byte ptr [RBX + 0x1], 0x0")
        body = body.replace(
            "00000112 48 89 44 24 20 - - - - -    mov      qword ptr [RSP + 0x20], RAX",
            "00000112 48 89 44 24 20 - - - - -    mov      qword ptr [RSP + 0x20], RAX\n"
            "00000117 48 89 c3 - - - - - - - -      mov      RBX, RAX")
        self.add_module("OemFakeCopy", {"00000100.asm": body})
        out, _code = self.run_tool("--offset", "UniWillVariable:0x1")
        self.assertIn("OemFakeCopy/00000100.asm", out)
        self.assertNotIn("no reader found", out)

    def test_a_store_is_reported_as_a_write_and_a_compare_as_a_read(self):
        # `cmp`'s memory operand sits in the destination position, so treating
        # position as the answer would file the commonest read as a write.
        body = getvar_frame(
            "OemFakeRw", "rw_reader", SETUP_GUID, 0x7D8,
            access="00000199 80 bc 24 33 05 00 00 - - -    cmp      "
                   "byte ptr [RSP + 0x533], 0x1\n"
                   "000001a0 88 9c 24 34 05 00 00 - - -    mov      "
                   "byte ptr [RSP + 0x534], BL")
        self.add_module("OemFakeRw", {"00000100.asm": body})
        out, _code = self.run_tool("--offset", "Setup:0x4F3", "--offset", "Setup:0x4F4")
        read_part, write_part = out.split("Setup[0x4F4]")
        self.assertIn("reads", read_part)
        self.assertIn("writes", write_part)

    def test_a_lea_of_the_base_is_not_an_offset_zero_access(self):
        # `lea RAX, [RSP + 0x40]` names the buffer's first byte but reads no
        # memory; counting it puts a phantom reader at offset 0.
        self.add_module("OemFakeLea", {
            "00000100.asm": getvar_frame("OemFakeLea", "lea_reader",
                                         SETUP_GUID, 0x7D8)})
        out, _code = self.run_tool("--offset", "Setup:0x0")
        self.assertIn("no reader found", out)

    def test_a_call_target_is_not_a_buffer_access(self):
        # `call qword ptr [RAX + 0x48]` names a dispatch slot in the runtime
        # services table, not a byte of the variable.
        self.add_module("OemFakeCall", {
            "00000100.asm": getvar_frame("OemFakeCall", "call_reader",
                                         SETUP_GUID, 0x7D8)})
        out, _code = self.run_tool("--offset", "Setup:0x48")
        self.assertIn("no reader found", out)


# --------------------------------------------------------------------------
# The refusals: what the tool declines rather than guesses
# --------------------------------------------------------------------------

class RefusalTests(TreeCase):
    """The cases a tool that quietly accepts everything would get wrong."""

    def test_no_size_means_no_offset_is_placed(self):
        # Without a bound the whole frame is "inside the buffer", which is how
        # a tool like this claims readers it does not have.
        body = getvar_frame("OemFakeNoSize", "no_size", SETUP_GUID, 0x7D8,
                            access="00000199 80 bc 24 33 05 00 00 - - -    "
                                   "cmp      byte ptr [RSP + 0x533], 0x1")
        body = "\n".join(ln for ln in body.splitlines()
                         if ", 0x7d8" not in ln) + "\n"
        self.add_module("OemFakeNoSize", {"00000100.asm": body})
        out, _code = self.run_tool("--offset", "Setup:0x4F3")
        self.assertIn("no reader found", out)
        self.assertIn("no size argument recovered", out)

    def test_a_site_whose_guid_is_a_static_is_reported_as_skipped(self):
        # `lea RDX, [0x1520]` names a GUID in .data. A code listing does not
        # carry those bytes, so the site is skipped whole and the count says
        # so -- this is what keeps a negative from reading as an absence.
        body = getvar_frame("OemFakeStatic", "static_guid", SETUP_GUID, 0x7D8)
        body = body.replace("lea      RDX, [RSP + -0x20]",
                            "lea      RDX, [0x1520]")
        body = "\n".join(ln for ln in body.splitlines()
                         if "dword ptr [RSP + -0x" not in ln) + "\n"
        self.add_module("OemFakeStatic", {"00000100.asm": body})
        out, _code = self.run_tool("--offset", "Setup:0x4F3")
        self.assertIn("no reader found", out)
        self.assertRegex(out, r"sites skipped.*:\s*[1-9]")

    def test_the_skipped_count_is_not_labelled_with_one_cause(self):
        # The skipped population is not one thing: naming a single cause on
        # the count makes a reader believe the whole of it is that cause. The
        # label must describe the population, and the breakdown must exist.
        self.add_module("OemFakeSkip", {
            "00000100.asm": getvar_frame("OemFakeSkip", "skipped", SETUP_GUID,
                                         0x7D8)})
        out, _code = self.run_tool("--offset", "Setup:0x4F3")
        self.assertIn("sites skipped, GUID not recoverable from this listing",
                      out)
        self.assertNotIn("GUID named by a static", out)

    def test_skip_causes_separates_a_static_from_a_forwarded_pointer(self):
        # These need different things next, so they must not share a bucket:
        # a static's bytes are in the module image, while a frame slot holding
        # a pointer has no GUID in this listing at all.
        static = getvar_frame("OemFakeStat", "static_guid", SETUP_GUID, 0x7D8)
        static = static.replace("lea      RDX, [RSP + -0x20]",
                                "lea      RDX, [0x1520]")
        static = "\n".join(ln for ln in static.splitlines()
                           if "dword ptr [RSP + -0x" not in ln) + "\n"
        # A frame slot that holds a pointer, so there is no GUID to read.
        fwd = getvar_frame("OemFakeFwd", "forwarded", SETUP_GUID, 0x7D8)
        fwd = fwd.replace("lea      RDX, [RSP + -0x20]",
                          "lea      RDX, [RSP + 0x30]")
        fwd = fwd.replace(
            "00000112 48 89 44 24 20 - - - - -    mov      qword ptr [RSP + 0x20], RAX",
            "00000112 48 89 44 24 20 - - - - -    mov      qword ptr [RSP + 0x20], RAX\n"
            "00000117 48 89 44 24 30 - - - - -    mov      qword ptr [RSP + 0x30], RBX")
        fwd = "\n".join(ln for ln in fwd.splitlines()
                        if "dword ptr [RSP + -0x" not in ln) + "\n"
        self.add_module("OemFakeStat", {"00000100.asm": static})
        self.add_module("OemFakeFwd", {"00000100.asm": fwd})
        # Assert on the classification itself rather than on the printed
        # layout: a site that names a static and a site whose RDX is a
        # forwarded pointer must not land in the same bucket.
        _m, _f, stat_sites, _u = xrefs.analyse_listing(
            os.path.join(self.listings, "OemFakeStat", "00000100.asm"))
        _m, _f, fwd_sites, _u = xrefs.analyse_listing(
            os.path.join(self.listings, "OemFakeFwd", "00000100.asm"))
        self.assertEqual([s.skip_cause for s in stat_sites],
                         ["static address in .data"])
        self.assertEqual([s.skip_cause for s in fwd_sites],
                         ["frame slot holding a pointer"])
        out, _code = self.run_tool("--list-skip-causes")
        self.assertIn("static address in .data", out)
        self.assertIn("frame slot holding a pointer", out)

    def test_an_indexed_access_is_counted_rather_than_placed(self):
        body = getvar_frame(
            "OemFakeIndexed", "indexed", SETUP_GUID, 0x7D8,
            access="00000199 41 8a 04 08 - - - - - - -    mov      AL, "
                   "byte ptr [R8 + RCX*0x1]")
        self.add_module("OemFakeIndexed", {"00000100.asm": body})
        out, _code = self.run_tool("--offset", "Setup:0x4F3")
        self.assertIn("no reader found", out)
        self.assertRegex(out, r"accesses this method does not place:\s*[1-9]")

    def test_a_negative_carries_the_counts_that_bound_it(self):
        # The point of the two counts is that they appear on the negative
        # itself, not only on a positive.
        self.add_module("OemFakeEmpty", {
            "00000100.asm": getvar_frame("OemFakeEmpty", "nothing", SETUP_GUID,
                                         0x7D8)})
        out, _code = self.run_tool("--offset", "Setup:0x4F3")
        self.assertIn("no reader found by this method", out)
        self.assertIn("method:", out)
        self.assertIn("sites skipped", out)
        self.assertIn("accesses this method does not place", out)

    def test_an_offset_beyond_the_recovered_size_is_not_placed(self):
        # The size is what bounds the subtraction; without applying it, a
        # frame access far above the buffer would count as an offset.
        body = getvar_frame(
            "OemFakeBig", "past_end", SETUP_GUID, 0x7D8,
            access="00000199 80 bc 24 01 40 00 00 - - -    cmp      "
                   "byte ptr [RSP + 0x4001], 0x1")
        self.add_module("OemFakeBig", {"00000100.asm": body})
        out, _code = self.run_tool("--offset", "Setup:0x3F01")
        self.assertIn("no reader found", out)

    def test_an_unknown_store_name_is_refused_with_the_ones_it_knows(self):
        self.add_module("OemFakeEmpty2", {
            "00000100.asm": getvar_frame("OemFakeEmpty2", "nothing",
                                         SETUP_GUID, 0x7D8)})
        with self.assertRaises(SystemExit) as caught:
            self.run_tool("--offset", "NotAVariable:0x10")
        self.assertIn("NotAVariable", str(caught.exception))
        self.assertIn("Setup", str(caught.exception))

    def test_a_non_hex_offset_is_refused(self):
        self.add_module("OemFakeEmpty3", {
            "00000100.asm": getvar_frame("OemFakeEmpty3", "nothing",
                                         SETUP_GUID, 0x7D8)})
        with self.assertRaises(SystemExit):
            self.run_tool("--offset", "Setup:zzz")

    def test_a_missing_listing_tree_says_so_rather_than_reporting_nothing(self):
        # An empty result from a path that does not exist is indistinguishable
        # from a real negative unless the tool refuses.
        with self.assertRaises(SystemExit) as caught:
            xrefs.main(["--offset", "Setup:0x4F3",
                        "--listings", os.path.join(self.root, "absent"),
                        "--loadmap", os.path.join(self.root, "load-map.csv")])
        self.assertIn("absent", str(caught.exception))


