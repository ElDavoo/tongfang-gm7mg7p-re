class ParseTests(unittest.TestCase):
    """`parse_listing` and the operand regexes, against a real listing's lines."""

    def test_a_byte_column_padded_with_dashes_parses(self):
        # The exporter pads short instructions with `-`, so the byte column
        # cannot be split on whitespace and taken by position.
        module, func, insns = xrefs.parse_listing(
            os.path.join(xrefs.DEFAULT_LISTINGS, "OemOcDxe", "000007A8.asm"))
        self.assertEqual(module, "OemOcDxe")
        self.assertEqual(func, "SyncOcVariables")
        self.assertTrue(insns)
        self.assertEqual(insns[0][0], 0x7A8)

    def test_the_named_marker_is_not_part_of_the_function_name(self):
        module, func, _insns = xrefs.parse_listing(
            os.path.join(xrefs.DEFAULT_LISTINGS, "OemOcDxe", "000005D8.asm"))
        self.assertEqual(module, "OemOcDxe")
        self.assertNotIn("[", func or "")

    def test_an_unnamed_function_still_gets_a_name(self):
        # `FUN_00000260` has no `[named]` marker; the name is still the second
        # field and is what a reader cites.
        _m, func, _i = xrefs.parse_listing(
            os.path.join(xrefs.DEFAULT_LISTINGS, "DxeOverClock", "00000260.asm"))
        self.assertEqual(func, "FUN_00000260")

    def test_a_negative_displacement_keeps_its_sign(self):
        # `[RBP + -0x6d]` is a positive frame address and `[RBP + 0x11]` is not;
        # dropping the sign would move every access in the frame.
        self.assertEqual(xrefs.parse_int("-0x6d"), -0x6D)
        self.assertEqual(xrefs.parse_int("0x6d"), 0x6D)
        m = xrefs.MEM.match("byte ptr [RBP + -0x6d]")
        self.assertIsNotNone(m)
        self.assertEqual(xrefs.parse_int(m.group(4)), -0x6D)

    def test_an_indexed_operand_is_recognised_as_computed(self):
        m = xrefs.MEM.match("byte ptr [R8 + RCX*0x1]")
        self.assertTrue(m.group(5), "the index term was not captured")

    def test_a_fixed_address_is_not_a_frame_reference(self):
        self.assertTrue(xrefs.ABSOLUTE.match("0x000019a0"))
        self.assertFalse(xrefs.ABSOLUTE.match("RBP"))

    def test_a_non_immediate_is_not_a_number(self):
        for tok in ("RAX", "ECX", "gRT", ""):
            self.assertIsNone(xrefs.parse_int(tok), tok)


