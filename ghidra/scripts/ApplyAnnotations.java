// Apply this repository's annotation layer to the current program: function
// names, signatures and comments from the hand-maintained CSV, and XDATA
// labels from the generated one.
//
// This is the editable surface. An agent or a human improves a decompilation
// by adding a row to the CSV and re-running the export -- never by hand-editing
// the Ghidra project or an exported .c. That is what makes the improvement
// reviewable in a diff; a .rep is not.
//
// arg 0: function annotations CSV, header-only, columns:
//          scope,addr,name,signature,type,comment,evidence,basis
//        `scope` is the Ghidra program name, or "common" for a function in
//        the 0x0000-0x7FFF area that is the same in every bank program.
// arg 1: XDATA symbol CSV, header-only, columns:
//          addr,name,from_register,register_status,derivation,programs
//        Generated by ec/tools/gen_xdata_symbols.py from
//        ec/annotations/registers.yaml -- never hand-edited. Pass "" to skip.
// arg 2: report DIRECTORY; the report is written as
//        apply-<program>.tsv inside it, one per program, because a batched
//        analyzeHeadless run executes this script once per program and a
//        single shared filename would leave only the last program's report.
//
// A row that matches no function is REPORTED, never dropped. The driver turns
// a non-zero unmatched count into a failure, because an annotation pointing at
// an address the project has no function for is either a typo or a sign the
// project needs a rebuild -- and quietly ignoring it is how a stale annotation
// outlives the thing it named.
//@category TongFang
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.address.AddressSpace;
import ghidra.program.model.data.ByteDataType;
import ghidra.program.model.listing.CommentType;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.Listing;
import ghidra.program.model.symbol.SourceType;
import ghidra.program.model.symbol.Symbol;
import ghidra.program.model.symbol.SymbolTable;

import java.io.BufferedReader;
import java.io.FileReader;
import java.io.PrintWriter;
import java.util.ArrayList;
import java.util.List;

public class ApplyAnnotations extends GhidraScript {

    @Override
    public void run() throws Exception {
        String[] args = getScriptArgs();
        if (args.length < 3) {
            throw new IllegalArgumentException(
                "usage: ApplyAnnotations.java <functions.csv|-> <xdata.csv|-> <report-dir>");
        }
        String programName = currentProgram.getName();
        int applied = 0;
        int unmatched = 0;
        int labels = 0;
        int labelsSkipped = 0;
        List<String> problems = new ArrayList<>();

        // --- XDATA labels, banks only -------------------------------------
        // The ITE8850-PD program has its own XDATA map (ec/README.md,
        // ec/annotations/lightbar-bat-flow.md §2): a MOV DPTR,#0x07E2 in that
        // program is not a reference to that register, so an EC register name
        // there would be a first-class overclaim. The generator already never
        // emits pd rows; this is the second lock on the same door.
        if (!args[1].isEmpty() && !"-".equals(args[1])) {
            AddressSpace xdata = currentProgram.getAddressFactory().getAddressSpace("EXTMEM");
            if (xdata == null) {
                problems.add("no EXTMEM address space in " + programName
                    + "; XDATA labels not applied (is this really an 8051 program?)");
            } else {
                SymbolTable st = currentProgram.getSymbolTable();
                Listing listing = currentProgram.getListing();
                for (String[] row : readCsv(args[1])) {
                    if (!appliesTo(row[5], programName)) {
                        continue;
                    }
                    int addr = hex(row[0]);
                    String name = row[1];
                    Address a = xdata.getAddress(addr);
                    if (a == null) {
                        labelsSkipped++;
                        problems.add("EXTMEM address out of range: 0x" + Integer.toHexString(addr));
                        continue;
                    }
                    Symbol s = st.getPrimarySymbol(a);
                    if (s != null) {
                        s.setName(name, SourceType.USER_DEFINED);
                    } else {
                        st.createLabel(a, name, SourceType.USER_DEFINED);
                    }
                    // Defining the byte makes the decompiler read the label as a
                    // named object rather than an undefined location. Failure
                    // here is cosmetic (the name still applies), so it is not fatal.
                    try {
                        if (listing.getDataAt(a) == null) {
                            listing.createData(a, ByteDataType.dataType);
                        }
                    } catch (Exception e) {
                        // Left as-is; the label is the part that matters.
                    }
                    labels++;
                }
            }
        }

        // --- function names, signatures, comments --------------------------
        // arg 0 may be "" on a first build, before the annotations file exists
        // yet -- the driver's --check then reports zero annotations applied.
        List<String[]> functionRows = (args[0].isEmpty() || "-".equals(args[0]))
            ? new ArrayList<>()
            : readCsv(args[0]);
        for (String[] row : functionRows) {
            String scope = row[0];
            // The program name Ghidra reports is the imported FILE name
            // ("bank0.bin"), so compare on the stem: an annotation row saying
            // `bank0` should not stop matching because the image is a .bin.
            String stem = stem(programName);
            boolean mine = scope.equals(stem)
                || (scope.equals(programName))
                || ("common".equals(scope) && stem.startsWith("bank"));
            if (!mine) {
                continue;
            }
            int addr = hex(row[1]);
            String name = row[2];
            String signature = row[3];
            String type = row[4];
            String comment = row[5];
            String evidence = row[6];
            String basis = row[7];

            if (evidence.trim().isEmpty()) {
                unmatched++;
                problems.add(String.format(
                    "0x%04X in %s: no evidence citation; an annotation without one is a claim, not a finding",
                    addr, programName));
                continue;
            }
            Address a = toAddr(addr);
            Function f = getFunctionAt(a);
            if (f == null) {
                unmatched++;
                problems.add(String.format("0x%04X in %s: no function at this address", addr, programName));
                continue;
            }
            if (!name.trim().isEmpty()) {
                f.setName(name, SourceType.USER_DEFINED);
            }
            String signatureNote = null;
            if (!signature.trim().isEmpty()) {
                // Recorded, not applied. Ghidra has no Keil C51 calling-convention
                // model, so applying a prototype to 8051 code would put a guess
                // into the function's type system where it reads as a fact --
                // the overclaim CLAUDE.md puts above every other rule. The text
                // still reaches the export, where a human can act on it.
                signatureNote = "signature: " + signature.trim();
            }
            StringBuilder plate = new StringBuilder();
            if (!comment.trim().isEmpty()) {
                plate.append(comment.trim());
            }
            if (!type.trim().isEmpty()) {
                if (plate.length() > 0) {
                    plate.append('\n');
                }
                plate.append("type: ").append(type.trim());
            }
            if (signatureNote != null) {
                plate.append('\n').append(signatureNote);
            }
            plate.append("\nevidence: ").append(evidence.trim());
            plate.append("\nbasis: ").append(basis.trim().isEmpty() ? "unspecified" : basis.trim());
            if ("inferred".equals(basis.trim())) {
                // The repo's own marker (bios/decompiled/OemOcDxe.annotated.c):
                // a reading, not something the bytes state outright.
                plate.append("  <- reading, not a fact read out of the binary");
            }
            // Function declares setComment(String), which sets the plate
            // comment. (The two-argument CodeUnit.setComment(CommentType, ...)
            // is not visible on a Function reference in this Ghidra.)
            f.setComment(plate.toString());
            applied++;
        }

        new java.io.File(args[2]).mkdirs();
        try (PrintWriter pw = new PrintWriter(args[2] + "/apply-" + stem(programName) + ".tsv")) {
            pw.println("# ApplyAnnotations report for " + programName);
            pw.println("program\t" + programName);
            pw.println("annotations_applied\t" + applied);
            pw.println("annotations_unmatched\t" + unmatched);
            pw.println("xdata_labels\t" + labels);
            pw.println("xdata_labels_skipped\t" + labelsSkipped);
            for (String p : problems) {
                pw.println("problem\t" + p.replace('\t', ' '));
            }
        }
        println("ApplyAnnotations " + programName + ": applied " + applied
            + ", unmatched " + unmatched + ", xdata labels " + labels
            + (labelsSkipped > 0 ? " (" + labelsSkipped + " skipped)" : ""));
        if (unmatched > 0) {
            println("  " + unmatched + " annotation(s) did not resolve -- see " + args[2]);
        }
    }

    /** `programs` is `bank0;bank1`; a row applies if this program is named. */
    private static boolean appliesTo(String programs, String programName) {
        String stem = stem(programName);
        for (String p : programs.split(";")) {
            String want = p.trim();
            if (programName.equals(want) || stem.equals(want)) {
                return true;
            }
        }
        return false;
    }

    /** "bank0.bin" -> "bank0". Ghidra names a raw-binary program after the file. */
    private static String stem(String name) {
        int dot = name.lastIndexOf('.');
        return dot > 0 ? name.substring(0, dot) : name;
    }

    private static int hex(String s) {
        return Integer.parseInt(s.trim().replace("0x", ""), 16);
    }

    /**
     * RFC4180-ish field split. Not String.split: a comment field is quoted and
     * routinely contains commas ("0x09C7/0x09C8, tiered by temperature"), and a
     * naive split shifts every later column by one -- which showed up as the
     * type and evidence columns carrying fragments of the comment.
     */
    private static String[] splitCsvLine(String line) {
        List<String> out = new ArrayList<>();
        StringBuilder cur = new StringBuilder();
        boolean quoted = false;
        for (int i = 0; i < line.length(); i++) {
            char c = line.charAt(i);
            if (quoted) {
                if (c == '"') {
                    if (i + 1 < line.length() && line.charAt(i + 1) == '"') {
                        cur.append('"');
                        i++;
                    } else {
                        quoted = false;
                    }
                } else {
                    cur.append(c);
                }
            } else if (c == '"') {
                quoted = true;
            } else if (c == ',') {
                out.add(cur.toString());
                cur.setLength(0);
            } else {
                cur.append(c);
            }
        }
        out.add(cur.toString());
        return out.toArray(new String[0]);
    }

    /** Header-only CSV, no comment lines (ec/README.md:156-159). */
    private static List<String[]> readCsv(String path) throws Exception {
        List<String[]> rows = new ArrayList<>();
        try (BufferedReader r = new BufferedReader(new FileReader(path))) {
            String line = r.readLine();
            if (line == null) {
                throw new IllegalArgumentException("empty CSV: " + path);
            }
            while ((line = r.readLine()) != null) {
                if (line.trim().isEmpty()) {
                    continue;
                }
                String[] f = splitCsvLine(line);
                if (f.length < 2) {
                    throw new IllegalArgumentException("short row in " + path + ": " + line);
                }
                // Tolerate a hand-written file that omits the empty `signature`
                // column rather than failing a build over a blank cell.
                String[] padded = new String[8];
                System.arraycopy(f, 0, padded, 0, Math.min(f.length, 8));
                for (int i = 0; i < 8; i++) {
                    if (padded[i] == null) {
                        padded[i] = "";
                    }
                }
                rows.add(padded);
            }
        }
        return rows;
    }
}
