// Disassembly listing, one file per function, beside the decompiled C.
//
// Why this exists. A decompilation is a *reading* of the machine code: the
// decompiler decides what the bytes mean, and the reader is shown only its
// conclusion. That is the right default for breadth and the wrong default for
// trust, because a wrong reading of the bytes is indistinguishable from a
// right one in the output. The listing is the other half of the same fact --
// the instructions the bytes decode to -- so any claim in a `.c` can be
// checked against the code that produced it, and the annotated layer
// (<component>/annotations/ghidra-functions.csv) can cite instructions rather
// than citing a tool's opinion of them.
//
// It is also the layer the 1:1 check works on: ghidra/README.md's reassembly
// check reads these lines, encodes them with an external assembler, and compares
// the result to the input image. Nothing in the decompiler is trusted twice.
//
// Output format, one `<ADDR>.asm` per function under `<outdir>/<program>/`:
//
//   ; bank0 @ B158  charge_target_update  [named]
//   ; Ghidra 12.1.3 disassembly, generated by <generator> -- do not edit.
//   ; Source: <source>, SHA-256 <sha256>
//   ; <seed basis> ; the instructions below are the ground truth for the .c
//   B158  74 09 -        mov   dptr,#0x09
//   B15C  e0  -  -       movx  a,@dptr
//
// The `;` lines are comments, the rest is `addr  bytes  mnemonic  operands`,
// which is what objdump prints and therefore what a reader already knows how to
// read -- with the byte column always three slots, a missing byte shown as `-`.
// See format() for why the width has to be fixed.
//
// args:
//   0  output directory (created if absent)
//   1  index CSV to append rows to (header written by the driver)
//   2  mode: per-function | per-program
//   3  context file, key=value lines (see ExportDecompile.java)
//   4  seed basis CSV, header-only, columns: program,addr,basis (or "-")
//@category TongFang
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionIterator;
import ghidra.program.model.listing.Instruction;
import ghidra.program.model.mem.MemoryBlock;

import java.io.File;
import java.io.FileWriter;
import java.io.PrintWriter;
import java.util.Map;

public class ExportListing extends GhidraScript {

    @Override
    public void run() throws Exception {
        String[] args = getScriptArgs();
        if (args.length < 5) {
            throw new IllegalArgumentException("usage: ExportListing.java <outdir> <index.csv> "
                + "<per-function|per-program> <context.txt> <seed-basis.csv|->");
        }
        String outDir = args[0];
        String indexPath = args[1];
        String mode = args[2];
        Map<String, String> ctx = TongFang.readContext(args[3]);
        Map<String, String> basis = TongFang.readBasis(args[4]);

        String program = TongFang.labelFor(ctx, currentProgram.getName());
        TongFang.assertDistinctLabels(ctx, program);

        long imageBytes = 0;
        for (MemoryBlock b : currentProgram.getMemory().getBlocks()) {
            imageBytes += b.getSize();
        }
        // Bucket every instruction in the program by the function containing
        // it, in one pass. Function.getInstructions() is not on Function in
        // Ghidra 12 and getBody() is not worth depending on either; walking the
        // listing once is both cheaper and stable across versions.
        // The byte column is padded to the widest instruction in *this*
        // program, not to a fixed 3. The 8051's longest is 3 bytes; x86-64's
        // is 15, and a fixed 3 would silently truncate every 7-byte `mov r64,
        // [rip+disp32]` in a BIOS module -- a listing that looks fine and is
        // wrong about the instruction it claims to show.
        int maxBytes = 1;
        Map<Long, java.util.List<Instruction>> byEntry = new java.util.HashMap<>();
        ghidra.program.model.listing.InstructionIterator all =
            currentProgram.getListing().getInstructions(true);
        while (all.hasNext()) {
            Instruction ins = all.next();
            Function owner = currentProgram.getFunctionManager()
                .getFunctionContaining(ins.getAddress());
            if (owner == null) {
                continue;
            }
            byEntry.computeIfAbsent(owner.getEntryPoint().getOffset(),
                k -> new java.util.ArrayList<>()).add(ins);
            // The instruction's own length, not a prototype's maximum: the
            // column has to be as wide as the widest instruction this program
            // actually contains, and `getMaxBytes()` is on InstructionPrototype,
            // not on Instruction, in Ghidra 12.
            int len = ins.getLength();
            if (len > maxBytes) {
                maxBytes = len;
            }
        }
        if (maxBytes > 15) {
            maxBytes = 15;
        }
        byteSlots = maxBytes;
        println("ExportListing " + program + ": byte column padded to "
                + maxBytes + " slot(s), the widest instruction in this program");

        TongFang.mkdirs(new File(outDir));
        PrintWriter index = new PrintWriter(new FileWriter(indexPath, true));
        PrintWriter whole = "per-program".equals(mode)
            ? new PrintWriter(new FileWriter(new File(outDir, program + ".asm")))
            : null;
        if (whole != null) {
            writeHeader(whole, program, ctx, "asm");
        }

        FunctionIterator it = currentProgram.getFunctionManager().getFunctions(true);
        int n = 0, insns = 0;
        long insnBytes = 0;
        while (it.hasNext()) {
            Function f = it.next();
            n++;
            Address entry = f.getEntryPoint();
            String addrHex = TongFang.addrKey(entry.toString());
            String name = f.getName();
            String seedBasis = basis.get(addrHex);
            if (seedBasis == null) {
                seedBasis = "auto";
            }
            String annotated = TongFang.isPlaceholderName(name) ? "no" : "yes";

            Instruction[] body = null;
            java.util.List<Instruction> owned = byEntry.get(entry.getOffset());
            if (owned != null && !owned.isEmpty()) {
                body = owned.toArray(new Instruction[0]);
            }
            int count = body == null ? 0 : body.length;
            int bytes = 0;
            if (body != null) {
                for (Instruction ins : body) {
                    bytes += ins.getLength();
                }
            }
            insns += count;
            insnBytes += bytes;

            String outFile = "";
            if (count == 0) {
                // A function with no instructions is a symbol with no code
                // behind it -- an external or a mis-seeded entry. Recording
                // that is the useful outcome; writing an empty listing would
                // read as "zero instructions decoded", which is a claim about
                // bytes this program may not even contain.
                outFile = "(no-instructions)";
            } else {
                if (whole != null) {
                    // per-program: one listing for the whole program, so every
                    // row in this program names the same file. A per-function
                    // path here would point at a file that was never written.
                    outFile = program + ".asm";
                    whole.println("; ==== " + name + " @ " + addrHex);
                    for (Instruction ins : body) {
                        whole.println(format(ins));
                    }
                    whole.println();
                } else {
                    outFile = program + "/" + addrHex + ".asm";
                    writeFunctionFile(new File(outDir, program + "/" + addrHex + ".asm"),
                        program, name, addrHex, seedBasis, ctx, body);
                }
            }
            index.println(String.join("\t", program, addrHex, name,
                Integer.toString(bytes), seedBasis, annotated, "", "", "", outFile));
        }
        if (whole != null) {
            whole.close();
        }
        index.close();

        long gap = imageBytes - insnBytes;
        println("ExportListing " + program + " [" + mode + "]: functions=" + n
            + " instructions=" + insns
            + " instruction_bytes=" + insnBytes
            + " image_bytes=" + imageBytes
            + " unclaimed_bytes=" + gap);
        try (PrintWriter m = new PrintWriter(new FileWriter(indexPath + "." + program + ".listing-counts", true))) {
            m.println(program + "\t" + n + "\t" + insns + "\t" + insnBytes
                + "\t" + imageBytes + "\t" + gap);
        }
    }

    /**
     * `addr  bytes  mnemonic  operands`, objdump's shape, with one difference
     * that turns out to be necessary: the byte column is always three slots and
     * a missing byte is a `-`, so the mnemonic always begins at a known place.
     *
     * The width is the widest instruction in the program, not a constant: 3 on
     * the 8051, 15 on x86-64, and a fixed 3 would truncate every 7-byte
     * `mov r64, [rip+disp32]` in a BIOS module.
     *
     * The 8051 has a reserved one-byte instruction the SLEIGH spells `da A`,
     * and `da` is two hex digits. Rendered with a variable-width byte column --
     * which is what objdump does and what this did -- the line
     *
     *     D438  d4  da  A
     *
     * is ambiguous: it reads equally as the one-byte instruction `d4` with
     * mnemonic `da` (what it is) and as the two-byte instruction `d4 da` with
     * mnemonic `A` (what it is not). The image settles it -- the byte after
     * `d4` is `84` -- and the re-encode check found the ambiguity by reporting
     * five instructions whose bytes were not in the firmware. Fixed slots make
     * it impossible rather than merely detectable.
     */
    private int byteSlots = 3;

    private String format(Instruction ins) throws ghidra.program.model.mem.MemoryAccessException {
        StringBuilder hex = new StringBuilder();
        byte[] bytes = ins.getBytes();
        int n = bytes == null ? 0 : Math.min(bytes.length, byteSlots);
        for (int i = 0; i < byteSlots; i++) {
            if (i > 0) {
                hex.append(' ');
            }
            hex.append(i < n ? String.format("%02x", bytes[i] & 0xff) : "-");
        }
        StringBuilder ops = new StringBuilder();
        for (int i = 0; i < ins.getNumOperands(); i++) {
            if (i > 0) {
                ops.append(", ");
            }
            ops.append(ins.getDefaultOperandRepresentation(i));
        }
        String mnem = ins.getMnemonicString().toLowerCase();
        return String.format("%-8s %-" + (byteSlots * 3 - 1) + "s %-8s %s",
            TongFang.addrKey(ins.getAddress().toString()), hex.toString(),
            mnem, ops.toString());
    }

    private void writeHeader(PrintWriter w, String program, Map<String, String> ctx, String ext) {
        w.println("; " + program + ": Ghidra " + TongFang.get(ctx, "ghidra_version", "unknown")
            + " disassembly");
        w.println("; Generated by " + TongFang.get(ctx, "generator", "unknown")
            + " -- do not edit. This is the machine code the decompiled C reads from.");
        w.println("; Source: " + TongFang.sourceFor(ctx, program)
            + ", SHA-256 " + TongFang.get(ctx, "sha256", "unknown"));
        w.println();
    }

    private void writeFunctionFile(File f, String program, String name, String addrHex,
        String seedBasis, Map<String, String> ctx, Instruction[] body) throws Exception {
        TongFang.mkdirs(f.getParentFile());
        try (PrintWriter w = new PrintWriter(new FileWriter(f))) {
            w.println("; " + program + " @ " + addrHex + "   " + name
                + (TongFang.isPlaceholderName(name) ? "" : "   [named]"));
            w.println("; Ghidra " + TongFang.get(ctx, "ghidra_version", "unknown")
                + " disassembly, generated by " + TongFang.get(ctx, "generator", "unknown")
                + " -- do not edit.");
            w.println("; Source: " + TongFang.sourceFor(ctx, program)
                + ", SHA-256 " + TongFang.get(ctx, "sha256", "unknown"));
            w.println("; This is the machine code. The decompiled C for this address is "
                + addrHex + ".c in the same tree;");
            w.println("; where the two disagree, this file is right and the C is a reading of it.");
            if ("call-target".equals(seedBasis)) {
                w.println("; function boundary from a call-target byte scan; that census is an "
                    + "upper bound (ec/annotations/bank-call-audit.md §1),");
                w.println("; so this boundary is a hypothesis and the instructions below may not "
                    + "be the whole function.");
            }
            w.println();
            for (Instruction ins : body) {
                w.println(format(ins));
            }
        }
    }
}
